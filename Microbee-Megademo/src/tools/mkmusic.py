def bass_line(root, style):
    """16 tokens for a bar on chord root (e.g. 'A2')"""
    r = midi(root)
    up = r + 12
    fifth = r + 7

    def n(m):
        name = ['C', 'C#', 'D', 'D#', 'E', 'F', 'F#', 'G', 'G#', 'A', 'A#', 'B'][m % 12]
        return '%s%d' % (name, m // 12 - 1)
    if style == 'eighths':
        s = [n(r), '.'] * 8
    elif style == 'octave':
        s = [n(r), '.', n(up), '.'] * 4
    elif style == 'drive':
        s = [n(r), n(r), n(up), n(r)] * 4
    elif style == 'walk':
        s = [n(r), '.', '.', n(r), '.', '.', n(fifth), '.', n(up), '.', '.', n(fifth), '.', n(r), '.', '.']
    elif style == 'slow':
        s = [n(r)] + ['.'] * 7 + [n(fifth)] + ['.'] * 7
    elif style == 'pulse':
        s = [n(r), '.', '.', '.'] * 4
    elif style == 'none':
        s = ['.'] * 16
    else:
        raise ValueError(style)
    return ' '.join(s)


DRUMS = {
    'none': '................',
    'kick4': 'K...K...K...K...',
    'basic': 'K.H.S.H.K.K.S.H.',
    'drive': 'K.H.S.H.K.HKS.HH',
    'fill': 'K.S.S.SSKSSSSSSS',
    'half': 'K.......S.......',
    'hats': 'H.H.H.H.H.H.H.H.',
    'four': 'X.H.S.H.X.H.S.H.',
    'break': 'K..K..S...K.S...',
    'ticks': '..H...H...H...H.',
}


def chord_bars(song, prefix, chords, lead_bars, li, bi, bstyle, drum, fill_last=False):
    """one pattern per chord; lead_bars = list of 16-token strings (or None)"""
    names = []
    for i, ch in enumerate(chords):
        d = DRUMS['fill'] if (fill_last and i == len(chords) - 1) else DRUMS[drum]
        lead = lead_bars[i] if lead_bars and lead_bars[i] else ' '.join(['.'] * 16)
        nm = '%s%d' % (prefix, i)
        song.pat(nm, lead, bass_line(ch, bstyle), d, li, bi)
        names.append(nm)
    return names


def arp_bar(notes):
    """a chord held with the arpeggio instrument: the root once at the start"""
    return ' '.join([notes] + ['.'] * 15)


