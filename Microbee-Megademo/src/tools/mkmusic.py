"""MICROBEE MEGADEMO soundtrack -> src/notes.inc, src/song.inc

Two voices (lead: 25% pulse, bass: square) played by the raster kernel at
15625 Hz; drums borrow them. One pattern = 16 rows = one bar of 16ths.
Row bytes: lead, bass, drum (see src/music.asm).

Parts are synced to the music: 'mark NAME' in the order list defines
ORD_NAME = the order position at which the part named NAME begins (the
part before it runs until that pattern starts).
"""
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
RATE = 3375000 / 216          # samples a second, per voice

NOTES = {'C': 0, 'D': 2, 'E': 4, 'F': 5, 'G': 7, 'A': 9, 'B': 11}
LI = dict(blip=0, pluck=1, hold=2, arpma=3, arpmi=4, echo=5)
BI = dict(gate=0, oct=1, hold=2)
DR = {'.': 0, 'K': 1, 'S': 2, 'H': 3, 'X': 4}


def midi(tok):
    """'C#4' -> 61 (C4 = 60)"""
    n = NOTES[tok[0]]
    i = 1
    while i < len(tok) and tok[i] in '#b':
        n += 1 if tok[i] == '#' else -1
        i += 1
    return n + 12 * (int(tok[i:]) + 1)


def note_table():
    inc = []
    for n in range(128):
        f = 440.0 * 2 ** ((n - 69) / 12)
        v = int(round(f * 65536 / RATE))
        inc.append(v if 2 <= n and v < 65536 else 0)
    return inc


def tok(t):
    if t == '.':
        return 0
    if t == '^':
        return 1
    return midi(t)


class Song:
    def __init__(self):
        self.pats = []          # (name, bytes)
        self.index = {}
        self.order = []         # ints or ('speed', n) or ('mark', name) or ('loop',)

    def pat(self, name, lead, bass, drum, li='blip', bi='gate'):
        L = lead.split()
        B = bass.split()
        D = list(drum.replace(' ', ''))
        assert len(L) == 16 and len(B) == 16 and len(D) == 16, (name, len(L), len(B), len(D))
        data = bytearray([LI[li], BI[bi]])
        for l, b, d in zip(L, B, D):
            data += bytes([tok(l), tok(b), DR[d]])
        if name in self.index:
            raise ValueError('pattern %s twice' % name)
        self.index[name] = len(self.pats)
        self.pats.append((name, bytes(data)))
        return name

    def play(self, *names):
        for n in names:
            self.order.append(self.index[n])

    def speed(self, n):
        self.order.append(('speed', n))

    def mark(self, name):
        self.order.append(('mark', name))

    def loop(self):
        self.order.append(('loop',))

    def asm(self):
        out = ['; generated by tools/mkmusic.py']
        npos = 0
        olines = []
        marks = {}
        frames = 0
        speed = 6
        for o in self.order:
            if isinstance(o, int):
                olines.append('\tdb %d' % o)
                npos += 1
                frames += 16 * speed
            elif o[0] == 'speed':
                olines.append('\tdb $FE,%d' % o[1])
                speed = o[1]
            elif o[0] == 'mark':
                marks[o[1]] = npos + 1
                out.append('; %s at %d:%05.2f' % (o[1], frames // 3000, frames % 3000 / 50))
            elif o[0] == 'loop':
                olines.append('\tdb $FD')
        olines.append('\tdb $FF')
        for k, v in marks.items():
            out.append('ORD_%s\tequ %d' % (k, v))
        out.append('; total %d patterns, %d:%05.2f' % (npos, frames // 3000, frames % 3000 / 50))
        out.append('song:')
        out += olines
        out.append('song_pats:')
        for i, (name, _) in enumerate(self.pats):
            out.append('\tdw pat_%s' % name)
        for name, data in self.pats:
            out.append('pat_%s:' % name)
            for i in range(0, len(data), 16):
                out.append('\tdb ' + ','.join(str(b) for b in data[i:i + 16]))
        return '\n'.join(out) + '\n', npos, frames


