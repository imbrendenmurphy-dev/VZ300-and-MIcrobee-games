"""SKYLARKIN' music (original, VIBED BY BPM 2026) for the two-voice
pin-pulse beeper engine (frame_wait loop: 127 T at 3.375 MHz). One step of
a song is one 25 Hz frame. Every note's last frame is silent, so notes stay
separate and gritty. Writes src/music.inc."""
import os

HERE = os.path.dirname(os.path.abspath(__file__))
LOOPRATE = 3375000.0 / 127
NAMES = {'C': 0, 'C#': 1, 'D': 2, 'D#': 3, 'E': 4, 'F': 5, 'F#': 6, 'G': 7, 'G#': 8, 'A': 9, 'A#': 10, 'B': 11}


def nidx(tok):
    return (int(tok[-1]) - 2) * 12 + NAMES[tok[:-1]] + 1


def build(out):
    L = ['; generated by tools/music.py', 'notetab:']
    steps = [0]
    for i in range(1, 73):
        f = 65.406 * 2 ** ((i - 1) / 12.0)
        steps.append(int(round(f * 65536 / LOOPRATE)))
    L.append('    dw ' + ','.join(str(s) for s in steps))

    def db(bs):
        bs = list(bs)
        for i in range(0, len(bs), 16):
            L.append('    db ' + ','.join('$%02X' % b for b in bs[i:i + 16]))

    def song(name, step, *chans, loop=False):
        for ci, txt in enumerate(chans):
            ev = []
            for t in txt.split():
                if t == '-':
                    ev[-1][1] += step
                elif t == 'r':
                    ev.append([0, step])
                else:
                    ev.append([nidx(t), step])
            o = []
            for n, d in ev:
                while d > 255:
                    o += [n, 255]
                    d -= 255
                o += [n, d]
            o.append(0xFE if loop else 0xFF)
            L.append('mus_%s_%d:' % (name, ci))
            db(o)

    # title: "Skylarkin'" - a cheeky swing in F with a rising hook
    title = """
F4 r A4 C5 F5 - E5 D5  C5 - A4 r C5 - r r
D5 r F5 D5 C5 - A4 F4  G4 - - r r r r r
F4 r A4 C5 F5 - E5 D5  C5 - A4 r F5 - G5 -
A5 - G5 F5 E5 - C5 E5  F5 - - r F4 - r r
"""
    tbass = """
F2 r C3 r F2 r C3 r  F2 r C3 r A2 r C3 r
A#2 r F3 r A#2 r F3 r  C3 r G2 r C3 r E3 r
F2 r C3 r F2 r C3 r  D3 r A2 r D3 r C3 r
A#2 r C3 r C3 r E3 r  F2 r C3 r F2 - r r
"""
    song('title', 4, title, tbass, loop=True)
    # OPEN PLAN: lift muzak, a polite bossa (sparse so the game keeps its time)
    ingame = """
E5 r r C5 r r D5 r  r r E5 r r r r r
D5 r r B4 r r C5 r  r r A4 r r r r r
E5 r r C5 r r G5 r  r r F5 r E5 r D5 r
C5 r r r r r r r  r r r r r r r r
"""
    ingb = """
C3 r r G2 r r C3 r  C3 r r G2 r r C3 r
G2 r r D3 r r G2 r  A2 r r E3 r r A2 r
F2 r r C3 r r F2 r  G2 r r D3 r r G2 r
C3 r r G2 r r C3 r  C3 r G2 r C3 r r r
"""
    song('game', 5, ingame, ingb, loop=True)
    # boss: the copier means business
    boss = """
A4 r A4 C5 r A4 G4 r  A4 r r r E5 r D5 r
A4 r A4 C5 r A4 G4 r  F4 r E4 r r r r r
"""
    bossb = """
A2 r A2 r A2 r G2 r  A2 r A2 r A2 r C3 r
A2 r A2 r A2 r G2 r  F2 r E2 r E2 r E2 r
"""
    song('boss', 3, boss, bossb, loop=True)
    song('ready', 4, 'C5 E5 G5 C6 - - - r', 'C3 r C4 r C3 C4 C3 r')
    song('clear', 4, 'C5 E5 G5 C6 - E6 - G6 - - - r C6 - - - r',
         'C3 C3 C2 C3 C2 C3 C2 C3 G2 G3 G2 G3 C3 - - r')
    song('over', 8, 'G4 - F#4 - F4 - E4 - - - D4 - - - r', 'G2 - - - F2 - - - E2 - - - D2 - - r')
    open(out, 'w').write('\n'.join(L) + '\n')


if __name__ == '__main__':
    build(os.path.join(HERE, '..', 'src', 'music.inc'))
