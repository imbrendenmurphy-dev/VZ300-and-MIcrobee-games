def explosion(k):
    """16 x 12 cartoon puff: a bang, a cloud, a smaller cloud, sparks"""
    w, h = 16, 12
    a = np.zeros((h, w), bool)
    cx, cy = 7.5, 5.5
    for y in range(h):
        for x in range(w):
            dx, dy = (x - cx), (y - cy) * 1.25
            r = math.hypot(dx, dy)
            ang = math.atan2(dy, dx)
            if k == 0:
                spike = 3.5 + 2.5 * (0.5 + 0.5 * math.cos(ang * 6))
                a[y, x] = r < spike
            elif k == 1:
                bump = 6.0 + 1.2 * math.cos(ang * 5)
                a[y, x] = r < bump and not (r < bump - 2.2 and ((x + y) % 3 == 0))
            elif k == 2:
                bump = 5.0 + 1.0 * math.cos(ang * 4 + 1)
                a[y, x] = (bump - 2 < r < bump) or (r < 2)
            else:
                a[y, x] = (abs(r - 6) < 0.7) and ((int(ang * 4 / math.pi) & 1) == 0)
    return a


def shield_ring(phase):
    """22 x 16 box: a dotted arc in front of the pilot (a force field; only
    the front is drawn, which keeps it to a few cells)"""
    w, h = 22, 16
    a = np.zeros((h, w), bool)
    for i in range(36):
        if (i + phase) % 3 == 0:
            continue
        t = i * 2 * math.pi / 36
        if math.cos(t) < 0.3:
            continue
        x = int(round(10.5 + 10.5 * math.cos(t)))
        y = int(round(7.5 + 7.5 * math.sin(t)))
        a[y, x] = True
    return a


def ring(r):
    """the Spin Cycle ring: an ellipse of radius r (squashed for the 4:3 screen)"""
    w = 2 * r + 2
    h = int(round(2 * r / 1.2)) + 2
    a = np.zeros((h, w), bool)
    for i in range(64):
        t = i * 2 * math.pi / 64
        x = int(round(w / 2 - 0.5 + r * math.cos(t)))
        y = int(round(h / 2 - 0.5 + (r / 1.2) * math.sin(t)))
        a[y, x] = True
    return a


