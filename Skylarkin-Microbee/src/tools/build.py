def wfile(name, data):
    open(os.path.join(BUILD, name), 'wb').write(bytes(data))


def winc(name, lines):
    open(os.path.join(SRC, name), 'w').write('; generated by tools/build.py\n' + '\n'.join(lines) + '\n')


def blk_port(b):
    """port 50h value for block b in the lower window (ROMs off, video at F000)"""
    return ((b & 0x1C) << 3) | ((b & 3) ^ 2) | 4


class BlockPacker:
    """places byte items into a run of 32K blocks"""

    def __init__(self, blocks, start=0):
        self.blocks = list(blocks)
        self.data = {b: bytearray() for b in blocks}
        self.cur = 0
        if start:
            self.data[self.blocks[0]] += bytes(start)

    def put(self, item, align=1):
        item = bytes(item)
        while True:
            b = self.blocks[self.cur]
            d = self.data[b]
            pad = (-len(d)) % align
            if len(d) + pad + len(item) <= 32768:
                d += bytes(pad)
                a = len(d)
                d += item
                return b, a
            self.cur += 1
            assert self.cur < len(self.blocks), 'out of blocks'

    def used(self):
        return [b for b in self.blocks if len(self.data[b])]


# ---------------------------------------------------------------- common glyphs
def common_store():
    st = G.Store()
    for ch in range(32, 96):
        st.put(ch, G.font_glyph(chr(ch)))
    icons = {}
    for i, n in enumerate(AC.ICON_ORDER):
        g = 1 + i
        st.put(g, AC.ICONS[n])
        icons[n] = g
    kinds = {}
    for n in AC.KIND_ORDER:
        kinds[n] = G.kind_pieces(st, G.grid(AC.KINDS[n]), n in AC.KIND_EVEN)
    return st, icons, kinds


def gk_blob(kinds, base):
    """gk_tab (dw per kind) -> 32 x dw -> piece lists, at address base"""
    order = AC.KIND_ORDER
    head = bytearray(2 * len(order))
    tabs = bytearray()
    lists = bytearray()
    t0 = base + len(head)
    l0 = t0 + 64 * len(order)
    for k, n in enumerate(order):
        head[2 * k:2 * k + 2] = (t0 + 64 * k).to_bytes(2, 'little')
        for ps in kinds[n]:
            tabs += (l0 + len(lists)).to_bytes(2, 'little')
            lists.append(len(ps))
            for dc, dr, g in ps:
                lists += bytes([dc, dr]) + g.to_bytes(2, 'little')
    return bytes(head + tabs + lists)


# ---------------------------------------------------------------- common sprites
def common_sprites():
    """-> list of (name, bits, mask)"""
    S = []

    def add(n, bits, mask=None):
        bits = np.asarray(bits, bool)
        S.append((n, bits, G.outline(bits)[1:-1, 1:-1] if mask is None else mask))

    for p in ['BAZZA', 'SHEILA', 'WALLY', 'QUEENIE', 'LOCKIE']:
        for f, rows in enumerate(AC.PILOTS[p]):
            craft = G.grid(rows, '#*')
            rider = G.grid(rows, 'o')
            both = craft | rider
            m = G.outline(both)[1:-1, 1:-1]
            S.append(('%s_A%d' % (p, f), craft, m))
            S.append(('%s_B%d' % (p, f), rider, rider))
        o = G.grid(AC.OPTIONS[p], '#o')
        add('OPT_%s' % p, o)
    for i, b in enumerate(AC.BELL):
        add('BELL%d' % i, G.grid(b))
    for i, b in enumerate(AC.CAPSULE):
        add('CAPS%d' % i, G.grid(b))
    for k in range(4):
        add('BOOM%d' % k, AC.explosion(k))
    for k in range(3):
        add('SHIELD%d' % k, AC.shield_ring(k), AC.shield_ring(k))
    for k, r in enumerate([4, 7, 10, 13]):
        add('RING%d' % k, AC.ring(r), AC.ring(r))
    for k, b in enumerate(AC.BOOMERANG):
        add('BOOMER%d' % k, G.grid(b))
    return S


def pack_sprites(S, base, block, first_id):
    data = bytearray()
    tab = []
    L = []
    for i, (n, b, m) in enumerate(S):
        fb = G.sprite_frame(b, m)
        tab.append((base + len(data), block))
        data += fb
        L.append('SF_%s equ %d' % (n, first_id + i))
    assert base + len(data) <= 0x8000, 'sprite block full: %d' % (base + len(data))
    return bytes(data), tab, L


# ---------------------------------------------------------------- stages
def strip_cells(store, img, sky_row, rows, mw):
    """-> per strip row: 4 phases x mw cells of (glyph, colour)"""
    out = []
    a = img.a
    for r in rows:
        ph = []
        for p in range(4):
            cells = []
            for m in range(mw):
                x = m * 8 + 2 * p
                win = a[r * 8:r * 8 + 8, x:x + 8]
                if win.shape[1] < 8:
                    win = np.pad(win, ((0, 0), (0, 8 - win.shape[1])))
                pat, ink, paper = G.cell_colours(win, sky_row[r])
                if not any(pat):
                    g = 0
                else:
                    g = store.stage(pat, G.mono_of(pat, ink, paper))
                cells.append((g, (paper << 4) | ink))
            ph.append(cells)
        out.append(ph)
    return out


def boss_blob(frames, pal, base):
    """header: db NC, NRC (8-px grid rows), H, nvar; per variant per shift: dw bmp, dw colmap;
    bitmaps column-major with 8 blank lines above and below"""
    H, W = frames[0].shape
    NC = W // 8 + 1
    NRC = (H + 7) // 8
    head = bytearray([NC, NRC, H, len(frames)])
    ptrs = bytearray()
    body = bytearray()
    off0 = base + 4 + 4 * 4 * len(frames)
    for f in frames:
        for s in range(4):
            can = np.zeros((H + 16, NC * 8), np.uint8)
            can[8:8 + H, 2 * s:2 * s + W] = f
            bits = can > 0
            bmp = bytearray()
            for c in range(NC):
                for y in range(H + 16):
                    v = 0
                    for x in range(8):
                        if bits[y, c * 8 + x]:
                            v |= 128 >> x
                    bmp.append(v)
            cm = bytearray()
            for c in range(NC):
                for r in range(NRC):
                    blk = can[8 + r * 8:8 + r * 8 + 8, c * 8:c * 8 + 8]
                    vals, cnt = np.unique(blk[blk > 0], return_counts=True)
                    cm.append(int(vals[np.argmax(cnt)]) if len(vals) else 0)
            ptrs += (off0 + len(body)).to_bytes(2, 'little')
            body += bmp
            ptrs += (off0 + len(body)).to_bytes(2, 'little')
            body += cm
    return bytes(head + ptrs + body)


def build_stage(num, mod, common, blocks):
    """-> (A block bytes, {block: bytes}, include lines)"""
    st = common.copy()
    sky = mod.sky_rows()
    near, far = mod.build_scenery()
    MW = mod.MW
    rows = [(r, 0) for r in mod.NEAR_ROWS] + [(r, 1) for r in mod.FAR_ROWS]
    rows.sort()
    cells = {}
    nc = strip_cells(st, near, sky, [r for r, f in rows if f == 0], MW)
    fc = strip_cells(st, far, sky, [r for r, f in rows if f == 1], MW)
    ni = fi = 0
    for r, f in rows:
        if f == 0:
            cells[r] = nc[ni]
            ni += 1
        else:
            cells[r] = fc[fi]
            fi += 1
    NR = len(rows)
    RL = MW
    nglyph = st.next_stage - G.G_STAGE0
    print('stage %d: %d strip rows, %d scenery glyphs (room for %d), fast glyphs %d'
          % (num, NR, nglyph, G.G_FAST_TOP - G.G_STAGE0 - (G.G_FAST_TOP - st.next_fast), G.G_FAST_TOP - st.next_fast))
    # runs [k][i][p] into the strip blocks
    per = 32768 // RL
    runs = {}
    strip_tab = bytearray()
    sblob = {b: bytearray() for b in BLK_STRIP}
    j = 0
    for k in range(3):
        for i, (r, f) in enumerate(rows):
            for p in range(4):
                data = bytearray()
                for g, col in cells[r][p]:
                    data.append(0x80 | (g & 127) if k == 0 else (g >> 7 if k == 1 else col))
                b = BLK_STRIP[j // per]
                a = len(sblob[b])
                sblob[b] += data
                strip_tab += bytes([blk_port(b)]) + a.to_bytes(2, 'little')
                j += 1
    assert j <= per * len(BLK_STRIP), 'strip data too big'
    row_info = bytearray()
    for r, f in rows:
        row_info += ((r + 1) * 40).to_bytes(2, 'little') + bytes([f])
    # the A block: colour store + stage sprites
    sprites = []
    for n in mod.SPRITE_ORDER:
        b = G.grid(mod.SPRITES[n])
        sprites.append((n, b, G.outline(b)[1:-1, 1:-1]))
    sdata, stab, sinc = pack_sprites(sprites, SPR_DATA, blocks[0], N_COMMON)
    assert len(sprites) <= 64
    A = bytearray(st.blob(False))
    A += bytes(SPR_DATA - len(A))
    A += sdata
    # the B blocks
    P = BlockPacker(blocks[1:], start=64)
    hdr = bytearray(64)
    hdr[0] = NR
    hdr[1:3] = (MW - 40).to_bytes(2, 'little')
    hdr[3:5] = RL.to_bytes(2, 'little')
    b_, a_ = P.put(strip_tab)
    assert b_ == blocks[1]
    hdr[5:7] = a_.to_bytes(2, 'little')
    b_, a_ = P.put(row_info)
    hdr[7:9] = a_.to_bytes(2, 'little')
    base = bytearray()
    for r in range(23):
        if r in cells:
            base += bytes([(sky[r] << 4) | sky[r]] * 40)
        else:
            base += bytes([(sky[r] << 4) | sky[r]] * 40)
    b_, a_ = P.put(base)
    assert b_ == blocks[1]
    hdr[26:28] = a_.to_bytes(2, 'little')
    ceil, floor = mod.heights(near)
    b_, a_ = P.put(bytes(ceil))
    assert b_ == blocks[1]
    hdr[31:33] = a_.to_bytes(2, 'little')
    b_, a_ = P.put(bytes(floor))
    assert b_ == blocks[1]
    hdr[33:35] = a_.to_bytes(2, 'little')
    wv = bytearray()
    for w in mod.waves():
        col, t, y = w[0], w[1], w[2]
        wv += col.to_bytes(2, 'little') + bytes([mod.WAVE_TYPES.index(t), y])
    wv += bytes([0xFF, 0xFF, 0, 0])
    b_, a_ = P.put(wv)
    assert b_ == blocks[1]
    hdr[35:37] = a_.to_bytes(2, 'little')
    st_tab = bytearray()
    for a, b in stab:
        st_tab += a.to_bytes(2, 'little') + bytes([b])
    st_tab += bytes(64 * 3 - len(st_tab))
    b_, a_ = P.put(st_tab)
    assert b_ == blocks[1]
    hdr[40:42] = a_.to_bytes(2, 'little')
    ups = [b for b in BLK_STRIP if len(sblob[b])]
    hdr[9] = len(ups)
    tot_raw = tot_pk = 0
    for n, b in enumerate(ups):
        pk = lz.pack(sblob[b])
        assert lz.unpack(pk) == bytes(sblob[b])
        tot_raw += len(sblob[b])
        tot_pk += len(pk)
        sb, sa = P.put(pk)
        hdr[10 + 4 * n:14 + 4 * n] = bytes([sb]) + sa.to_bytes(2, 'little') + bytes([b])
    print('  strips %d bytes packed to %d' % (tot_raw, tot_pk))
    mb, ma = P.put(st.blob(True)[:0x3000])
    hdr[28] = mb
    hdr[29:31] = ma.to_bytes(2, 'little')
    # the boss (its addresses depend on where it lands: place a dummy first)
    frames = mod.boss_frames()
    probe = boss_blob(frames, mod.BOSS_PAL, 0)
    bb, ba = P.put(bytes(len(probe)))
    blob = boss_blob(frames, mod.BOSS_PAL, ba)
    P.data[bb][ba:ba + len(blob)] = blob
    hdr[37] = bb
    hdr[38:40] = ba.to_bytes(2, 'little')
    hdr[42:58] = bytes(mod.BOSS_PAL)
    ob, oa = P.put(bytes(OVL_MAX))
    hdr[58] = ob
    hdr[59:61] = oa.to_bytes(2, 'little')
    hdr[61:63] = OVL_MAX.to_bytes(2, 'little')
    OVL_SLOTS[num] = (ob, oa)
    P.data[blocks[1]][0:64] = hdr
    used = P.used()
    print('  blocks: A %d (%d bytes), B %s' % (blocks[0], len(A), ', '.join('%d (%d)' % (b, len(P.data[b])) for b in used)))
    inc = ['; stage %d' % num] + sinc
    inc.append('S%d_BW equ %d' % (num, frames[0].shape[1]))
    inc.append('S%d_BH equ %d' % (num, frames[0].shape[0]))
    out = {blocks[0]: bytes(A)}
    for b in used:
        out[b] = bytes(P.data[b])
    return out, inc, st


# ---------------------------------------------------------------- program, loader, disk
def assemble():
    zasm = os.path.join(HERE, 'zasm.py')
    subprocess.check_call([sys.executable, zasm, 'main.asm', '--sym=../build/main.sym'], cwd=SRC)
    subprocess.check_call([sys.executable, zasm, 'loader.asm', '--sym=../build/loader.sym'], cwd=SRC)


def disk(bank_files):
    import build_disk as BD
    from pathlib import Path
    B = Path(BUILD)
    sysdisk = (Path(ROOT) / 'resources' / 'boot_tracks.bin').read_bytes()
    files = {'SAVE.DAT': b'\x1a' * 4096}
    files['SKYLARK.COM'] = (B / 'SKYLARK.COM').read_bytes()
    files['SKY.BIN'] = (B / 'SKY.BIN').read_bytes()
    for n in bank_files:
        files[n] = (B / n).read_bytes()
    files['CCP.SYS'] = (Path(ROOT) / 'resources' / 'CCP.SYS').read_bytes()
    readme = Path(ROOT) / 'docs' / 'DISK_README.TXT'
    if readme.exists():
        files['README.TXT'] = readme.read_text().replace('\r\n', '\n').replace('\n', '\r\n').encode('ascii') + b'\x1a'
    used = BD.build_disk(sysdisk, files, B / 'SKYLARK.DS8')
    print('SKYLARK.DS8: %d of 196 blocks used (%dK free), %d files' % (used, (196 - used) * 4, len(files)))


def main():
    common, icons, kinds = common_store()
    print('common: fast glyphs %d' % (G.G_FAST_TOP - common.next_fast))
    # the common sprite block: store (filled at stage start), gk tables, frames
    S = common_sprites()
    gk = gk_blob(kinds, SPR_DATA)
    sdata, stab, sinc = pack_sprites(S, SPR_DATA + len(gk), BLK_SPR, 0)
    assert len(S) <= N_COMMON
    spr = bytearray(common.blob(False)) + bytes(SPR_DATA - 0x3000 + 0x3000 - len(common.blob(False)))
    spr = bytearray(SPR_DATA)
    spr[0:len(common.blob(False))] = common.blob(False)
    spr += gk + sdata
    banks = {BLK_SPR: bytes(spr)}
    print('common sprites: %d frames, block %d: %d bytes' % (len(S), BLK_SPR, len(spr)))
    L = ['GK_TAB equ $%04X' % SPR_DATA]
    for i, n in enumerate(AC.KIND_ORDER):
        L.append('K_%s equ %d' % (n, i))
    for n, g in icons.items():
        L.append('IC_%s equ %d' % (n, g))
    L += sinc
    L.append('N_COMMON equ %d' % N_COMMON)
    T = ['; generated by tools/build.py: sprite frames (dw address, db block)']
    for a, b in stab:
        T.append('\tdw $%04X : db %d' % (a, b))
    T.append('\tds %d' % ((N_COMMON - len(stab)) * 3))
    T.append('\tds %d' % (64 * 3))
    winc('sprtab.inc', T)
    # stages
    nxt = 4
    stage_blocks = []
    for num, mname in enumerate(STAGE_MODULES, 1):
        mod = __import__(mname)
        blocks = list(range(nxt, nxt + 4))
        out, inc, st = build_stage(num, mod, common, blocks)
        banks.update(out)
        L += inc
        used = sorted(out.keys())
        L.append('BLK_S%dA equ %d' % (num, used[0]))
        L.append('BLK_S%dB equ %d' % (num, used[1]))
        stage_blocks.append(used[:2])
        nxt = used[-1] + 1
    L.append('stage_blk:')
    for a, b in stage_blocks:
        L.append('\tdb %d,%d' % (a, b))
    winc('gen.inc', L)
    names = []
    lf = ['\tDB STG_PROG, $00, "SKY     BIN"']
    for b in sorted(banks):
        names.append('B%02d.BNK' % b)
        lf.append('\tDB %d, $00, "%-8s%s"' % (b, 'B%02d' % b, 'BNK'))
    open(os.path.join(SRC, 'loadfiles.inc'), 'w').write('\n'.join(lf) + '\n')
    import music
    music.build(os.path.join(SRC, 'music.inc'))
    if '--noasm' in sys.argv:
        return
    assemble()
    overlays(banks)
    for b in sorted(banks):
        wfile('B%02d.BNK' % b, banks[b])
    disk(names)


def overlays(banks):
    """main.sym -> build/main.equ; assemble src/stageN.asm; patch each into its B block"""
    L = []
    for line in open(os.path.join(BUILD, 'main.sym')):
        if ': equ ' not in line:
            continue
        n, v = line.split(': equ ')
        n = n.strip()
        if '.' in n:
            continue
        L.append('%s equ $%04X' % (n, int(v, 16)))
    open(os.path.join(BUILD, 'main.equ'), 'w').write('\n'.join(L) + '\n')
    zasm = os.path.join(HERE, 'zasm.py')
    for num, (ob, oa) in sorted(OVL_SLOTS.items()):
        subprocess.check_call([sys.executable, zasm, 'stage%d.asm' % num, '--sym=../build/stage%d.sym' % num], cwd=SRC)
        code = open(os.path.join(BUILD, 'OVL%d.BIN' % num), 'rb').read()
        assert len(code) <= OVL_MAX
        blk = bytearray(banks[ob])
        blk[oa:oa + len(code)] = code
        banks[ob] = bytes(blk)
        print('stage %d overlay: %d bytes' % (num, len(code)))
        OVL_LEN[num] = len(code)


if __name__ == '__main__':
    main()
