SPR_DATA = 0x3000          # sprite frames start here in a sprite block (store below)
BLK_SPR = 3
BLK_STRIP = [29, 30, 31]
N_COMMON = 192             # sprite frames 0..191 common, 192..255 the stage's
STAGE_MODULES = ['stage1', 'stage2', 'stage3']

