"""STARHIVE game data: the five levels, their sprites, and game.inc.

Per level (blocks assigned from 8 up):
  LnROWS.BNK  row index (2 bytes a row) and row records from 0000:
              n, then n x (column, slot | 80h if its colour changes);
              the pair-load schedule from 6000h: dw offset[rows], then per
              coarse step: n, n x (slot, offset lo, offset hi, block)
  LnPAIRx.BNK pair records, 134 bytes (11 phases x 11, 11 colours, then
              2 bytes of merge flags), 244 to a block
  LnSPR.BNK   WORK block: buckets below 1600h, the sprites from 1600h
Writes build/game.inc (constants, tables, the level table) and
build/game_files.inc / .txt (the loader's list)."""
import sys
from pathlib import Path
sys.path.insert(0, str(Path(__file__).resolve().parent))
import numpy as np
import gfx
import art
import font
import mksoft
import levels

ROOT = Path(__file__).resolve().parent.parent
B = ROOT / 'build'
CL, COLS = 11, 40
PAIR_SZ = 134
PAIRS_PER_BLK = 32768 // PAIR_SZ          # 244
SCHED_AT = 0x6000
FIRST_BLK = 8
STAR_BANK = 11


def merge_flags(ph):
    """bit k: at phase k the glyph's set pixels cover more of the cell than
    its clear ones. A sprite or bullet merged into the cell then inverts
    the glyph and takes the ink as its paper, so the main colour stays
    and only the thinner detail turns the sprite's colour.
    -> 2 bytes (phases 0-7, 8-10)"""
    f = 0
    for k, g in enumerate(ph):
        if 2 * sum(bin(x).count('1') for x in g) > CL * 8:
            f |= 1 << k
    return bytes((f & 255, f >> 8))


def level_data(n, f):
    sp = f()
    sp.old_checks = False
    b, rows, pairs = mksoft.build(sp)
    slots, groups, peak = mksoft.schedule(rows)
    R = len(rows)
    vcol = b['vcol']
    # rows block
    blk = bytearray(0x8000)
    at = 2 * R
    for r in range(R):
        blk[2 * r:2 * r + 2] = at.to_bytes(2, 'little')
        plist = []
        for c in range(COLS):
            p = rows[r][c]
            if p is not None:
                cols = pairs[p][1]
                plist.append((c, slots[r][c] | (0 if len(set(cols)) == 1 else 0x80)))
        rec = bytes([len(plist)]) + bytes(x for e in plist for x in e)
        blk[at:at + len(rec)] = rec
        at += len(rec)
    assert at <= SCHED_AT, 'level %d rows: %d bytes' % (n + 1, at)
    sch = bytearray(2 * R)
    for u in range(R):
        g = groups.get(u, [])
        o = SCHED_AT + len(sch)
        sch[2 * u:2 * u + 2] = o.to_bytes(2, 'little')
        sch.append(len(g))
        for s, p in g:
            off = (p % PAIRS_PER_BLK) * PAIR_SZ
            sch += bytes((s, off & 255, off >> 8, p // PAIRS_PER_BLK))
    assert SCHED_AT + len(sch) <= 0x8000
    blk[SCHED_AT:SCHED_AT + len(sch)] = sch
    # pair blocks
    npb = (len(pairs) + PAIRS_PER_BLK - 1) // PAIRS_PER_BLK
    pblk = [bytearray(0x8000) for _ in range(npb)]
    for i, (ph, cols) in enumerate(pairs):
        o = (i % PAIRS_PER_BLK) * PAIR_SZ
        pblk[i // PAIRS_PER_BLK][o:o + PAIR_SZ] = bytes(x for g in ph for x in g) + bytes(cols) + merge_flags(ph)
    lib, labels = art.level_lib(n)
    print('level %d %-15s rows %d pairs %d (%d blocks) peak %d, row data %d, sprites %d' % (
        n + 1, levels.LEVELS[n][1], R, len(pairs), npb, peak, at, len(lib)))
    return dict(R=R, rows=bytes(blk), pairs=pblk, spr=bytes(0x1600) + lib, labels=labels, vcol=vcol)


def trim(bb):
    n = len(bb)
    while n > 128 and not any(bb[n - 128:n]):
        n -= 128
    return bytes(bb[:max(n, 128)])


def main():
    h = ['; generated by tools/mklevels.py']
    files = []
    blk = FIRST_BLK
    tab = []
    labels0 = None
    vcol0 = None
    for n, (f, name) in enumerate(levels.LEVELS):
        d = level_data(n, f)
        if labels0 is None:
            labels0, vcol0 = d['labels'], d['vcol']
        assert d['labels'] == labels0 and d['vcol'] == vcol0
        rb = blk
        (B / ('L%dROWS.BNK' % (n + 1))).write_bytes(trim(d['rows']))
        files.append((blk, 'L%dROWS  BNK' % (n + 1)))
        blk += 1
        pb = blk
        for i, p in enumerate(d['pairs']):
            (B / ('L%dPAIR%d.BNK' % (n + 1, i))).write_bytes(trim(p))
            files.append((blk, 'L%dPAIR%dBNK' % (n + 1, i)))
            blk += 1
        wb = blk
        (B / ('L%dSPR.BNK' % (n + 1))).write_bytes(d['spr'])
        files.append((blk, 'L%dSPR   BNK' % (n + 1)))
        blk += 1
        tab.append((rb, pb, wb, d['R'], name))
    assert blk <= 31, 'out of blocks: %d' % blk
    print('blocks %d..%d' % (FIRST_BLK, blk - 1))
    h.append('NLEVELS\tequ %d' % len(tab))
    h.append('STAR_BANK\tequ %d' % STAR_BANK)
    h.append('STAR_COL\tequ %d' % art.STAR_COLOUR)
    h.append('SCHED_AT\tequ $%04X' % SCHED_AT)
    for name, v in labels0.items():
        h.append('%s\tequ $%04X' % (name, v))
    # the level table: rows block, pairs block, sprites block, rows (2),
    # boss row (2), name (2) - 9 bytes
    h.append('lvl_tab:')
    for i, (rb, pb, wb, R, name) in enumerate(tab):
        h.append('\tdb %d,%d,%d\n\tdw %d,%d,lvl_name%d' % (rb, pb, wb, R, R - 26, i + 1))
    for i, (rb, pb, wb, R, name) in enumerate(tab):
        h.append('lvl_name%d:\tdb "%-24s"' % (i + 1, name))
    h.append('vcol_tab:\tdb ' + ','.join(str(v) for v in vcol0))
    tex = art.star_textures()
    for v in range(4):
        h.append('star_tex%d:\tdb %s' % (v, ','.join('$%02X' % x for x in tex[v] + tex[v])))
    boot = ['; boot-only data (font, overlay glyphs): at C000h, used before the\n; scroll segments are built there']
    fg = []
    for ch in font.ORDER[1:]:
        g = list(font.glyph(ch)[:7])
        fg += [0, 0] + g + [0, 0] + [0] * 5
    h.append('N_FONT\tequ %d' % (len(font.ORDER) - 1))
    for i in range(0, len(fg), 16):
        boot.append(('font_gl:' if i == 0 else '') + '\tdb ' + ','.join('$%02X' % x for x in fg[i:i + 16]))
    fmap = [0x80] * 64
    for i, ch in enumerate(font.ORDER):
        if 32 <= ord(ch) < 96:
            fmap[ord(ch) - 32] = 0x80 + i
    h.append('FONT_BAR\tequ $%02X' % (0x80 + font.ORDER.index('|')))
    h.append('font_map:\tdb ' + ','.join('$%02X' % x for x in fmap))
    for art_, tabname in ((art.BULLET, 'ovl_bul'), (art.SHOT, 'ovl_shot')):
        m = art_ >= 0
        oh, ow = m.shape
        gl, t = [], []
        for s2 in range(4):
            for j in range(CL):
                cv = np.zeros((2 * CL, 16), bool)
                cv[j:j + oh, 2 * s2:2 * s2 + ow] = m
                codes = [0, 0, 0, 0]
                for k, (ri, ci) in enumerate(((0, 0), (0, 1), (1, 0), (1, 1))):
                    cell = cv[ri * CL:(ri + 1) * CL, ci * 8:(ci + 1) * 8]
                    if cell.any():
                        codes[k] = 0x80 + len(gl)
                        gl.append(bytes(gfx.byte8(cell[y]) for y in range(CL)))
                t += codes
        h.append('%s:\tdb %s' % (tabname, ','.join('$%02X' % x for x in t)))
        h.append('%s_n\tequ %d' % (tabname, len(gl)))
        flat = b''.join(gl)
        for i in range(0, len(flat), 22):
            boot.append(('%s_gl:' % tabname if i == 0 else '') + '\tdb ' + ','.join('$%02X' % x for x in flat[i:i + 22]))
    rt = [max(0, 2 + (t - 16) // CL) for t in range(256)]
    ot = [(t - 16) % CL for t in range(256)]
    for i in range(0, 256, 32):                  # (copied to rowt at boot)
        boot.append(('rowt_gl:' if i == 0 else '') + '\tdb ' + ','.join(str(x) for x in rt[i:i + 32]))
    for i in range(0, 256, 32):
        boot.append('\tdb ' + ','.join(str(x) for x in ot[i:i + 32]))
    (B / 'game.inc').write_text('\n'.join(h) + '\n')
    (B / 'boot.inc').write_text('\n'.join(boot) + '\n')
    (B / 'game_files.inc').write_text(''.join('\tDB %d,"%s"\n' % (b_, nm) for b_, nm in files))
    (B / 'game_files.txt').write_text('\n'.join(nm.replace(' ', '').replace('BNK', '.BNK') for _, nm in files))


if __name__ == '__main__':
    main()
