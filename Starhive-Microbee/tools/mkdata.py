"""Build STARHIVE data: WORK.BNK (scenery mirror + sprite library),
LEVEL1.BNK, build/data.inc (sprite labels, tables), build/hud.inc."""
import sys
from pathlib import Path
sys.path.insert(0, str(Path(__file__).resolve().parent))
import numpy as np
import gfx
import art
import font
import space

ROOT = Path(__file__).resolve().parent.parent
B = ROOT / 'build'
B.mkdir(exist_ok=True)
HUD_BANKS = [12, 13, 14, 15, 5, 6]


def db(name, data, per=16):
    out = [name + ':'] if name else []
    for i in range(0, len(data), per):
        out.append('\tdb ' + ','.join('$%02X' % x for x in data[i:i + per]))
    return '\n'.join(out) + '\n'


def main():
    # ---- level (test): space
    sp = space.build_test()
    b = sp.build()
    print('level: %d rows, %d glyphs, %d metatiles' % (b['nrows'], len(b['glyphs']), len(b['meta'])))
    (B / 'LEVEL1.BNK').write_bytes(space.level_bank(b))
    tex = art.star_textures()

    # ---- WORK block: mirror (640 x 16) + sprite library
    work = bytearray(0x2800)
    for i, g in enumerate(b['glyphs']):
        work[i * 16:i * 16 + 11] = bytes(g)
    for k in range(16):
        g = art.star_glyph(tex, k // 4, k % 4)
        o = (art.STAR_FIRST + k) * 16
        work[o:o + 11] = bytes(g)
    lib, labels = art.sprite_lib()
    work += lib
    (B / 'WORK.BNK').write_bytes(bytes(work))
    print('sprite library %d bytes' % len(lib))

    # ---- data.inc
    inc = ['; generated by tools/mkdata.py']
    for k, v in labels.items():
        inc.append('%s\tequ $%04X' % (k, v))
    inc.append('N_STARS\tequ 16')
    (B / 'data.inc').write_text('\n'.join(inc) + '\n')

    # ---- tables.inc: row/line tables, stars, HUD, font
    h = ['; generated by tools/mkdata.py']
    h.append('\tALIGN 256')
    h.append(db('rowt', [(t + 16) // 11 for t in range(256)]))
    h.append(db('offt', [(t + 16) % 11 for t in range(256)]))
    h.append('star_tab:')
    for k in range(16):
        v, p = k // 4, k % 4
        h.append('\tdw $%04X,star_tex%d\n\tdb %d' % ((art.STAR_FIRST + k) * 16, v, 11 * p))
    for v in range(4):
        h.append(db('star_tex%d' % v, tex[v] + tex[v]))
    regs = art.hud_regions()
    col = 0
    tab = []
    flat = []
    for i, r in enumerate(regs):
        tab.append('hr_%s:\tdb %d,%d,%d\n\tdw hud_bmp%d,hud_cells%d' % (r.name, r.col0, r.ncols, r.colour, i, i))
        cl = []
        for c in range(r.ncols):
            bank = HUD_BANKS[col // 5]
            for j in range(2):
                idx = (col % 5) * 2 + j
                cl += [bank, idx]
                flat.append((r.col0 + c, j, idx, bank, r.colour))
            col += 1
        tab_cells = cl
        h_cells = db('hud_cells%d' % i, cl)
        tab.append(h_cells.rstrip())
    assert col <= 5 * len(HUD_BANKS), 'HUD columns %d' % col
    print('HUD columns', col)
    h.append('hud_regions:\n' + '\n'.join(t for t in tab if t.startswith('hr_')) + '\n\tdb $FF\n')
    for t in tab:
        if not t.startswith('hr_'):
            h.append(t)
    for i, r in enumerate(regs):
        h.append('hud_bmp%d:\tds %d' % (i, r.ncols * 8))
    h.append('N_HUDC\tequ %d' % len(flat))
    h.append(db('hud_flat', [b for (c, j, idx, bank, colr) in flat for b in (c, j, idx, bank, colr)]))
    h.append('hud_off:\tds %d' % (3 * len(flat)))
    h.append('hud_texts:')
    for r in regs:
        if r.text:
            h.append('\tdw hr_%s\n\tdb "%s",0' % (r.name, r.text))
    h.append('\tdw 0')
    f7 = []
    fmap = [0] * 96
    for i, ch in enumerate(font.ORDER):
        f7 += font.glyph(ch)[:7]
        if 32 <= ord(ch) < 128:
            fmap[ord(ch) - 32] = i
    for ch in 'abcdefghijklmnopqrstuvwyz':
        fmap[ord(ch) - 32] = font.ORDER.index(ch.upper())
    h.append(db('font7', f7))
    h.append(db('font_map', fmap))
    (B / 'tables.inc').write_text('\n'.join(h) + '\n')

    from PIL import Image
    rgb = space.preview(b, tex, rows=120)
    Image.fromarray(rgb).save(B / 'level_preview.png')


if __name__ == '__main__':
    main()
