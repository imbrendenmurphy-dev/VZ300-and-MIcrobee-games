"""STARHIVE wave scripts and boss settings for the five levels ->
build/waves.inc (deterministic). Wave entry: dw map row; db type,
column, count, gap (frames), amplitude. Boss entry (bosstab, 12 bytes):
hits (at the first round), box width, box height, sway amplitude, sway
speed, y to stop at, gap between attacks, attack set, how many, column
of the first, name (2)."""
from pathlib import Path
import random
import levels

B = Path(__file__).resolve().parent.parent / 'build'
T_DRONE, T_DART, T_POD, T_SWEEP, T_SPIT = 1, 2, 3, 6, 7
A_AIM, A_SPREAD3, A_SPREAD5, A_DRONES, A_DARTS = 1, 2, 4, 8, 16

BOSSES = [  # hits, w, h, amp, speed, y, gap, attacks, count, column, name
    (40, 38, 20, 112, 2, 30, 46, A_AIM | A_SPREAD3, 1, 18, 'HIVE QUEEN'),
    (48, 38, 20, 100, 3, 30, 40, A_AIM | A_SPREAD3 | A_DARTS, 1, 18, 'ROCK MITE'),
    (24, 24, 16, 70, 3, 26, 44, A_AIM | A_SPREAD3, 2, 10, 'TWIN WARDENS'),
    (56, 46, 18, 60, 1, 28, 40, A_SPREAD5 | A_DARTS | A_AIM, 1, 16, 'DEAD FLEET HULK'),
    (72, 38, 24, 110, 2, 30, 34, A_AIM | A_SPREAD3 | A_SPREAD5 | A_DRONES, 1, 18, 'THE HIVE MIND'),
]

KINDS = [
    [T_DRONE, T_DRONE, T_DART, T_POD],
    [T_DRONE, T_DART, T_SWEEP, T_POD, T_DART],
    [T_DRONE, T_SPIT, T_SWEEP, T_DART, T_DRONE],
    [T_DART, T_SWEEP, T_POD, T_SPIT, T_DRONE, T_DART],
    [T_DRONE, T_SWEEP, T_SPIT, T_DART, T_POD, T_DRONE, T_SWEEP],
]


def script(n, rows):
    rnd = random.Random(1000 + n)
    out = []
    row = 30
    gap_rows = 17 - 2 * n                  # busier as it goes on
    last = rows - 32
    while row < last:
        t = rnd.choice(KINDS[n])
        if t == T_DRONE:
            out.append((row, t, rnd.choice([8, 12, 18, 24, 28]), 5 + n // 2, 8 - n // 2, rnd.choice([30, 40, 60, 80, 100])))
        elif t == T_DART:
            out.append((row, t, 0, 3 + n, 12 - n, 0))
        elif t == T_POD:
            c = rnd.randrange(4, 32)
            out.append((row, t, c, 1, 1, 0))
            if n >= 3:
                out.append((row + 3, t, 36 - c, 1, 1, 0))
        elif t == T_SWEEP:
            side = rnd.choice([1, 36])
            out.append((row, t, side, 3 + n // 2, 14, 0))
        elif t == T_SPIT:
            out.append((row, t, rnd.choice([6, 10, 14, 22, 26, 30]), 1, 1, 0))
        row += gap_rows + rnd.randrange(0, 8)
    return out


def main():
    h = ['; generated by tools/mkwaves.py']
    h.append('waves_tab:\tdw ' + ','.join('waves%d' % (i + 1) for i in range(5)))
    for n, (f, name) in enumerate(levels.LEVELS):
        h.append('waves%d:' % (n + 1))
        for (row, t, col, cnt, gap, amp) in script(n, levels.ROWS):
            h.append('\tdw %d\n\tdb %d,%d,%d,%d,%d' % (row, t, col, cnt, gap, amp))
        h.append('\tdw $FFFF')
    h.append('BOSS_SZ\tequ 12')
    h.append('bosstab:')
    for i, b in enumerate(BOSSES):
        h.append('\tdb %d,%d,%d,%d,%d,%d,%d,%d,%d,%d\n\tdw boss_name%d' % (b[:10] + (i + 1,)))
    for i, b in enumerate(BOSSES):
        h.append('boss_name%d:\tdb "%-16s"' % (i + 1, b[10]))
    (B / 'waves.inc').write_text('\n'.join(h) + '\n')
    print('waves:', [len(script(n, levels.ROWS)) for n in range(5)])


if __name__ == '__main__':
    main()
