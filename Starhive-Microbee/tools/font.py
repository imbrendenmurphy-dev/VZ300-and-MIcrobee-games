def glyph(ch, y0=0):
    """8 bytes: the character drawn from line y0 (7 rows, rest blank)"""
    rows = F.get(ch, F[' '])
    out = [0] * 8
    for i, r in enumerate(rows):
        if 0 <= y0 + i < 8:
            b = 0
            for x, c in enumerate(r):
                if c == '#':
                    b |= 0xC0 >> (2 * x)
            out[y0 + i] = b
    return out


