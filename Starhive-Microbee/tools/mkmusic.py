"""STARHIVE title music -> build/music.inc.

A two-voice 1-bit tune: the player (in game.asm) adds each voice's step
to a 16-bit phase every sample and sends the phase's top bit to the
speaker, the two voices taking turns (about 29,000 samples a second).
Event: dw samples, dw step of the lead, dw step of the bass; 0 ends."""
from pathlib import Path

B = Path(__file__).resolve().parent.parent / 'build'
CPU = 3375000
T_SAMPLE = 106                       # T-states a sample in the player loop
RATE = CPU / T_SAMPLE
SIXTEENTH = 0.105                    # seconds (about 143 beats a minute)
NOTES = {'C': 0, 'C#': 1, 'D': 2, 'D#': 3, 'E': 4, 'F': 5, 'F#': 6, 'G': 7, 'G#': 8, 'A': 9, 'A#': 10, 'B': 11}


def freq(n):
    if n in ('.', '-'):
        return 0
    name, octv = n[:-1], int(n[-1])
    semis = NOTES[name] + 12 * (octv - 4) - 9      # from A4
    return 440.0 * 2 ** (semis / 12)


def step(f):
    return int(round(f * 65536 / RATE)) if f else 0


# lead, in sixteenths ('-' holds the note before, '.' is a rest)
LEAD = (
    'A4 - C5 - E5 - A5 - G5 - E5 - D5 E5 - - '
    'F4 - A4 - C5 - F5 - E5 - C5 - A4 C5 - - '
    'C5 - E5 - G5 - C6 - B5 - G5 - E5 G5 - - '
    'G4 - B4 - D5 - G5 - F#5 - D5 - B4 D5 - - '
    'A5 - - - G5 - E5 - D5 - E5 - C5 - A4 - '
    'F5 - - - E5 - C5 - A4 - C5 - D5 - E5 - '
    'C6 - - - B5 - G5 - E5 - G5 - B5 - D6 - '
    'E6 - - - - - - - E5 . E5 . E5 - - - '
).split()
BASS_BAR = {'Am': ('A2', 'A3'), 'F': ('F2', 'F3'), 'C': ('C3', 'C4'), 'G': ('G2', 'G3'), 'E': ('E2', 'E3')}
CHORDS = ['Am', 'F', 'C', 'G', 'Am', 'F', 'C', 'E']


def main():
    bass = []
    for ch in CHORDS:
        lo, hi = BASS_BAR[ch]
        bass += [lo, lo, hi, lo] * 4
    assert len(LEAD) == len(bass) == 128, (len(LEAD), len(bass))
    names = sorted(set(LEAD + bass) - {'-', '.'}, key=freq)
    idx = {n: i + 1 for i, n in enumerate(names)}
    data = []
    cur = None
    for i in range(128):
        lead = LEAD[i]
        if lead == '-':
            lead = cur
        cur = lead
        data += [idx.get(lead, 0), idx[bass[i]]]
    n = int(SIXTEENTH * RATE)
    k = n * 2 // 3
    h = ['; generated by tools/mkmusic.py', 'TUNE_K\tequ %d\t\t; samples with the bass on' % k,
         'TUNE_R\tequ %d\t\t; then the lead alone' % (n - k),
         'tune_steps:\tdw 0,' + ','.join(str(step(freq(x))) for x in names)]
    for j in range(0, len(data), 32):
        h.append(('tune:' if j == 0 else '') + '\tdb ' + ','.join(str(x) for x in data[j:j + 32]))
    h.append('\tdb 255')
    (B / 'music.inc').write_text('\n'.join(h) + '\n')
    print('tune: %d notes, %d bytes, %.1f s' % (len(names), 2 * len(names) + len(data) + 3, 128 * SIXTEENTH))


if __name__ == '__main__':
    main()
