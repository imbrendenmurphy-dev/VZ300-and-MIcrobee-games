def font_glyphs():
    """64 glyphs for chars 32..95: the 5 x 7 letters with every stroke
    doubled to the right (6 wide), so they stay solid on an amber screen"""
    out = []
    for ch in CHARS:
        rows = FD.get(ch)
        if rows is None:
            out.append(bytes(8))
            continue
        b = []
        for r in rows.split():
            v = int(r, 2) << 2
            b.append(v | (v >> 1))
        out.append(bytes(b + [0]))
    return out
