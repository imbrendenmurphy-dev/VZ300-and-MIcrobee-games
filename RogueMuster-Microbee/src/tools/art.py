# ---------------------------------------------------------------- small glyphs
def g8(rows):
    rows = rows.split()
    assert len(rows) == 8
    return bytes(int(r.replace('#', '1').replace('.', '0'), 2) for r in rows)


def quad(pat4):
    """a 4 x 4 pattern in each quarter of a cell -> 4 glyphs (y*2 + x)"""
    out = []
    rows = pat4.split()
    for qy in range(2):
        for qx in range(2):
            b = bytearray(8)
            for y, r in enumerate(rows):
                for x, c in enumerate(r):
                    if c == '#':
                        b[qy * 4 + y] |= 128 >> (qx * 4 + x)
            out.append(bytes(b))
    return out


