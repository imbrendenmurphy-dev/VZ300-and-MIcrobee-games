def art(rows, w=12):
    rows = [r for r in rows.strip('\n').split('\n')]
    a = np.zeros((12, 16), bool)
    assert len(rows) <= 12, rows
    for y, r in enumerate(rows):
        r = r.strip()
        assert len(r) <= w, (r, len(r))
        for x, ch in enumerate(r):
            a[y, x] = ch == '#'
    return a


def mirror(a, w=12):
    b = np.zeros_like(a)
    b[:, :w] = a[:, :w][:, ::-1]
    return b


