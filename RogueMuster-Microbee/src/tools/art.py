def popup(txt):
    a = np.zeros((12, 16), bool)
    for i, ch in enumerate(txt):
        for y, r in enumerate(D35[ch].split()):
            for x, c in enumerate(r):
                a[3 + y, i * 4 + x] = c == '#'
    return a


