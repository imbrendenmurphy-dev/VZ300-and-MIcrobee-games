"""ROGUE MUSTER music (original, VIBED BY BPM 2026) for the two-voice
pin-pulse beeper engine (frame_wait loop: 127 T at 3.375 MHz). One step of
a song is one 25 Hz frame. Every note's last frame is silent, so notes stay
separate and gritty. Writes src/music.inc."""
import os

HERE = os.path.dirname(os.path.abspath(__file__))
LOOPRATE = 3375000.0 / 127
NAMES = {'C': 0, 'C#': 1, 'D': 2, 'D#': 3, 'E': 4, 'F': 5, 'F#': 6, 'G': 7, 'G#': 8, 'A': 9, 'A#': 10, 'B': 11}


def nidx(tok):
    return (int(tok[-1]) - 2) * 12 + NAMES[tok[:-1]] + 1


def build(out):
    L = ['; generated by tools/music.py', 'notetab:']
    steps = [0]
    for i in range(1, 73):
        f = 65.406 * 2 ** ((i - 1) / 12.0)
        steps.append(int(round(f * 65536 / LOOPRATE)))
    L.append('    dw ' + ','.join(str(s) for s in steps))

    def db(bs):
        bs = list(bs)
        for i in range(0, len(bs), 16):
            L.append('    db ' + ','.join('$%02X' % b for b in bs[i:i + 16]))

    def song(name, step, *chans, loop=False):
        for ci, txt in enumerate(chans):
            ev = []
            for t in txt.split():
                if t == '-':
                    ev[-1][1] += step
                elif t == 'r':
                    ev.append([0, step])
                else:
                    ev.append([nidx(t), step])
            o = []
            for n, d in ev:
                while d > 255:
                    o += [n, 255]
                    d -= 255
                o += [n, d]
            o.append(0xFE if loop else 0xFF)
            L.append('mus_%s_%d:' % (name, ci))
            db(o)

    # title: "The Rogue Muster" - a stockman's march gone wrong, A minor
    title = """
A4 r A4 C5 E5 - C5 r  D5 r D5 F5 A5 - F5 r
E5 r E5 G#5 B5 - G#5 r  A5 - E5 - C5 - A4 r
A4 r C5 E5 A5 - G5 E5  F5 r A5 F5 D5 - - r
E5 r G#4 B4 E5 - D5 B4  A4 - - r A4 - - r
"""
    bass = """
A2 r E3 r A2 r E3 r  D3 r A2 r D3 r A2 r
E3 r B2 r E3 r B2 r  A2 r E3 r A2 r E3 r
A2 r E3 r A2 r E3 r  D3 r A2 r D3 r A2 r
E3 r B2 r E3 r G#2 r  A2 r E3 r A2 - - r
"""
    song('title', 5, title, bass, loop=True)
    # in play: slow, sparse blips (dink ... dink-dink-dink) so the game keeps its time
    ingame = """
A3 r r r r r r r  A3 r A3 r C4 r r r
r r r r r r r r  G3 r r r r r r r
A3 r r r r r r r  A3 r A3 r D4 r r r
r r r r r r r r  E4 r r r E3 r r r
"""
    ingb = """
r r r r A2 r r r  r r r r r r r r
F2 r r r r r r r  r r r r G2 r r r
r r r r A2 r r r  r r r r r r r r
D2 r r r r r r r  r r r r E2 r r r
"""
    song('game', 5, ingame, ingb, loop=True)
    song('ready', 4, 'E4 A4 C5 E5 - - - r', 'A2 r A3 r A2 A3 A2 r')
    song('clear', 4, 'A4 C5 E5 A5 - C6 - E6 - - - r', 'A2 A3 A2 A3 E2 E3 E2 E3 A2 - - r')
    song('over', 8, 'E4 - D4 - C4 - B3 - - - A3 - - - r', 'A2 - - - G2 - - - F2 - - - E2 - - r')
    open(out, 'w').write('\n'.join(L) + '\n')


if __name__ == '__main__':
    build(os.path.join(HERE, '..', 'src', 'music.inc'))
