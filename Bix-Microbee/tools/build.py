BLK_GAME, BLK_MAP = 4, 5
E_START = 9
ENEMIES = art2.ENEMY_ORDER
NEN = len(ENEMIES)
BLK_STG = 8                     # stage n is in block 8 + n
SPR_BLOCKS = [6, 23, 24, 25, 26, 27, 28, 29, 30]
# a stage's block
S_PAT, S_TABLES, S_TMAP, S_ENTS, S_HDR = 0x0000, 0x3000, 0x5000, 0x6400, 0x6600


def level():
    stages = data.stages()
    (BUILD / 'hudg.bin').write_bytes(font.hud_glyphs())
    (BUILD / 'font.bin').write_bytes(font.build())
    (BUILD / 'tattr.bin').write_bytes(bytes(a for _, _, a in vz.TILES).ljust(64, b'\0'))
    names = []
    for n, S in enumerate(stages):
        D = data.build(S)
        pat, colc, colm, mixed = data.pair_glyphs(D)
        tab, probes = data.hash_table(D, mixed)
        ncg, npair = len(D['C'].list), len(D['plist'])
        assert ncg < 255
        tc = bytearray()
        for name, _, _ in vz.TILES:
            tc += bytes(D['tcell'][name])
        pl = bytearray()
        for row in D['plath']:
            pl += bytes(row)
        pl = pl.ljust(0x20, b'\0')
        for rows in D['platv']:
            pl += bytes(rows)
        # the scroll glyphs; the map block's tables (as they sit from M_HASH);
        # the tile map; the spawn list; a header
        blob = tab + bytes(tc).ljust(256, b'\0') + bytes(pl).ljust(256, b'\0') + colc + colm
        assert len(blob) == 0x1E00
        g = S['g']
        tm = bytearray()
        for x in range(S['W']):
            for y in range(data.H):
                tm.append(vz.TID[g[x][y]])
        tm += bytes([vz.TID['sky']]) * data.H
        assert len(tm) <= 0x1400, len(tm)
        e = bytearray()
        for (x, y, t, p) in sorted(S['ents']):
            e += bytes([x & 255, x >> 8, y, t, p])
        e += b'\xff\xff'
        assert len(e) <= 0x200, len(e)
        hdr = bytes([S['W'] & 255, S['W'] >> 8, S['start'][0] & 255, S['start'][0] >> 8, S['start'][1], S['boss'],
                     S['world'], S.get('mirror', 0)])
        b = bytearray(pat).ljust(S_TABLES, b'\0') + blob
        b = b.ljust(S_TMAP, b'\0') + tm
        b = b.ljust(S_ENTS, b'\0') + e
        b = b.ljust(S_HDR, b'\0') + hdr
        (BUILD / ('S%d.BNK' % n)).write_bytes(bytes(b))
        names += [(BLK_STG + n, 0, 'S%d' % n, 'BNK')]
        print('stage %d-%d: %d tiles wide, %d cell glyphs, %d pairs of %d (%d of two inks), %d spawns' % (
            S['world'], n % 3 + 1, S['W'], ncg, npair, data.MAXPAIR, sum(mixed), len(S['ents'])))
    L = ['; generated by tools/build.py']
    for i, (n, _, _) in enumerate(vz.TILES):
        L.append('T_%s equ %d' % (n.upper(), i))
    for n in ['SOLID', 'ONEWAY', 'DIG', 'HAZ', 'STAR', 'SPRING', 'BREAK', 'SPECIAL']:
        L.append('A_%s equ %d' % (n, getattr(vz, n)))
    for i, n in enumerate(vz.BIX_ORDER):
        L.append('PF_%s equ %d' % (n.upper(), i))
    for i, n in enumerate(ENEMIES):
        L.append('EF_%s equ %d' % (n.upper(), len(vz.BIX_ORDER) + i))
    L.append('NEN equ %d' % NEN)
    L.append('BF_BOSS equ %d' % (len(vz.BIX_ORDER) + data.NWORLD * NEN))
    L += ['LEVH equ %d' % data.H, 'CAMYMAX equ %d' % (data.H * 8 - 92), 'NSTAGE equ %d' % len(stages), 'BLK_STG equ %d' % BLK_STG]
    L += ['S_PAT equ $%04X' % S_PAT, 'S_TABLES equ $%04X' % S_TABLES, 'S_TMAP equ $%04X' % S_TMAP,
          'S_ENTS equ $%04X' % S_ENTS, 'S_HDR equ $%04X' % S_HDR]
    (SRC / 'gen.inc').write_text('\n'.join(L) + '\n')
    return names


BOSSES = {1: (art2.BOSS1, art2.BOSS_ORDER), 2: (art2.BOSS2, art2.BOSS2_ORDER), 3: (art2.BOSS3, art2.BOSS3_ORDER),
          4: (art2.BOSS4, art2.BOSS4_ORDER), 5: (art2.BOSS5, art2.BOSS5_ORDER)}


def sprites():
    F = {}
    order = list(vz.BIX_ORDER)
    F.update(gfx.bix_frames())
    for w in range(1, data.NWORLD + 1):
        src = art2.w1_enemies() if w == 1 else getattr(art2, 'W%d_ENEMY' % w)
        for n in ENEMIES:
            F['e%d_%s' % (w, n)] = gfx.sprite_from(src[n])
            order.append('e%d_%s' % (w, n))
    for w in range(1, data.NWORLD + 1):
        B, bo = BOSSES[w]
        for n in bo:
            rows = B[n]
            if w == 1:
                # King Cane: his red mouth, warts and belly become dark lines in the ink; his toes stay lit
                rows = [r.replace('r', 'b') if y < len(rows) - 3 else r for y, r in enumerate(rows)]
            F['b%d_%s' % (w, n)] = gfx.boss_sprite(rows, w)
            order.append('b%d_%s' % (w, n))
    banks = [bytearray()]
    tab = []
    for name in order:
        ink, cut = F[name]
        for face in (0, 1):
            i2, c2 = (ink[:, ::-1], cut[:, ::-1]) if face else (ink, cut)
            vs = gfx.variants(i2, c2)
            size = 16 + sum(len(v) for v in vs)
            if len(banks[-1]) + size > 32768:
                banks.append(bytearray())
            b = banks[-1]
            table = len(b)
            b += bytes(16)
            for k, v in enumerate(vs):
                a = len(b)
                b[table + 2 * k] = a & 255
                b[table + 2 * k + 1] = a >> 8
                b += v
            tab.append((SPR_BLOCKS[len(banks) - 1], table))
    L = ['; generated by tools/build.py: block, 0, the variant table (in the block)',
         '; entry = frame * 2 + facing (0 right, 1 left)', 'sprtab:']
    for blk, table in tab:
        L.append('\tdb %d,0\n\tdw $%04X' % (blk, table))
    (SRC / 'sprtab.inc').write_text('\n'.join(L) + '\n')
    for i, b in enumerate(banks):
        (BUILD / ('SPR%d.BNK' % i)).write_bytes(bytes(b))
    print('sprites: %d frames, %d bytes in %d blocks' % (len(order), sum(len(b) for b in banks), len(banks)))
    return len(banks)


def dbs(vals, per=16):
    return ['\tdb ' + ','.join(str(int(v) & 255) for v in vals[i:i + per]) for i in range(0, len(vals), per)]


def pitch(f):
    """the speaker loop's count for a frequency: a half period is 42 T a count plus 37"""
    return max(1, min(254, int(round((3375000 / (2.0 * f) - 37) / 42))))


NOTE = {n: i for i, n in enumerate(['C', 'C#', 'D', 'D#', 'E', 'F', 'F#', 'G', 'G#', 'A', 'A#', 'B'])}


def hz(name):
    n, o = name[:-1], int(name[-1])
    return 440.0 * 2 ** ((NOTE[n] - 9) / 12.0 + (o - 4))


def sound():
    L = ['; generated by tools/build.py: effects are (pitch, frames) ... 0,0']
    names = []

    def sfx(name, steps):
        names.append(name)
        L.append('%s:' % name)
        v = []
        for f, t in steps:
            v += [255 if f == 'N' else (0 if f == 0 else pitch(f)), t]
        L.extend(dbs(v + [0, 0]))
    sfx('s_jump', [(300 + 90 * i, 1) for i in range(5)])
    sfx('s_spring', [(180 + 30 * i * i, 1) for i in range(7)] + [(1300, 2)])
    sfx('s_bonus', [(784, 2), (988, 2), (1175, 2), (1568, 3)])
    sfx('s_break', [('N', 3), (120, 1)])
    sfx('s_star', [(1568, 1), (2093, 2)])
    sfx('s_oneup', [(784, 2), (1047, 2), (1319, 2), (1568, 2), (2093, 4)])
    sfx('s_hurt', [(440 - 40 * i, 1) for i in range(7)] + [('N', 2)])
    sfx('s_die', [(600 - 36 * i, 1) for i in range(14)] + [('N', 4)])
    sfx('s_win', [(784, 3), (988, 3), (1175, 3), (1568, 6), (1175, 3), (1568, 10)])
    sfx('s_dig', [('N', 2), (110, 2), ('N', 2)])
    sfx('s_digstep', [(95, 1)])
    sfx('s_burst', [('N', 2)] + [(200 + 150 * i, 1) for i in range(7)])
    sfx('s_check', [(1047, 3), (1568, 5)])
    sfx('s_swoop', [(2200 - 180 * i, 1) for i in range(8)])
    sfx('s_hop', [(130, 1), (180, 1)])
    sfx('s_stomp', [(240, 1), (120, 1), ('N', 2)])
    sfx('s_power', [(523 + 130 * i, 1) for i in range(10)])
    L.append('sfx_tab: dw ' + ','.join(names))
    # the tune: Bix's motif (G-B-D-G, "dig-dig-dig-POP") from the VZ game,
    # an octave down, as slow separate blips
    mel = ("G3 B3 D4 G4 F#4 D4 E4 - C4 E4 G4 C5 B4 G4 A4 - "
           "G3 B3 D4 G4 A4 G4 E4 D4 C4 D4 E4 F#4 G4 - - - "
           "E4 - E4 G4 D4 - B3 - C4 - C4 E4 D4 - - - "
           "E4 F#4 G4 A4 B4 A4 G4 E4 D4 G4 F#4 A4 G4 - - -").split()
    ev = []
    for t in mel:
        if t == '-':
            ev[-1][1] += 7
        else:
            ev.append([pitch(hz(t)), 7])
    tunes = [ev]
    import music as vzm
    # the other worlds' tunes are the VZ game's, as the same slow blips
    for name, f8 in (('BOSS', 5), ('CAVES', 8), ('GOLEM', 6), ('FACTORY', 5), ('ROBOT', 5),
                     ('SKY', 5), ('HAWK', 5), ('PEAKS', 5), ('DRAGON', 5)):
        toks = getattr(vzm, 'SONG_' + name).split()
        notes = [t for t in toks if t not in ('-', 'r')]
        down = 0.5 if min(hz(n) for n in notes) / 2 >= 160 else 1.0
        ev = []
        for t in toks:
            if t in ('-', 'r'):
                ev[-1][1] += f8
            else:
                ev.append([min(253, pitch(hz(t) * down)), f8])
        tunes.append(ev)
    T = ['; generated by tools/build.py: the tunes (pitch, frames) ... $FE; by world * 2 + boss',
         'tune_tab: dw ' + ','.join('tune%d' % i for i in range(len(tunes)))]
    longest = 0
    for i, ev in enumerate(tunes):
        T.append('tune%d:' % i)
        v = []
        for p, t in ev:
            while t > 250:
                v += [p, 250]; t -= 250; p = 0
            v += [p, t]
        T.extend(dbs(v))
        T.append('\tdb $FE')
        longest = max(longest, len(v) + 1)
    (SRC / 'tunes.inc').write_text('\n'.join(T) + '\n')
    L.append('TUNELEN equ %d' % longest)
    L.append('tunebuf: ds TUNELEN')
    (SRC / 'snd.inc').write_text('\n'.join(L) + '\n')


def assemble(nspr, stg):
    names = [('STG_PROG', 0, 'BIX', 'BIN'), (BLK_GAME, 1, 'GAME', 'BNK'), (BLK_MAP, 0, 'MAP', 'BNK')] + stg
    for i in range(nspr):
        names.append((SPR_BLOCKS[i], 0, 'SPR%d' % i, 'BNK'))
    (SRC / 'loadfiles.inc').write_text('\n'.join('\tDB %s, $%02X, "%-8s%s"' % n for n in names) + '\n')
    zasm = str(HERE / 'zasm.py')
    subprocess.check_call([sys.executable, zasm, 'main.asm', '--sym=../build/main.sym'], cwd=SRC)
    subprocess.check_call([sys.executable, zasm, 'map.asm', '--sym=../build/map.sym'], cwd=SRC)
    sz = (BUILD / 'BIX.BIN').stat().st_size
    (SRC / 'proglen.inc').write_text('PROG_LEN    EQU $%04X\n' % ((sz + 255) // 256 * 256))
    subprocess.check_call([sys.executable, zasm, 'loader.asm', '--sym=../build/loader.sym'], cwd=SRC)
    print('BIX.BIN %d bytes, GAME.BNK %d, MAP.BNK %d' % (sz, (BUILD / 'GAME.BNK').stat().st_size, (BUILD / 'MAP.BNK').stat().st_size))
    return names


def disk(names):
    import build_disk as BD
    sysdisk = (ROOT / 'resources' / 'boot_tracks.bin').read_bytes()
    files = {'BIX.COM': (BUILD / 'BIX.COM').read_bytes()}
    for b, o, n, e in names:
        files['%s.%s' % (n, e)] = (BUILD / ('%s.%s' % (n, e))).read_bytes()
    files['CCP.SYS'] = (ROOT / 'resources' / 'CCP.SYS').read_bytes()
    readme = ROOT / 'docs' / 'DISK_README.TXT'
    if readme.exists():
        files['README.TXT'] = readme.read_text().replace('\r\n', '\n').replace('\n', '\r\n').encode('ascii') + b'\x1a'
    used = BD.build_disk(sysdisk, files, BUILD / 'BIX.DS8')
    print('BIX.DS8: %d of 196 blocks used, %d files' % (used, len(files)))


if __name__ == '__main__':
    stg = level()
    nspr = sprites()
    sound()
    names = assemble(nspr, stg)
    disk(names)
