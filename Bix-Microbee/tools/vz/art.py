def slope_rows(sky, grass, soil, right=True):
    # 45-degree ramp: ground below the diagonal, a grassy edge on it, sky above
    out = []
    for r in range(8):
        row = ''
        for c in range(8):
            cc = c if right else 7 - c
            edge = 7 - cc            # surface height at this column
            if r < edge: row += sky[r][c]
            elif r < edge + 2: row += grass[1 + (r - edge)][c]
            else: row += soil[r][c]
        out.append(row)
    return out
