def has(ch):
    return ch.upper() in G

def draw(im, x, y, s, fill=1, spacing=6):
    """Draw string s with top-left (x, y) onto a PIL image; returns end x."""
    for ch in s:
        g = G.get(ch.upper())
        if g:
            for yy, row in enumerate(g):
                for xx, c in enumerate(row):
                    if c == '#' and 0 <= x + xx < im.width and 0 <= y + yy < im.height:
                        im.putpixel((x + xx, y + yy), fill)
        x += spacing
    return x

def width(s, spacing=6):
    return len(s) * spacing - (spacing - 5)
