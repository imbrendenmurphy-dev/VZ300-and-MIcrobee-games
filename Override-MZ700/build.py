NAME = 'OVERRIDE'
LOAD = 0x1200


def db_lines(vals, per=16):
    return '\n'.join('        db ' + ','.join('%d' % (v & 0xFF) for v in vals[i:i + per])
                     for i in range(0, len(vals), per))


def asm_str(s):
    s = s.replace('"', "'")
    return 'db "%s",0' % s


# ---------------------------------------------------------------- codes
def gen_codes():
    out = [codes.tables_asm()]
    for nm in ('F_SOLID', 'F_SHOT', 'F_DOOR', 'F_LIFT', 'F_CON', 'F_ENER', 'F_VOID'):
        out.append('%s equ %d' % (nm, getattr(codes, nm)))
    # body groups must be 17 codes apart: L lit, R lit, L dim, R dim, 3 eyes, 10 digits
    for bi in range(len(codes.BODY)):
        base = codes.index['DL%d' % bi]
        assert codes.index['DR%d' % bi] == base + 1
        assert codes.index['DL%d.d' % bi] == base + 2
        assert codes.index['EYE%d_0' % bi] == base + 4
        assert codes.index['DG%d_0' % bi] == base + 7
    assert codes.index['SHP1'] == codes.index['SHP0'] + 2
    assert codes.index['SHP0.d'] == codes.index['SHP0'] + 1
    assert codes.index['EX1'] == codes.index['EX0'] + 2
    return '\n'.join(out) + '\n'


# ---------------------------------------------------------------- tables
ASCII = {' ': 0x00, '!': 0x61, '"': 0x62, '#': 0x63, '$': 0x64, '%': 0x65, '&': 0x66, "'": 0x67,
         '(': 0x68, ')': 0x69, '+': 0x6A, '*': 0x6B, ',': 0x2F, '-': 0x2A, '.': 0x2E, '/': 0x2D,
         ':': 0x4F, ';': 0x2C, '=': 0x2B, '?': 0x49, '<': 0x51, '>': 0x57, '[': 0x52, ']': 0x54}


def atod():
    t = [0] * 256
    for c in range(256):
        ch = chr(c)
        if 'A' <= ch <= 'Z':
            t[c] = c - 64
        elif 'a' <= ch <= 'z':
            t[c] = c - 96
        elif '0' <= ch <= '9':
            t[c] = 0x20 + c - 48
        elif ch in ASCII:
            t[c] = ASCII[ch]
        elif c >= 0x80:
            t[c] = c          # raw display codes pass through
    return t


def gen_tables():
    out = ['; generated by build.py', '        align 256', 'ATOD:', db_lines(atod()),
           '        align 256', 'NOTETAB:']
    nt = music.notetab()
    for i in range(0, 128, 8):
        out.append('        dw ' + ','.join('%d' % v for v in nt[i:i + 8]))
    return '\n'.join(out) + '\n'


# ---------------------------------------------------------------- roster
def bcd16(n):
    s = '%04d' % n
    return int(s[2:], 16), int(s[:2], 16)


def gen_roster():
    out = ['; generated by build.py - droid roster, 32 bytes per type',
           'NTYPES equ %d' % roster.NTYPES,
           'R_D0 equ 0', 'R_EN equ 3', 'R_SPD equ 4', 'R_WPN equ 5', 'R_AGG equ 6', 'R_CB equ 7',
           'R_DMG equ 8', 'R_RELOAD equ 9', 'R_RANGE equ 10', 'R_CLASS equ 11', 'R_SCORE equ 12',
           'R_NAME equ 14', 'R_TXT1 equ 16', 'R_TXT2 equ 18', 'R_WNAME equ 20']
    for i, nm in enumerate(['W_NONE', 'W_ZAP', 'W_LASER', 'W_TWIN', 'W_RAPID', 'W_CANNON']):
        out.append('%s equ %d' % (nm, i))
    out.append('        align 32')
    out.append('ROSTER:')
    strings = []
    for t, (num, name, en, spd, wpn, agg, t1, t2) in enumerate(roster.ROSTER):
        dmg, reload, rng = roster.WEAPONS[wpn]
        bi = codes.BODY_PLAYER if t == 0 else codes.body_index(num)
        cb = codes.index['DL%d' % bi]
        lo, hi = bcd16(roster.score_value(num))
        speed = max(3, round(spd * 0.85))
        vals = [num // 100, num // 10 % 10, num % 10, en, speed, wpn, agg, cb, dmg, reload, rng,
                num // 100, lo, hi]
        out.append('        db ' + ','.join('%d' % v for v in vals))
        out.append('        dw rn_%d, rt1_%d, rt2_%d, wn_%d' % (t, t, t, wpn))
        out.append('        ds 10')
        strings.append('rn_%d: %s' % (t, asm_str(name)))
        strings.append('rt1_%d: %s' % (t, asm_str(t1)))
        strings.append('rt2_%d: %s' % (t, asm_str(t2)))
    for i, w in enumerate(roster.WEAPON_NAMES):
        strings.append('wn_%d: %s' % (i, asm_str(w if i else 'UNARMED')))
    return '\n'.join(out + strings) + '\n'


# ---------------------------------------------------------------- ships
def rle(vals):
    out = []
    i = 0
    while i < len(vals):
        j = i
        while j < len(vals) and vals[j] == vals[i] and j - i < 255:
            j += 1
        n = j - i
        if n >= 4:
            out += [0xFF, n, vals[i]]
        else:
            out += vals[i:j]
        i = j
    return out


BASE = {'V': 0, 'F': 1, 'M': 1, 'W': 2}


def base_code(k):
    if k in BASE:
        return BASE[k]
    if k.startswith('D'):
        return 2            # doors sit in walls; drawn from the door list
    return 1                # lifts, energizers, consoles, props: on floor


def encode_rows(d):
    """rows of (code << 6 | run length) bytes, or FFh k = copy the row k up"""
    rows = [[base_code(d.K[y][x]) for x in range(d.W)] for y in range(d.H)]
    out = []
    for y, row in enumerate(rows):
        for k in range(1, min(y, 255) + 1):
            if rows[y - k] == row:
                out += [0xFF, k]
                break
        else:
            x = 0
            while x < d.W:
                j = x
                while j < d.W and row[j] == row[x] and j - x < 63:
                    j += 1
                out.append((row[x] << 6) | (j - x))
                x = j
    return out, rows


def check_deck(d, rows, props):
    """rebuild the tile names the way the loader does and compare"""
    T = [[['VOID', 'FLOOR', 'WALL'][rows[y][x]] for x in range(d.W)] for y in range(d.H)]
    for kind, x, y in d.doors:
        if kind == 'H':
            for i in range(3):
                T[y][x + i] = 'DH0'
        else:
            T[y][x] = T[y + 1][x] = 'DV0'
    for (x, y) in d.lifts:
        for k in range(6):
            T[y + k // 3][x + k % 3] = 'LIFT%d' % k
    for (x, y) in d.consoles:
        T[y][x], T[y][x + 1] = 'CON0', 'CON1'
    for x, y, nm in props:
        T[y][x] = nm
    for y in range(d.H):                      # decorate (top to bottom)
        for x in range(d.W):
            if T[y][x] == 'FLOOR' and x % 4 == 2 and y % 3 == 1:
                T[y][x] = 'MARK'
            elif T[y][x] == 'WALL' and y + 1 < d.H:
                b = T[y + 1][x]
                if b not in ('WALL', 'VOID') and not b.startswith('D'):
                    T[y][x] = 'FACE'
    for (x, y) in d.eners:
        for k in range(6):
            T[y + k // 3][x + k % 3] = 'ENER0'
    plain = {'STAR1': 'VOID', 'STAR2': 'VOID'}
    for y in range(d.H):
        for x in range(d.W):
            want = plain.get(d.tiles[y][x], d.tiles[y][x])
            assert T[y][x] == want, (d.name, x, y, T[y][x], want)


def gen_ships():
    MX0, MY0 = ships.MX0, ships.MY0
    for k in range(6):
        assert codes.index['LIFT%d' % k] == codes.index['LIFT0'] + k
    out = ['; generated by build.py - ships and decks',
           'MX0 equ %d' % MX0, 'MY0 equ %d' % MY0,
           'SH_NAME equ 1', 'SH_NSHAFT equ 3', 'SH_DECKS equ 7',
           'DK_W equ 0', 'DK_H equ 1', 'DK_OFF equ 2', 'DK_NDOOR equ 3', 'DK_NLIFT equ 4',
           'DK_NENER equ 5', 'DK_NCON equ 6', 'DK_NNODE equ 7', 'DK_NDROID equ 8', 'DK_NAME equ 9',
           'DK_RLE equ 11', 'DK_DOORS equ 13', 'DK_LIFTS equ 15', 'DK_ENERS equ 17', 'DK_CONS equ 19',
           'DK_NODES equ 21', 'DK_ADJ equ 23', 'DK_DROIDS equ 25', 'DK_NPROP equ 27', 'DK_PROPS equ 28',
           'SHIPTAB: dw ' + ','.join('ship_%d' % i for i in range(len(ships.SHIPS)))]
    total = 0
    for si, spec in enumerate(ships.SHIPS):
        decks = ships.make_ship(spec)
        sh = spec['shafts']
        out.append('ship_%d:' % si)
        out.append('        db %d' % len(decks))
        out.append('        dw shipname_%d' % si)
        out.append('        db %d,%s' % (len(sh), ','.join('%d' % x for x in (sh + [0, 0, 0])[:3])))
        out.append('        dw ' + ','.join('deck_%d_%d' % (si, di) for di in range(len(decks))))
        out.append('shipname_%d: %s' % (si, asm_str(spec['name'])))
        for di, d in enumerate(decks):
            p = 'd%d_%d' % (si, di)
            r, rows = encode_rows(d)
            props = [(x, y, d.K[y][x][1:]) for y in range(d.H) for x in range(d.W) if d.K[y][x][0] == 'P']
            check_deck(d, rows, props)
            total += len(r)
            assert len(d.doors) <= 24 and len(d.lifts) <= 3 and len(d.eners) <= 2 and len(d.consoles) <= 2
            out.append('deck_%d_%d:' % (si, di))
            out.append('        db %d,%d,%d,%d,%d,%d,%d,%d,%d' % (
                d.W, d.H, d.off, len(d.doors), len(d.lifts), len(d.eners), len(d.consoles),
                len(d.nodes), len(d.droids)))
            out.append('        dw %s_name,%s_rle,%s_doors,%s_lifts,%s_eners,%s_cons,%s_nodes,%s_adj,%s_droids'
                       % ((p,) * 9))
            out.append('        db %d' % len(props))
            out.append('        dw %s_props' % p)
            out.append('%s_props:' % p)
            for x, y, nm in props:
                out.append('        db %d,%d,C_%s' % (x + MX0, y + MY0, nm))
            out.append('%s_name: %s' % (p, asm_str(d.name)))
            out.append('%s_doors:' % p)
            for kind, x, y in d.doors:
                out.append('        db %d,%d,%d' % (x + MX0, y + MY0, 0 if kind == 'H' else 1))
            out.append('%s_lifts:' % p)
            for (x, y), s in zip(d.lifts, d.shaft_of):
                out.append('        db %d,%d,%d,0' % (x + MX0, y + MY0, s))
            out.append('%s_eners:' % p)
            for x, y in d.eners:
                out.append('        db %d,%d' % (x + MX0, y + MY0))
            out.append('%s_cons:' % p)
            for x, y in d.consoles:
                out.append('        db %d,%d' % (x + MX0, y + MY0))
            out.append('%s_nodes:' % p)
            out.append(db_lines([v for (x, y) in d.nodes for v in (x + MX0, y + MY0)]))
            out.append('%s_adj:' % p)
            adj = []
            for l in d.adj:
                adj += [len(l)] + l
            out.append(db_lines(adj))
            out.append('%s_droids:' % p)
            out.append(db_lines([v for (t, n) in d.droids for v in (t, n)]) or '        ; none')
            out.append('%s_rle:' % p)
            out.append(db_lines(r))
    return '\n'.join(out) + '\n', total


# ---------------------------------------------------------------- logo
LOGO_TXT = {
    'O': ['/##\\', '#..#', '#..#', '#..#', '#..#', '#..#', 'L##J'],
    'V': ['#..#', '#..#', '#..#', '#..#', '#..#', 'L\\/J', '.LJ.'],
    'E': ['/###', '#...', '#...', '###.', '#...', '#...', 'L###'],
    'R': ['###\\', '#..#', '#..#', '###J', '#.\\.', '#.L\\', '#..#'],
    'I': ['####', '.##.', '.##.', '.##.', '.##.', '.##.', '####'],
    'D': ['###\\', '#..#', '#..#', '#..#', '#..#', '#..#', '###J'],
}
LOGO_CH = {'#': 0x43, '.': 0x00, '/': 0x4E, '\\': 0x4D, 'L': 0x42, 'J': 0x56}


def gen_logo():
    word = 'OVERRIDE'
    rows = []
    for y in range(7):
        row = []
        for ch in word:
            row += [LOGO_CH[c] for c in LOGO_TXT[ch][y]] + [0]
        rows.append(row[:40])
    out = ['; generated by build.py - title logo', 'LOGO_H equ 7', 'LOGO:']
    for r in rows:
        out.append(db_lines(r, 20))
    return '\n'.join(out) + '\n'


# ---------------------------------------------------------------- output
def mzf(name, load, data, exe):
    hdr = bytearray(128)
    hdr[0] = 0x01
    fn = name.encode('ascii')[:16] + b'\x0d'
    hdr[1:1 + len(fn)] = fn
    for i in range(1 + len(fn), 18):
        hdr[i] = 0x0d
    hdr[18:20] = len(data).to_bytes(2, 'little')
    hdr[20:22] = load.to_bytes(2, 'little')
    hdr[22:24] = exe.to_bytes(2, 'little')
    return bytes(hdr) + data


def main():
    os.makedirs(BUILD, exist_ok=True)
    os.makedirs(REL, exist_ok=True)

    def write(name, text):
        with open(os.path.join(BUILD, name), 'w') as f:
            f.write(text)

    write('gen_codes.inc', gen_codes())
    write('gen_tables.inc', gen_tables())
    write('gen_roster.inc', gen_roster())
    write('gen_music.inc', music.gen_asm())
    ship_text, rle_total = gen_ships()
    write('gen_ships.inc', ship_text)
    write('gen_logo.inc', gen_logo())
    asm = os.path.join(TOOLS, 'sjasmplus', 'sjasmplus.exe')
    r = subprocess.run([asm, '--nologo', '--msg=war', '--sym=../build/override.sym',
                        '--lst=../build/override.lst', 'main.asm'],
                       cwd=SRC, capture_output=True, text=True)
    sys.stdout.write(r.stdout + r.stderr)
    if r.returncode:
        sys.exit('assembly failed')
    data = open(os.path.join(BUILD, 'override.bin'), 'rb').read()
    out = mzf(NAME, LOAD, data, LOAD)
    for d in (BUILD, REL):
        for ext in ('MZT', 'MZF'):
            with open(os.path.join(d, NAME + '.' + ext), 'wb') as f:
                f.write(out)
    print('%s: %d codes, deck maps %d bytes RLE, binary %d bytes (%04X-%04X)' % (
        NAME, len(codes.codes), rle_total, len(data), LOAD, LOAD + len(data) - 1))


if __name__ == '__main__':
    main()
