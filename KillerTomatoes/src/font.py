CHARS = {c: i for i, (c, _) in enumerate(GLYPHS)}

def enc(s):
    out = []
    for ch in s.upper():
        if ch not in CHARS:
            raise ValueError('no glyph for %r in %r' % (ch, s))
        out.append(CHARS[ch])
    return out

def font_bytes():
    # 2 bytes per glyph: 15 bits, row0 in bits 14..12 ... row4 bits 2..0 (bit2 = leftmost pixel)
    out = []
    for c, rows in GLYPHS:
        v = 0
        for r in rows:
            bits = 0
            for i, p in enumerate(r):
                if p == '#': bits |= 4 >> i
            v = (v << 3) | bits
        out += [v & 255, v >> 8]
    return out
