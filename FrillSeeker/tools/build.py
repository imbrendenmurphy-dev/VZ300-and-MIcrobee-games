BLK_SPR, BLK_GFX, BLK_ROOMC, BLK_ROOMM = 4, 8, 12, 16


def sprites():
    F = dict(hero.frames())
    F.update(critters.frames())
    banks = [bytearray()]
    L = ['; generated by tools/build.py: block, x offset, y offset, 0, four pre-shifted variants',
         '; entry = frame * 2 + facing (0 right, 1 left)']
    tab = []
    for i, (name, (ink, cut, ox, oy)) in enumerate(F.items()):
        L.append('SF_%s equ %d' % (name, i))
        for face in (0, 1):
            if face:
                ink2, cut2, ox2 = ink[:, ::-1], cut[:, ::-1], ink.shape[1] - 1 - ox
            else:
                ink2, cut2, ox2 = ink, cut, ox
            vs = art.sprite_variants(ink2, cut2)
            size = sum(len(v) for v in vs)
            if len(banks[-1]) + size > 32768:
                banks.append(bytearray())
            addrs = []
            for v in vs:
                addrs.append(len(banks[-1]))
                banks[-1] += v
            tab.append((BLK_SPR + len(banks) - 1, ox2, oy - 1, addrs))
    L.append('sprtab:')
    for blk, ox, oy, addrs in tab:
        L.append('\tdb %d,%d,%d,0\n\tdw %s' % (blk, ox & 255, oy & 255, ','.join('$%04X' % a for a in addrs)))
    open(os.path.join(SRC, 'sprtab.inc'), 'w').write('\n'.join(L) + '\n')
    for i, b in enumerate(banks):
        open(os.path.join(BUILD, 'SPR%d.BNK' % i), 'wb').write(bytes(b))
    print('sprites: %d frames, %d bytes in %d blocks' % (len(F), sum(len(b) for b in banks), len(banks)))
    return len(banks)


def dbs(vals, per=16):
    out = []
    for i in range(0, len(vals), per):
        out.append('\tdb ' + ','.join(str(int(v) & 255) for v in vals[i:i + per]))
    return out


def tables():
    L = ['; generated by tools/build.py', '\tALIGN 256',
         '; screen line + 48 -> cell row, line within the cell', 'div6tab:']
    L += dbs([(i - 48) // 6 for i in range(256)])
    L.append('mod6tab:')
    L += dbs([(i - 48) % 6 for i in range(256)])
    L.append('; playfield y -> tile row * 16, and the top line of that tile')
    L.append('row18tab:')
    L += dbs([min(9, y // 18) * 16 for y in range(256)])
    L.append('top18tab:')
    L += dbs([min(9, y // 18) * 18 for y in range(256)])
    L.append('blkport:')
    L += dbs([((n & 0x1C) << 3) | ((n & 3) ^ 2) | 4 for n in range(32)])
    L.append('bobtab:')
    L += dbs([round(3 * math.sin(i * math.pi / 8)) for i in range(16)])
    L.append('hoparc:')
    L += dbs([round(7 * math.sin((i + 0.5) * math.pi / 16)) for i in range(16)])
    L.append('eekarc:')
    L += dbs([round(22 * math.sin((i + 0.5) * math.pi / 24)) for i in range(24)])
    open(os.path.join(SRC, 'tables.inc'), 'w').write('\n'.join(L) + '\n')


def pitch(f):
    """the speaker loop's count for a frequency: a half period is 42 T a
    count plus 37"""
    d = int(round((3375000 / (2.0 * f) - 37) / 42))
    return max(1, min(254, d))


NOTE = {n: i for i, n in enumerate(['C', 'C#', 'D', 'D#', 'E', 'F', 'F#', 'G', 'G#', 'A', 'A#', 'B'])}


def hz(name):
    n, o = name[:-1], int(name[-1])
    return 440.0 * 2 ** ((NOTE[n] - 9) / 12.0 + (o - 4))


def sound():
    L = ['; generated by tools/build.py: (pitch, ticks) ... 0,0']

    def sfx(name, steps):
        L.append('%s:' % name)
        v = []
        for f, t in steps:
            v += [255 if f == 'N' else (0 if f == 0 else pitch(f)), t]
        v += [0, 0]
        L.extend(dbs(v))

    sfx('sfx_jump', [(330 + 60 * i, 1) for i in range(7)])
    sfx('sfx_land', [(110, 1), (80, 1)])
    sfx('sfx_hiss', [('N', 6), (1400, 1), ('N', 5), (0, 1), ('N', 3)])
    sfx('sfx_bug', [(1047, 2), (1319, 2), (1568, 2), (2093, 3), (1568, 1), (2093, 3)])
    sfx('sfx_hurt', [(440 - 36 * i, 1) for i in range(9)] + [('N', 3)])
    sfx('sfx_boing', [(180 + 26 * i * i, 1) for i in range(9)] + [(900, 1), (1300, 2)])
    sfx('sfx_croak', [(95, 2), (0, 1), (80, 3)])
    # the walking tune: slow blips, each a note and then its wait in ticks
    tune = [('A3', 20), ('E4', 10), ('D4', 10), ('C4', 20), ('A3', 20),
            ('G3', 20), ('C4', 10), ('D4', 10), ('E4', 20), ('E4', 20),
            ('A3', 20), ('E4', 10), ('G4', 10), ('A4', 20), ('G4', 10), ('E4', 10),
            ('D4', 20), ('C4', 10), ('D4', 10), ('A3', 40)]
    L.append('tune:')
    v = []
    for n, t in tune:
        v += [pitch(hz(n)), t]
    L.extend(dbs(v))
    L.append('\tdb $FE')
    open(os.path.join(SRC, 'snd.inc'), 'w').write('\n'.join(L) + '\n')


def build_rooms(shots=None):
    n = len(rooms.ROOMS)
    for mono, tag in ((False, 'C'), (True, 'M')):
        banks = []
        for i in range(n):
            rc = rooms.compile_room(i, mono)
            if i % 2 == 0:
                banks.append(bytearray())
            banks[-1] += rooms.room_bytes(rc)
            print('  room %d %-6s %-14s %4d glyphs + %3d living, %5d bytes of animation' % (i, 'mono' if mono else 'colour', rc['room']['name'], rc['n'], rc['ndyn'], len(rc['anim'])))
            if shots:
                art.save_png(rc['rgb'], os.path.join(shots, 'room%d%s.png' % (i, 'm' if mono else '')))
        for k, b in enumerate(banks):
            open(os.path.join(BUILD, 'ROOM%s%d.BNK' % (tag, k)), 'wb').write(bytes(b))
    return (n + 1) // 2


def loadfiles(nspr, nroom):
    names = [('STG_PROG', 0, 'FRILL', 'BIN')]
    for i in range(nspr):
        names.append((BLK_SPR + i, 0, 'SPR%d' % i, 'BNK'))
    names.append((BLK_GFX, 0, 'GFX', 'BNK'))
    for i in range(nroom):
        names.append((BLK_ROOMC + i, 0, 'ROOMC%d' % i, 'BNK'))
        names.append((BLK_ROOMM + i, 0, 'ROOMM%d' % i, 'BNK'))
    for b, o, n, e in names:
        assert b == 'STG_PROG' or 4 <= b <= 22, b      # the blocks proven safe while CP/M is alive
    lines = ['\tDB %s, $%02X, "%-8s%s"' % (b, o, n, e) for b, o, n, e in names]
    open(os.path.join(SRC, 'loadfiles.inc'), 'w').write('\n'.join(lines) + '\n')
    return names


def assemble(names):
    zasm = os.path.join(HERE, 'zasm.py')
    subprocess.check_call([sys.executable, zasm, 'main.asm', '--sym=../build/main.sym'], cwd=SRC)
    sz = os.path.getsize(os.path.join(BUILD, 'FRILL.BIN'))
    plen = (sz + 255) // 256 * 256
    open(os.path.join(SRC, 'proglen.inc'), 'w').write('PROG_LEN    EQU $%04X\n' % plen)
    print('FRILL.BIN %d bytes (8000h-%04Xh)' % (sz, 0x8000 + sz))
    subprocess.check_call([sys.executable, zasm, 'loader.asm', '--sym=../build/loader.sym'], cwd=SRC)


def disk(names):
    import build_disk as BD
    B = Path(BUILD)
    sysdisk = (Path(ROOT) / 'resources' / 'boot_tracks.bin').read_bytes()
    files = {'SAVE.DAT': b'\x1a' * 4096}
    files['FRILL.COM'] = (B / 'FRILL.COM').read_bytes()
    for b, o, n, e in names:
        files['%s.%s' % (n, e)] = (B / ('%s.%s' % (n, e))).read_bytes()
    files['CCP.SYS'] = (Path(ROOT) / 'resources' / 'CCP.SYS').read_bytes()
    readme = Path(ROOT) / 'docs' / 'DISK_README.TXT'
    if readme.exists():
        files['README.TXT'] = readme.read_text().replace('\r\n', '\n').replace('\n', '\r\n').encode('ascii') + b'\x1a'
    used = BD.build_disk(sysdisk, files, B / 'FRILL.DS8')
    print('FRILL.DS8: %d of 196 blocks used, %d files' % (used, len(files)))


if __name__ == '__main__':
    nspr = sprites()
    tables()
    sound()
    open(os.path.join(BUILD, 'GFX.BNK'), 'wb').write(font.build())
    nroom = build_rooms()
    names = loadfiles(nspr, nroom)
    assemble(names)
    disk(names)
