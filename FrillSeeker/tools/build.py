"""FRILLSEEKER: build everything into build/.   python3 tools/build.py

1. sprites (tools/hero.py, tools/critters.py): four pre-shifted copies of
   every frame, facing each way, into RAM blocks 4..
2. the font, the tables, the sound effects and the tune
3. the rooms (tools/rooms.py), colour and monochrome
4. the program (src/main.asm), the CP/M loader, the disk (build/FRILL.DS8)
"""
