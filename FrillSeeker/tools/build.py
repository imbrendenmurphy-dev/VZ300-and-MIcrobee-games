BLK_SPR, BLK_GFX, BLK_ROOMC, BLK_ROOMM, BLK_TITLE = 4, 8, 9, 15, 21


def sprites():
    F = dict(hero.frames())
    F.update(critters.frames())
    banks = [bytearray()]
    L = ['; generated by tools/build.py: block, x offset, y offset, 0, the variant table (in the block), 0',
         '; entry = frame * 2 + facing (0 right, 1 left)']
    tab = []
    for i, (name, (ink, cut, ox, oy)) in enumerate(F.items()):
        L.append('SF_%s equ %d' % (name, i))
        for face in (0, 1):
            if face:
                ink2, cut2, ox2 = ink[:, ::-1], cut[:, ::-1], ink.shape[1] - 1 - ox
            else:
                ink2, cut2, ox2 = ink, cut, ox
            vs = art.sprite_variants(ink2, cut2)
            size = 16 + sum(len(v) for v in vs)
            if len(banks[-1]) + size > 32768:
                banks.append(bytearray())
            # in the block: a table of the eight variants' addresses, then the variants
            b = banks[-1]
            table = len(b)
            b += bytes(16)
            for k, v in enumerate(vs):
                a = len(b)
                b[table + 2 * k] = a & 255
                b[table + 2 * k + 1] = a >> 8
                b += v
            tab.append((BLK_SPR + len(banks) - 1, ox2, oy - 1, table))
    L.append('sprtab:')
    for blk, ox, oy, table in tab:
        L.append('\tdb %d,%d,%d,0\n\tdw $%04X,0' % (blk, ox & 255, oy & 255, table))
    open(os.path.join(SRC, 'sprtab.inc'), 'w').write('\n'.join(L) + '\n')
    for i, b in enumerate(banks):
        open(os.path.join(BUILD, 'SPR%d.BNK' % i), 'wb').write(bytes(b))
    print('sprites: %d frames, %d bytes in %d blocks' % (len(F), sum(len(b) for b in banks), len(banks)))
    return len(banks)


def dbs(vals, per=16):
    out = []
    for i in range(0, len(vals), per):
        out.append('\tdb ' + ','.join(str(int(v) & 255) for v in vals[i:i + per]))
    return out


def tables():
    CELLMAP = 0xB800
    L = ['; generated by tools/build.py', '\tALIGN 256',
         '; cell row -> the CELLMAP address of its first cell (low bytes, then high at +32)', 'rowtab:']
    L += dbs([(CELLMAP + r * 40) & 255 for r in range(32)])
    L += dbs([(CELLMAP + r * 40) >> 8 for r in range(32)])
    L.append('; tile row -> row * 20 (same page as rowtab)')
    L.append('row20tab:')
    L += dbs([min(10, r) * 20 for r in range(16)])
    L.append('blkport:')
    L += dbs([((n & 0x1C) << 3) | ((n & 3) ^ 2) | 4 for n in range(32)])
    L.append('hoparc:')
    L += dbs([round(7 * math.sin((i + 0.5) * math.pi / 16)) for i in range(16)])
    L.append('eekarc:')
    L += dbs([round(22 * math.sin((i + 0.5) * math.pi / 24)) for i in range(24)])
    L.append('TOTAL_BUGS equ %d' % sum(''.join(r['map']).count('B') for r in rooms.ROOMS))
    R = ['; generated by tools/build.py: the regions', 'NREGIONS equ %d' % len(rooms.REGIONS)]
    R.append('reg_start:\tdb ' + ','.join(str(g['start']) for g in rooms.REGIONS))
    tot, cum = 0, []
    for g in rooms.REGIONS:
        tot += sum(''.join(rooms.ROOMS[i]['map']).count('B') for i in g['rooms'])
        cum.append(tot)
    R.append('reg_total:\tdb ' + ','.join(str(c) for c in cum))
    R.append('reg_name:\tdw ' + ','.join('rgn%d' % i for i in range(len(rooms.REGIONS))))
    for i, g in enumerate(rooms.REGIONS):
        R.append('rgn%d:\tdb "%s",0' % (i, g['name']))
    open(os.path.join(SRC, 'regions.inc'), 'w').write('\n'.join(R) + '\n')
    open(os.path.join(SRC, 'tables.inc'), 'w').write('\n'.join(L) + '\n')


def pitch(f):
    """the speaker loop's count for a frequency: a half period is 42 T a
    count plus 37"""
    d = int(round((3375000 / (2.0 * f) - 37) / 42))
    return max(1, min(254, d))


NOTE = {n: i for i, n in enumerate(['C', 'C#', 'D', 'D#', 'E', 'F', 'F#', 'G', 'G#', 'A', 'A#', 'B'])}


def hz(name):
    n, o = name[:-1], int(name[-1])
    return 440.0 * 2 ** ((NOTE[n] - 9) / 12.0 + (o - 4))


def sound():
    L = ['; generated by tools/build.py: (pitch, ticks) ... 0,0']

    def sfx(name, steps):
        L.append('%s:' % name)
        v = []
        for f, t in steps:
            v += [255 if f == 'N' else (0 if f == 0 else pitch(f)), t]
        v += [0, 0]
        L.extend(dbs(v))

    sfx('sfx_jump', [(330 + 60 * i, 1) for i in range(7)])
    sfx('sfx_land', [(110, 1), (80, 1)])
    sfx('sfx_hiss', [('N', 6), (1400, 1), ('N', 5), (0, 1), ('N', 3)])
    sfx('sfx_bug', [(1047, 2), (1319, 2), (1568, 2), (2093, 3), (1568, 1), (2093, 3)])
    sfx('sfx_hurt', [(440 - 36 * i, 1) for i in range(9)] + [('N', 3)])
    sfx('sfx_boing', [(180 + 26 * i * i, 1) for i in range(9)] + [(900, 1), (1300, 2)])
    sfx('sfx_croak', [(95, 2), (0, 1), (80, 3)])
    sfx('sfx_sprint', [('N', 2), (500, 1), (650, 1), (800, 1), (1000, 1), (1250, 2)])
    sfx('sfx_splash', [('N', 2)])
    sfx('sfx_swoop', [(2400 - 160 * i, 1) for i in range(10)])
    sfx('sfx_squawk', [('N', 2), (1800, 1), ('N', 2), (1500, 1), ('N', 2), (2000, 2)])
    sfx('sfx_goanna', [('N', 3), (70, 2), ('N', 3), (60, 3)])
    L.extend(songs())
    # the walking tune: slow blips, each a note and then its wait in ticks
    tune = [('A3', 20), ('E4', 10), ('D4', 10), ('C4', 20), ('A3', 20),
            ('G3', 20), ('C4', 10), ('D4', 10), ('E4', 20), ('E4', 20),
            ('A3', 20), ('E4', 10), ('G4', 10), ('A4', 20), ('G4', 10), ('E4', 10),
            ('D4', 20), ('C4', 10), ('D4', 10), ('A3', 40)]
    L.append('tune:')
    v = []
    for n, t in tune:
        v += [pitch(hz(n)), t]
    L.extend(dbs(v))
    L.append('\tdb $FE')
    open(os.path.join(SRC, 'snd.inc'), 'w').write('\n'.join(L) + '\n')


T_LOOP = 89          # T-states in a loop of the two-voice player


def tw(name):
    if name == '.':
        return 0
    return max(1, min(255, int(round(3375000 / (2.0 * hz(name) * T_LOOP)))))


TITLE_BARS = [
    ("G4 B4 D5 B4 G4 - A4 B4", "G"), ("C5 - E5 C5 G4 - E4 G4", "C"),
    ("A4 B4 C5 D5 A4 - F#4 A4", "D"), ("G4 - - D4 G4 - . .", "G"),
    ("E4 G4 B4 E5 D5 B4 G4 B4", "Em"), ("C5 E5 D5 C5 B4 A4 G4 E4", "C"),
    ("D4 F#4 A4 D5 C5 A4 F#4 A4", "D"), ("D5 - C5 - B4 - A4 -", "D"),
    ("E5 - E5 D5 C5 - G4 -", "C"), ("D5 - D5 C5 B4 - G4 -", "G"),
    ("A4 C5 E5 C5 A4 C5 E5 C5", "Am"), ("D5 C5 B4 A4 F#4 A4 D5 .", "D"),
    ("B4 - G4 B4 D5 - B4 D5", "G"), ("E5 D5 C5 E5 D5 C5 B4 A4", "C"),
    ("G4 A4 B4 C5 D5 - F#4 -", "D"), ("G4 - - - . . . .", "G")]
CHORDS = {'G': ('G2', 'D3'), 'C': ('C3', 'G3'), 'D': ('D3', 'A2'), 'Em': ('E2', 'B2'), 'Am': ('A2', 'E3')}


def songs():
    """the title theme (an original oom-pah strut in G) and the jingles"""
    L = []
    slots = []
    for mel, ch in TITLE_BARS:
        r, f = CHORDS[ch]
        for k, tok in enumerate(mel.split()):
            slots.append((tok, [r, '.', f, '.'][k % 4]))
    ev = []
    cur = '.'
    for i, (tok, bass) in enumerate(slots):
        if tok != '-':
            cur = tok
        nxt = slots[(i + 1) % len(slots)][0]
        ev += [tw(cur), tw(bass), 6 | (0x80 if nxt == '-' else 0)]
    L.append('song_title:')
    L.extend(dbs(ev))
    L.append('\tdb $FF')

    def jingle(name, notes):
        v = []
        for m, bs, n in notes:
            # long notes go in pieces of 8 run on, so a key is noticed
            # within 8 fiftieths
            while n > 8:
                v += [tw(m), tw(bs), 8 | 0x80]
                n -= 8
            v += [tw(m), tw(bs), n]
        L.append(name + ':')
        L.extend(dbs(v))
        L.append('\tdb $FE')
    jingle('song_clear', [('G4', 'G2', 5), ('B4', '.', 5), ('D5', 'D3', 5), ('G4', 'G2', 4), ('B4', '.', 4),
                          ('D5', 'D3', 4), ('G5', 'G2', 40)])
    jingle('song_over', [('C5', 'C3', 14), ('.', '.', 4), ('B4', 'B2', 14), ('.', '.', 4), ('A#4', 'A#2', 14),
                         ('.', '.', 4), ('A4', 'A2', 50)])
    return L


def build_rooms(shots=None):
    n = len(rooms.ROOMS)
    for mono, tag in ((False, 'C'), (True, 'M')):
        banks = []
        for i in range(n):
            rc = rooms.compile_room(i, mono)
            if i % 2 == 0:
                banks.append(bytearray())
            banks[-1] += rooms.room_bytes(rc)
            print('  room %d %-6s %-14s %4d glyphs + %3d living, %5d bytes of animation' % (i, 'mono' if mono else 'colour', rc['room']['name'], rc['n'], rc['ndyn'], len(rc['anim'])))
            if shots:
                art.save_png(rc['rgb'], os.path.join(shots, 'room%d%s.png' % (i, 'm' if mono else '')))
        for k, b in enumerate(banks):
            open(os.path.join(BUILD, 'ROOM%s%d.BNK' % (tag, k)), 'wb').write(bytes(b))
    return (n + 1) // 2


def loadfiles(nspr, nroom):
    names = [('STG_PROG', 0, 'FRILL', 'BIN')]
    for i in range(nspr):
        names.append((BLK_SPR + i, 0, 'SPR%d' % i, 'BNK'))
    names.append((BLK_GFX, 0, 'GFX', 'BNK'))
    names.append((BLK_TITLE, 0, 'TITLE', 'BNK'))
    for i in range(nroom):
        names.append((BLK_ROOMC + i, 0, 'ROOMC%d' % i, 'BNK'))
        names.append((BLK_ROOMM + i, 0, 'ROOMM%d' % i, 'BNK'))
    for b, o, n, e in names:
        assert b == 'STG_PROG' or 4 <= b <= 22, b      # the blocks proven safe while CP/M is alive
    lines = ['\tDB %s, $%02X, "%-8s%s"' % (b, o, n, e) for b, o, n, e in names]
    open(os.path.join(SRC, 'loadfiles.inc'), 'w').write('\n'.join(lines) + '\n')
    return names


def assemble(names):
    zasm = os.path.join(HERE, 'zasm.py')
    subprocess.check_call([sys.executable, zasm, 'main.asm', '--sym=../build/main.sym'], cwd=SRC)
    sz = os.path.getsize(os.path.join(BUILD, 'FRILL.BIN'))
    plen = (sz + 255) // 256 * 256
    open(os.path.join(SRC, 'proglen.inc'), 'w').write('PROG_LEN    EQU $%04X\n' % plen)
    print('FRILL.BIN %d bytes (8000h-%04Xh)' % (sz, 0x8000 + sz))
    subprocess.check_call([sys.executable, zasm, 'loader.asm', '--sym=../build/loader.sym'], cwd=SRC)


def disk(names):
    import build_disk as BD
    B = Path(BUILD)
    sysdisk = (Path(ROOT) / 'resources' / 'boot_tracks.bin').read_bytes()
    files = {'SAVE.DAT': b'\x1a' * 4096}
    files['FRILL.COM'] = (B / 'FRILL.COM').read_bytes()
    for b, o, n, e in names:
        files['%s.%s' % (n, e)] = (B / ('%s.%s' % (n, e))).read_bytes()
    files['CCP.SYS'] = (Path(ROOT) / 'resources' / 'CCP.SYS').read_bytes()
    readme = Path(ROOT) / 'docs' / 'DISK_README.TXT'
    if readme.exists():
        files['README.TXT'] = readme.read_text().replace('\r\n', '\n').replace('\n', '\r\n').encode('ascii') + b'\x1a'
    used = BD.build_disk(sysdisk, files, B / 'FRILL.DS8')
    print('FRILL.DS8: %d of 196 blocks used, %d files' % (used, len(files)))


if __name__ == '__main__':
    nspr = sprites()
    tables()
    sound()
    open(os.path.join(BUILD, 'GFX.BNK'), 'wb').write(font.build())
    nroom = build_rooms()
    tc, nc, _ = title.compile_title(False)
    tm, nm, _ = title.compile_title(True)
    open(os.path.join(BUILD, 'TITLE.BNK'), 'wb').write(tc + tm)
    print('title picture: %d glyphs colour, %d mono' % (nc, nm))
    names = loadfiles(nspr, nroom)
    assemble(names)
    disk(names)
