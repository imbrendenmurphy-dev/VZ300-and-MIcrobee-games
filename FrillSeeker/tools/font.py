HEART = ["........", ".##..##.", "###.####", "########", "########", "########", ".######.", ".######.",
         "..####..", "...##...", "...#....", "........"]
HEART0 = ["........", ".##..##.", "#..##..#", "#......#", "#......#", "#......#", ".#....#.", ".#....#.",
          "..#..#..", "...##...", "...#....", "........"]
BUG = ["........", "##....##", "###..###", ".######.", "..####..", ".#o##o#.", ".######.", "#.####.#",
       "..####..", ".#.##.#.", "........", "........"]
STRETCH = [1, 2, 1, 2, 1, 2, 1]


def glyph(ch):
    a = np.zeros((12, 8), bool)
    if ch == '[':
        rows = HEART
    elif ch == ']':
        rows = HEART0
    elif ch == '^':
        rows = BUG
    else:
        rows = None
    if rows:
        for y, r in enumerate(rows):
            for x, c in enumerate(r):
                a[y, x] = c == '#'
        return a
    src = F57.get(ch)
    if not src:
        return a
    y = 1
    for r, n in zip(src.split(','), STRETCH):
        for k in range(n):
            for x, c in enumerate(r):
                if c == '1':
                    a[y, 1 + x] = True
                    a[y, 2 + x] = True
            y += 1
    return a


def build():
    """256 glyphs x 6 bytes: letter c -> glyphs c*4 .. c*4+3 (TL, TR, BL, BR)"""
    out = bytearray()
    for c in range(64):
        a = glyph(chr(32 + c))
        b = byte_rows(a)            # (12, 2)
        for half in (0, 1):
            for col in (0, 1):
                out += bytes(int(v) for v in b[half * 6:half * 6 + 6, col])
    return bytes(out)
