def big(ink, k=2):
    return np.repeat(np.repeat(ink, k, 0), k, 1)


def crop(a):
    ys, xs = np.where(a)
    return a[ys.min():ys.max() + 1, xs.min():xs.max() + 1]


def picture(ink, col):
    """-> w, h (cells), colour glyphs, mono glyphs, colours"""
    ink = crop(ink)
    h, w = ink.shape
    H, W = (h + 7) // 8 * 8, (w + 7) // 8 * 8
    img = np.zeros((H, W), np.uint8)
    img[H - h:, (W - w) // 2:(W - w) // 2 + w][ink] = 1
    out = []
    for mono in (False, True):
        pat, i, p = cells_from_image(img * (15 if mono else col), solid=mono)
        out.append(bytes(np.asarray(pat, np.uint8).reshape(-1)))
    cols = bytes([col] * ((H // 8) * (W // 8)))
    return W // 8, H // 8, out[0], out[1], cols


def pictures():
    F = dict(hero.frames())
    F.update(critters.frames())
    hero.K = 2
    c = hero.pose(head=hero.HEAD_HISS, frill_t=1.0, lean=1.6, tailup=0.7, tail=1.8, bob=-0.6,
                  arms=((8.2, -14.0), (8.6, -15.4)), legs=((3.0, 0), (-2.8, 0)))
    hero.K = 1
    P = [('BLUFF2', picture(c.ink & ~c.cut if c.cut.shape == c.ink.shape else c.ink, YELLOW))]

    def spr(name, col, k=2):
        ink, cut, ox, oy = F[name]
        P.append((name, picture(big(ink, k), col)))
    spr('FLARE2', YELLOW, 1)
    spr('TOAD_SIT', BGREEN)
    spr('MAG_DIVE', WHITE)
    spr('GOAN0', BROWN)
    spr('BUG0', BCYAN)
    spr('TOAD_BACK0', BGREEN)
    spr('JAR', BCYAN)
    spr('GLIDE0', YELLOW, 1)
    spr('SPR2', YELLOW, 1)
    return P


def build():
    P = pictures()
    idx = {n: i for i, (n, _) in enumerate(P)}
    L = ['; generated by tools/pages.py']
    L.append('pictures:\tdw ' + ','.join('pic%d' % i for i in range(len(P))))
    tot = 0
    for i, (n, (w, h, pc, pm, cols)) in enumerate(P):
        L.append('pic%d:\tdb %d,%d\t; %s' % (i, w, h, n))
        for blob in (pc, pm, cols):
            for k in range(0, len(blob), 24):
                L.append('\tdb ' + ','.join(str(b) for b in blob[k:k + 24]))
        tot += 2 + len(pc) * 2 + len(cols)

    def text(row, s, col, at=0xFF):
        assert len(s) <= 40 and '"' not in s, s
        return '\tdb 1,%d,%d,%d,"%s",0' % (row, at, col, s)

    def pic(name, row, colm):
        return '\tdb 2,%d,%d,%d' % (idx[name], row, colm)

    def page(name, items):
        L.append(name + ':')
        L.extend(items)
        L.append('\tdb 0')

    page('pg_story', [
        text(1, 'THE STORY SO FAR', YELLOW),
        pic('BLUFF2', 5, 2),
        text(5, "KING BUFO'S CANE TOADS", WHITE, 13),
        text(7, 'HAVE PINCHED EVERY BUG', WHITE, 13),
        text(9, 'IN THE TOP END.', WHITE, 13),
        text(12, 'ONE LIZARD IS HUNGRY', BCYAN, 13),
        text(14, 'ENOUGH TO GO AND GET', BCYAN, 13),
        text(16, 'THEM BACK.', BCYAN, 13),
        text(20, 'BLUFF - ALL FRILL, NO FEAR', YELLOW),
        text(22, 'PRESS SPACE TO PLAY', BGREEN)])
    page('pg_cast', [
        text(0, "WHO'S WHO IN THE TOP END", YELLOW),
        pic('FLARE2', 3, 2), text(3, 'BLUFF', YELLOW, 12), text(5, 'OUR HERO. MOSTLY FRILL.', WHITE, 12),
        pic('TOAD_SIT', 8, 2), text(7, 'CANE TOADS', BGREEN, 12), text(9, 'FALL OVER AT A FRILL.', WHITE, 12),
        pic('MAG_DIVE', 12, 2), text(11, 'MAGPIES', BCYAN, 12), text(13, 'SWOOP. A FRILL SEES THEM OFF', WHITE, 12),
        pic('GOAN0', 16, 1), text(15, 'GOANNAS', BRED, 12), text(17, 'NOT IMPRESSED. JUMP!', WHITE, 12),
        pic('BUG0', 20, 4), text(19, 'BUGS', BCYAN, 12), text(21, 'DINNER. FIND THEM ALL.', WHITE, 12)])
    page('pg_moves', [
        text(0, 'THE MOVES', YELLOW),
        pic('FLARE2', 3, 1), text(3, 'FRILL - Q OR UP', YELLOW, 8), text(5, 'THE BLUFF. TOADS FLIP OVER.', WHITE, 8),
        pic('TOAD_BACK0', 8, 1), text(7, 'JUMP - SPACE', YELLOW, 8), text(9, 'A FLIPPED TOAD IS A TRAMPOLINE', WHITE, 8),
        pic('GLIDE0', 11, 1), text(11, 'FRILL IN THE AIR', YELLOW, 8), text(13, 'IT IS ALSO A PARACHUTE.', WHITE, 8),
        pic('SPR2', 16, 1), text(15, 'RUN - ARROWS OR O P', YELLOW, 8), text(17, 'KEEP GOING AND HE BOLTS,', WHITE, 8),
        text(19, 'RIGHT ACROSS THE WATER.', WHITE, 8),
        text(22, 'A JOYSTICK WORKS TOO', BGREEN)])
    page('pg_card', [
        text(3, 'NOW SHOWING', GREY),
        '\tdb 3,7,%d' % YELLOW,
        '\tdb 4,11,%d' % WHITE,
        pic('BUG0', 15, 12), pic('JAR', 14, 18), pic('BUG0', 15, 25),
        text(19, 'BLUFF PLAYS IT HIMSELF', BCYAN),
        text(22, 'PRESS SPACE TO PLAY', BGREEN)])
    L.append('pages:\tdw pg_story,pg_cast,pg_moves')
    n = len(rooms.REGIONS)
    L.append('reg_lines:\tdw ' + ','.join('rl%d' % i for i in range(n)))
    for i in range(n):
        assert len(REG_LINES[i]) <= 40
        L.append('rl%d:\tdb "%s",0' % (i, REG_LINES[i]))
    # the sequence: title, a page, a region; and again
    st = []
    for i in range(n * 3 if n % 3 else n):
        st += [(0, 0), (1, i % 3), (2, i % n)]
    L.append('stages:\tdb ' + ','.join('%d,%d' % s for s in st) + ',$FF,0')
    return L, tot


if __name__ == '__main__':
    L, tot = build()
    print(tot, 'bytes of pictures')
