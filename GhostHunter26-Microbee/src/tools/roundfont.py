    S = 4
    text = ["1UP 012345  HI 010000  RD 01", "GHOST HUNTER '26  MEET THE GHOSTS",
            "GRUMBLE SNEAKY DIZZY PEEKABOO", "PRESS SPACE OR FIRE TO HUNT!", "ABCDEFGHIJKLMNOPQRSTUVWXYZ",
            "0123456789 +-*/:.,()?", "WHO'S HUNTING WHO? READY!"]
    im = Image.new('RGB', (40 * 8 * S, len(text) * 10 * S), (0, 0, 0))
    for r, line in enumerate(text):
        for i, ch in enumerate(line):
            g = glyph_rows(ch)
            for y in range(10):
                for x in range(8):
                    if g[y] & (128 >> x):
                        for a in range(S):
                            for b in range(S):
                                im.putpixel(((i * 8 + x) * S + a, (r * 10 + y) * S + b), (255, 220, 60))
    im.save(sys.argv[1])
