CHARS = ' !"#$%&\'()*+,-./0123456789:;<=>?@ABCDEFGHIJKLMNOPQRSTUVWXYZ[\\]^_'


def glyph_rows(ch):
    s = G.get(ch)
    rows = [0] * 10
    if s is None:
        return rows
    rs = s.split()
    assert len(rs) == 8, ch
    for y, r in enumerate(rs):
        assert len(r) == 7, (ch, r)
        rows[1 + y] = sum(128 >> x for x, c in enumerate(r) if c == '#')
    return rows


def font_bytes():
    assert len(CHARS) == 64
    return [bytes(glyph_rows(ch)) for ch in CHARS]


