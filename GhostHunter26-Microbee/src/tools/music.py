"""GHOST HUNTER '26 music (original, VIBED BY BPM 2026) for the two-voice
pin-pulse beeper engine (frame_wait loop: 127 T at 3.375 MHz). One step of
a song is one 25 Hz frame. Every note's last frame is silent, so notes stay
separate and gritty. Writes src/music.inc."""
import os

HERE = os.path.dirname(os.path.abspath(__file__))
LOOPRATE = 3375000.0 / 127
NAMES = {'C': 0, 'C#': 1, 'D': 2, 'D#': 3, 'E': 4, 'F': 5, 'F#': 6, 'G': 7, 'G#': 8, 'A': 9, 'A#': 10, 'B': 11}


def nidx(tok):
    return (int(tok[-1]) - 1) * 12 + NAMES[tok[:-1]] + 1


def build(out):
    L = ['; generated by tools/music.py', 'notetab:']
    steps = [0]
    for i in range(1, 73):
        f = 32.703 * 2 ** ((i - 1) / 12.0)
        steps.append(int(round(f * 65536 / LOOPRATE)))
    L.append('    dw ' + ','.join(str(s) for s in steps))

    def db(bs):
        bs = list(bs)
        for i in range(0, len(bs), 16):
            L.append('    db ' + ','.join('$%02X' % b for b in bs[i:i + 16]))

    def song(name, step, *chans, loop=False):
        for ci, txt in enumerate(chans):
            ev = []
            for t in txt.split():
                if t == '-':
                    ev[-1][1] += step
                elif t == 'r':
                    ev.append([0, step])
                else:
                    ev.append([nidx(t), step])
            o = []
            for n, d in ev:
                while d > 255:
                    o += [n, 255]
                    d -= 255
                o += [n, d]
            o.append(0xFE if loop else 0xFF)
            L.append('mus_%s_%d:' % (name, ci))
            db(o)

    # title: "Who's Hunting Who?" - a low, swaggering minor-key stomp. The
    # sequencer gives every note a squelch (it starts an octave up and drops
    # onto the pitch) and the bass voice a rough edge, so nothing bleeps.
    title = """
A2 r A2 C3 r A2 D3 r  E3 r D3 C3 A2 r G2 r
A2 r A2 C3 r A2 D3 r  E3 r G3 E3 D3 - C3 r
F2 r F2 A2 r F2 C3 r  D3 r C3 A2 F2 r E2 r
E2 r E2 G#2 r B2 E3 r  D3 r B2 G#2 E2 - - r
A2 r A2 C3 r A2 D3 r  E3 r D3 C3 A2 r G2 r
A2 r C3 E3 r A3 G3 r  E3 r D3 C3 D3 - E3 r
F2 r A2 C3 r F3 E3 r  D3 r C3 A2 B2 - G#2 r
A2 r E3 r A2 r E3 D3  C3 B2 A2 r A2 - - r
"""
    bass = """
A1 r r A1 r r A1 r  A1 r r A1 G1 r G1 r
A1 r r A1 r r A1 r  A1 r r A1 C2 r B1 r
F1 r r F1 r r F1 r  F1 r r F1 E1 r E1 r
E1 r r E1 r r E1 r  E1 r r E1 G#1 r B1 r
A1 r r A1 r r A1 r  A1 r r A1 G1 r G1 r
A1 r r A1 r r A1 r  A1 r r A1 C2 r B1 r
F1 r r F1 r r F1 r  F1 r r F1 E1 r E1 r
A1 r A1 r E1 r E1 r  A1 r G1 r A1 - - r
"""
    song('title', 4, title, bass, loop=True)
    # in play: slow, suspenseful low blips ("dink ... dink-dink-dink")
    ingame = """
A2 r r r r r r r  r r r r A2 r A2 r
C3 r r r r r r r  r r r r r r r r
A2 r r r r r r r  r r r r A2 r A2 r
G#2 r r r r r r r  r r r r r r r r
"""
    ingb = """
r r r r r r r r  A1 r r r r r r r
r r r r r r r r  E1 r r r r r E1 r
r r r r r r r r  A1 r r r r r r r
r r r r r r r r  E1 r r r F1 r r r
"""
    song('game', 5, ingame, ingb, loop=True)
    # ghosts on the run: a quicker, nervous wobble
    song('fright', 3, 'E2 r G2 r E2 r A#2 r  E2 r G2 r E2 r B2 r', 'E1 r r r E1 r r r  E1 r r r G1 r r r', loop=True)
    song('hunter', 3, 'A2 C3 E3 A3 r E3 A3 r  G2 B2 D3 G3 r D3 G3 r', 'A1 r A1 r A1 r r r  G1 r G1 r G1 r r r', loop=True)
    song('ready', 4, 'A2 r C3 r E3 r A3 E3 A3 - - r', 'A1 r r r E1 r A1 r A1 - - r')
    song('clear', 4, 'A2 C3 E3 A3 r G3 A3 r C4 - A3 - C4 - - - r', 'A1 r A1 r E1 r E1 r A1 r E1 r A1 - - r')
    song('death', 4, 'A3 G#3 G3 F#3 F3 E3 D#3 D3 C#3 C3 B2 A#2 A2 - r A1 - - r', 'r r r r r r r r r r r r A1 - r E1 - - r')
    song('over', 7, 'A2 - G2 - F2 - E2 - - - A1 - - - r', 'A1 - - - F1 - - - E1 - - - A1 - - r')
    song('bonus', 3, 'E3 r E3 G3 r E3 A3 r A3 C4 r A3 E4 - - r', 'A1 r r A1 r r E1 r A1 r r A1 E1 - - r')
    song('inter', 4, """
A2 r C3 r E3 r C3 r  D3 r F3 r A3 r F3 r
E3 r G#3 r B3 r G#3 r  A3 r E3 r A2 - - r
""", """
A1 r r r E1 r r r  D1 r r r A1 r r r
E1 r r r B1 r r r  A1 r E1 r A1 - - r
""", loop=True)
    song('fame', 4, 'A2 r E3 r A3 - E3 r  F2 r C3 r F3 - C3 r  G2 r D3 r G3 - D3 r  A2 r E3 A3 E3 - - r',
         'A1 - - r r r r r  F1 - - r r r r r  G1 - - r r r r r  A1 - - r A1 - - r', loop=True)
    open(out, 'w').write('\n'.join(L) + '\n')


if __name__ == '__main__':
    build(os.path.join(HERE, '..', 'src', 'music.inc'))
