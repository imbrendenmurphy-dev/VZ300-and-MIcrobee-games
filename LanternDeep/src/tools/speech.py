"""Sampled 1-bit speech for THE LANTERN DEEP.

flite (CMU, built from source) speaks the lines; ffmpeg deepens the voice;
the result is encoded as a 1-bit delta-sigma stream at 3375000/64 =
52.7 kHz - one speaker state every 64 T-states. The speaker cone and the
TV's audio stage low-pass that bit stream back into a voice.

Output: build/AUDIO.BNK (block 11) and src/gen/speech.asm (offsets).
"""
import subprocess
import wave
from pathlib import Path
import numpy as np

ROOT = Path(__file__).resolve().parent.parent
FLITE = '/root/tools/flite/bin/flite'
TMP = Path('/tmp/claude-0')
RATE = 3375000 / 42.0             # one bit every 42 T-states (src/core.asm speak)
PHRASES = [
    ('TITLE', 'The Lantern Deep.', 'rms', 0.86),
    ('HALL', 'Beware... the drowned hall.', 'rms', 0.82),
    ('END', 'The Lantern is lit.', 'rms', 0.86),
    ('R1', 'The Ossuary.', 'rms', 0.80),
    ('R2', 'The Crystal Caverns.', 'rms', 0.84),
    ('R3', 'The Ember Halls.', 'rms', 0.80),
    ('R4', 'The Heart of the Deep.', 'rms', 0.78),
    ('KING', 'Who brings light... to my hall?', 'rms', 0.70),
]
BANKS = [(11, 'AUDIO.BNK'), (26, 'AUDIO2.BNK'), (27, 'AUDIO3.BNK'), (28, 'AUDIO4.BNK'), (29, 'AUDIO5.BNK')]
LIMIT = 0x8000


def synth(text, voice, pitch):
    raw = TMP / 'sp_raw.wav'
    out = TMP / 'sp_proc.wav'
    subprocess.run([FLITE, '-voice', voice, '-t', text, '-o', str(raw)], check=True)
    # lower the voice, add a little stone-hall echo, resample
    af = ('asetrate=16000*%.2f,aresample=16000,highpass=f=180,lowpass=f=3400,'
          'aecho=0.8:0.6:60|110:0.25|0.15,acompressor=threshold=0.1:ratio=6:attack=5:release=60,'
          'aresample=%d' % (pitch, int(RATE)))
    subprocess.run(['ffmpeg', '-loglevel', 'error', '-y', '-i', str(raw), '-af', af, '-ac', '1', str(out)], check=True)
    with wave.open(str(out)) as w:
        x = np.frombuffer(w.readframes(w.getnframes()), dtype=np.int16).astype(np.float64)
    x /= max(1.0, np.abs(x).max())
    # trim silence
    idx = np.where(np.abs(x) > 0.02)[0]
    x = x[max(0, idx[0] - 200):idx[-1] + 2000]
    return x


def gate(x):
    """1 where the voice is speaking, 0 in the pauses (20 ms hangover).
    A delta-sigma stream never stops toggling, even for silence, and a
    real speaker turns that idle pattern into hiss; in the pauses the
    speaker is now simply left off."""
    w = int(RATE * 0.010)
    env = np.convolve(np.abs(x), np.ones(w) / w, mode='same')
    on = env > 0.045 * env.max()
    hang = int(RATE * 0.020)
    g = np.convolve(on.astype(float), np.ones(2 * hang + 1), mode='same') > 0
    return g


def delta_sigma(x):
    """2nd-order delta-sigma modulator -> bits (1 = speaker on); silent
    (speaker off, no toggling) wherever the voice pauses"""
    g = gate(x)
    x = np.clip(x * 0.85, -0.95, 0.95)
    i1 = i2 = 0.0
    y = -1.0
    bits = np.zeros(len(x), dtype=np.uint8)
    for n, s in enumerate(x):
        if not g[n]:
            i1 = i2 = 0.0
            y = -1.0
            continue
        i1 += s - y
        i2 += i1 - y
        y = 1.0 if i2 >= 0 else -1.0
        bits[n] = 1 if y > 0 else 0
    return bits


def main():
    blobs = [bytearray() for _ in BANKS]
    asm = ['; generated by tools/speech.py']
    lines = []
    for name, text, voice, pitch in PHRASES:
        x = synth(text, voice, pitch)
        bits = delta_sigma(x)
        pad = (-len(bits)) % 2048                 # whole 256-byte pages (speaker off)
        bits = np.concatenate([bits, np.zeros(pad, dtype=np.uint8)])
        lines.append((name, np.packbits(bits).tobytes(), len(bits) / RATE))
    # pack the banks: largest lines first, each into the first bank with room
    for name, data, secs in sorted(lines, key=lambda l: -len(l[1])):
        bi = next(i for i in range(len(BANKS)) if len(blobs[i]) + len(data) <= LIMIT)
        asm.append('SPEECH_%s EQU $%04X' % (name, len(blobs[bi])))
        asm.append('SPEECH_%s_LEN EQU %d' % (name, len(data)))
        asm.append('SPEECH_%s_BLK EQU %d' % (name, BANKS[bi][0]))
        blobs[bi] += data
        print('%s: %.2f s, %d bytes, block %d' % (name, secs, len(data), BANKS[bi][0]))
    for (blk, fn), blob in zip(BANKS, blobs):
        (ROOT / 'build' / fn).write_bytes(bytes(blob) or b'\0')
    (ROOT / 'src' / 'gen' / 'speech.asm').write_text('\n'.join(asm) + '\n')
    blob = blobs[0]
    # check: low-pass the bit stream back to audio
    b = np.unpackbits(np.frombuffer(bytes(blob), dtype=np.uint8)).astype(np.float64) * 2 - 1
    k = np.ones(12) / 12
    y = np.convolve(b, k, mode='same')[::6]
    y = (y / np.abs(y).max() * 20000).astype(np.int16)
    with wave.open(str(ROOT / 'out' / 'speech_check.wav'), 'wb') as w:
        w.setnchannels(1)
        w.setsampwidth(2)
        w.setframerate(int(RATE / 6))
        w.writeframes(y.tobytes())


if __name__ == '__main__':
    main()
