"""Where SAVE.DAT lives on the DS8 (it is always the first file, blocks 1-2),
as (track, side, sector ID) for the game's disk driver: src/gen/savemap.asm.

Layout as build_disk.py writes it and as the Microbee BIOS reads it:
directory at track-side 4 (offset 20480), 4K blocks, 10 x 512-byte sectors
per track-side, track-sides alternating side 0 / side 1, logical sector s
stored as physical sector SKEW[s], sector IDs 21-30 from track 2 on."""
from pathlib import Path
ROOT = Path(__file__).resolve().parent.parent
SKEW = [1, 4, 7, 0, 3, 6, 9, 2, 5, 8]
SAVE_BLOCK = 1
SAVE_SECTORS = 11            # header + 10 sectors of explored-room bits


def sectors():
    out = []
    for k in range(SAVE_SECTORS):
        off = 20480 + SAVE_BLOCK * 4096 + k * 512
        ts, s = off // 5120, (off % 5120) // 512
        track, side = ts // 2, ts % 2
        assert track >= 2
        out.append((track, side, SKEW[s] + 21))
    return out


if __name__ == '__main__':
    lines = ['; generated by tools/savemap.py', 'SAVE_NSECT EQU %d' % SAVE_SECTORS, 'SAVE_SECT:']
    for t, sd, i in sectors():
        lines.append('    DB %d,%d,%d' % (t, sd, i))
    (ROOT / 'src' / 'gen' / 'savemap.asm').write_text('\n'.join(lines) + '\n')
    print('SAVE.DAT sectors', sectors())
