def glyph_bytes(ch):
    rows = G.get(ch, G['?'])
    out = []
    for r in rows:
        v = 0
        for i, c in enumerate(r):
            if c == '#':
                v |= 0x80 >> i
        out.append(v)
    return out


ORDER = [chr(c) for c in range(32, 96) if chr(c) in G]


def font_index():
    """glyph number for each character 32..95 (unknown -> space)"""
    return [ORDER.index(chr(c)) if chr(c) in G else 0 for c in range(32, 96)]


def font_bytes():
    out = []
    for ch in ORDER:
        out += glyph_bytes(ch)
    return out
