"""Build VZ-ED: out/VZED.VZ (run from VZ-DECK) and out/PLAYTXT.VZ (VZ-DECK plug-in for .TXT).
Needs Python 3 only.  The assembler is tools/zasm.py."""
import os, sys, subprocess, zlib
OVERLAYS = ['ovl_help', 'ovl_sheet', 'ovl_menu']   # slots 0, 1, 2
HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, HERE)
import gen

def build():
    gen.gen_vars(); gen.gen_tables()
    os.makedirs(os.path.join(ROOT, 'out'), exist_ok=True)
    binf = os.path.join(ROOT, 'out', 'vzed.bin'); symf = os.path.join(ROOT, 'out', 'vzed.sym')
    r = subprocess.run([sys.executable, os.path.join(ROOT, 'tools', 'zasm.py'), 'vzed.asm',
                        '-o', binf, '--sym', symf, '--lst', os.path.join(ROOT, 'out', 'vzed.lst'),
                        '--start', '0x9000'], cwd=HERE, capture_output=True, text=True)
    print(r.stdout.strip(), r.stderr.strip())
    if r.returncode or 'ERROR' in r.stdout: sys.exit(1)
    sym = {}
    for line in open(symf):
        a, n = line.split(); sym[n] = int(a, 16)
    img = open(binf, 'rb').read()               # out/vzed.bin starts at $9000
    # the file: code $A000..code_end, then the tail (tables, font, messages) that
    # start-up copies down to tail..tail_end
    code = bytearray(img[0xA000 - 0x9000:sym['code_end'] - 0x9000]
                     + img[sym['tail'] - 0x9000:sym['tail_end'] - 0x9000])
    assert code[3] == 0
    # overlays (0.3): assembled one by one against the main symbols, 3K slots in VZED.OVL.
    # The build id (a checksum of the program) goes into ovl_id and into each slot, so a
    # VZED.OVL from another build is refused instead of crashing.
    bid = (zlib.crc32(bytes(code)) & 0xFFFF) or 1
    ia = sym['ovl_id'] - sym['tail'] + (sym['code_end'] - 0xA000)
    assert code[ia] == 0 and code[ia + 1] == 0
    code[ia] = bid & 255; code[ia + 1] = bid >> 8
    open(os.path.join(HERE, 'mainsym.inc'), 'w').write(
        '; generated by build.py from out/vzed.sym - do not edit\n' +
        ''.join('%s equ $%04X\n' % (n, v) for n, v in sym.items() if '.' not in n))
    slot = sym['OVLSEC'] * 512
    ovl = bytearray()
    for name in OVERLAYS:
        ob = os.path.join(ROOT, 'out', name + '.bin')
        r = subprocess.run([sys.executable, os.path.join(ROOT, 'tools', 'zasm.py'), name + '.asm',
                            '-o', ob, '--lst', os.path.join(ROOT, 'out', name + '.lst'), '--sym', os.path.join(ROOT, 'out', name + '.sym'),
                            '--start', '0x%X' % sym['OVLA']], cwd=HERE, capture_output=True, text=True)
        if r.returncode or 'ERROR' in r.stdout:
            print(r.stdout.strip(), r.stderr.strip()); sys.exit(1)
        body = bytearray(open(ob, 'rb').read())
        assert len(body) <= slot, (name, len(body))
        body[0] = bid & 255; body[1] = bid >> 8
        print('overlay %d %s: %d bytes' % (len(ovl) // slot, name, len(body)))
        ovl += body + bytes(slot - len(body))
    open(os.path.join(ROOT, 'out', 'VZED.OVL'), 'wb').write(ovl)
    def vz(name, body):
        return b'VZF0' + name.encode().ljust(17, b'\0') + b'\xf1' + bytes([0x00, 0xA0]) + bytes(body)
    open(os.path.join(ROOT, 'out', 'VZED.VZ'), 'wb').write(vz('VZ-ED', code))
    plug = bytearray(code); plug[3] = 1
    open(os.path.join(ROOT, 'out', 'PLAYTXT.VZ'), 'wb').write(vz('VZ-ED', plug))
    print('code $A000-$%04X, tail $%04X-$%04X, file %d bytes, text buffer $%04X-$F5FF (%d bytes)' % (
        sym['code_end'] - 1, sym['tail'], sym['tail_end'] - 1, len(code), sym['BUFS'], 0xF600 - sym['BUFS']))
    return sym

if __name__ == '__main__':
    build()
