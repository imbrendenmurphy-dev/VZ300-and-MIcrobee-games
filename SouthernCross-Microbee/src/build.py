#!/usr/bin/env python3
"""Generate tables/panel/variables, append to scross.asm and assemble -> SCROSS.COM"""
import math, subprocess, sys, os
here = os.path.dirname(os.path.abspath(__file__))

# ---- panel layout (rows 8-15, 64 columns) ----
rows = [
    " SOUTHERN CROSS  STAGE 1 FLIGHT ENGINE TEST    VIBED BY BPM 2026",
    "-" * 64,
    " AIRSPEED {IAS:3} KT    ALTITUDE {ALT:5} FT    HEADING {HDG:3}",
    " THROTTLE {THR:3} %     CLIMB  {VS:6} FT/M   PITCH  {PIT:4}",
    " STATUS   {STAT:12}  GROUND  {GS:3} KT      BANK   {BNK:4}",
    "-" * 64,
    " Q/A NOSE DOWN/UP  O/P BANK  T/G THROTTLE  SPACE LEVEL  D DETAIL",
    " R RUNWAY  F FINAL APPROACH   DETAIL {DET:1}   FPS {FPS:2}   FRAMES {FRM:5}",
]
import re
text = []
fields = {}
for r, row in enumerate(rows):
    out = ''
    i = 0
    for m in re.finditer(r'\{(\w+):(\d+)\}', row):
        out += row[i:m.start()]
        fields[m.group(1)] = (r * 64 + len(out) + 512, int(m.group(2)))
        out += ' ' * int(m.group(2))
        i = m.end()
    out += row[i:]
    out = out[:64].ljust(64)
    text.append(out)
paneltext = ''.join(text)
assert len(paneltext) == 512

gen = []
gen.append('; ---- generated by build.py ----')
for k, (off, w) in fields.items():
    gen.append('F_%-6s equ %d' % (k, off))
gen.append('paneltext:')
for r in range(8):
    s = paneltext[r*64:(r+1)*64].replace('"', "'")
    gen.append('        db "%s"' % s)
gen.append('        align 256')
gen.append('sintab:')
vals = [int(round(127 * math.sin(2 * math.pi * i / 256))) for i in range(256)]
for i in range(0, 256, 16):
    gen.append('        db ' + ','.join(str(v & 0xff) for v in vals[i:i+16]))

# ---- variables ----
vars_ = [
 ('savsp',2),('front',1),('backbank',1),('backscr',2),
 ('pin',1),('rin',1),('lvl',1),('thr',1),
 ('pxf',1),('px',2),('pzf',1),('pz',2),('altf',1),('alt',2),
 ('vel',2),('pitch',2),('roll',2),('hdg',2),('vs',2),('gs',2),
 ('ongnd',1),('crashed',1),('stall',1),('sinp',1),('cosp',1),('cosr',1),
 ('msgn',1),('dsgn',1),('ticks',1),('fps',1),('secfr',1),('frames',2),
 ('sh',1),('ch',1),('spp',1),('cpp',1),('sr',1),('cr',1),('u0',1),('u2',1),
 ('m00',1),('m10',1),('m20',1),('m01',1),('m11',1),('m21',1),('m02',1),('m12',1),('m22',1),
 ('nege',2),('cyr',2),('cyu',2),('cyf',2),('acv',2),
 ('tx',2),('ty',2),('tz',2),('vr',2),('vu',2),('vf',2),
 ('cvr',2),('cvu',2),('cvf',2),('svec',6),('lvec',6),('scount',1),
 ('sega',6),('segb',6),('ncdst',2),('nlo',6),('nhi',6),('nmid',6),
 ('pr',2),('fr',2),('fu',2),('ff',2),('ffh',2),('frh',2),('fca',1),('hA',6),('hB',6),('hD',9),('dsg',1),('isrc',2),('hT',6),('dA',10),('dB',10),('dT',10),('lcA',1),('lcB',1),('lbm',1),('lbpa',2),('lbpb',2),('tmin',2),('tmax',2),('sega0',6),('hdd',2),('hr',2),('hu',2),('hf',2),('hq',2),('hq2',2),('spx0',2),('spx1',2),('xrow',1),('rnga',8),('rngb',8),('rngback',2),('cbank',1),('xacc',1),('hfull',1),('hnear',2),('efp',2),('efq',2),('efe',2),('efy',2),('eqx',2),('eqy',2),('efd',2),('efn',2),('efo',2),('efy2',2),('efq2',2),('hcode',1),('itt',2),('idst',2),('ioff',2),('icnt',1),('fcb',1),('gr',2),('gu',2),('glim',2),('gca',1),('gmask',1),('gcnt',1),('vblast',1),('fields',1),('lastfr',1),('fsec',1),('detail',1),('m11h',1),('vcnt',1),('vidx',1),('ea',1),('eb',1),('axx',24),('axy',24),('axz',24),('vbuf',96),('vcode',16),('vproj',64),('dkey',1),('pu',2),('pf',2),('psx',2),
 ('ht0',2),('ht1',2),('hden',2),
 ('cx0',2),('cy0',2),('cx1',2),('cy1',2),('mx',2),('my',2),('smx',2),('smy',2),
 ('six',2),('siy',2),('sox',2),('soy',2),('oc0',1),('oc1v',1),('cstkp',2),
 ('gH',2),('gd',2),('gcolh',2),('gfcnt',1),('gnh',2),('gnd',2),('ga',1),('gb',1),('gpp',2),('gqp',2),('gnp',2),('gci',1),
 ('gN',6),('gvok',1),('gvx',2),('gvy',2),('gvf',1),('gvu',1),('gcl0',1),('gcl1',1),('gq',2),('hzfl',1),('gT',2),('gg0',2),('gg1',2),('gmp',2),('gfr',1),('hzy0',2),('hzy1',2),
 ('ldx',2),('lady',1),('curbank',1),('lmask',1),('xout',1),('numbuf',6),
]
gen.append('        align 256')
gen.append('sqtab:')                       # floor(i*i/4): low bytes page, high bytes page
sq = [i * i // 4 for i in range(256)]
for part in (0, 1):
    v = [(x >> (8 * part)) & 255 for x in sq]
    for i in range(0, 256, 16):
        gen.append('        db ' + ','.join(str(x) for x in v[i:i+16]))
gen.append('vars:')
for n, s in vars_:
    gen.append('%-10s ds %d' % (n, s))
gen.append('cstk       ds 64*8')
gen.append('cstkend    equ $')
gen.append('progend    equ $')

src = open(os.path.join(here, 'scross.asm')).read().replace('        include_ggrid\n', open(os.path.join(here, 'ggrid.inc')).read()) + '\n' + '\n'.join(gen) + '\n'
full = os.path.join(here, 'build', 'scross_full.asm')
os.makedirs(os.path.join(here, 'build'), exist_ok=True)
open(full, 'w').write(src)
r = subprocess.run([sys.executable, os.path.join(here, 'tools', 'z80asm.py'), full,
                    os.path.join(here, 'build', 'SCROSS.COM'), os.path.join(here, 'build', 'scross.lst')],
                   capture_output=True, text=True)
print(r.stdout, r.stderr)
if r.returncode:
    sys.exit(r.returncode)

# ---- bootable DS80 disk image (system tracks + CCP.SYS from the earlier Premium disks)
sys.path.insert(0, os.path.join(here, 'tools'))
import build_disk as BD
res = os.path.join(here, 'resources')
files = {
    'SCROSS.COM': open(os.path.join(here, 'build', 'SCROSS.COM'), 'rb').read(),
    'CCP.SYS': open(os.path.join(res, 'CCP.SYS'), 'rb').read(),
}
rd = os.path.join(here, '..', 'docs', 'DISK_README.TXT')
if os.path.exists(rd):
    files['README.TXT'] = open(rd).read().replace('\r\n', '\n').replace('\n', '\r\n').encode('ascii') + b'\x1a'
used = BD.build_disk(open(os.path.join(res, 'boot_tracks.bin'), 'rb').read(), files,
                     os.path.join(here, 'build', 'SCROSS.DS8'))
print('SCROSS.DS8: %d of 196 blocks used' % used)
