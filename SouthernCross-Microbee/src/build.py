#!/usr/bin/env python3
"""Generate tables/panel/variables, append to scross.asm and assemble -> SCROSS.COM"""
import math, subprocess, sys, os
here = os.path.dirname(os.path.abspath(__file__))

# ---- panel layout (rows 8-15, 64 columns) ----
rows = [
    " SOUTHERN CROSS  STAGE 3  {LOC:16}  VIBED BY BPM 2026",
    "-" * 64,
    " AIRSPEED {IAS:3} KT    ALTITUDE {ALT:5} FT    HEADING {HDG:3}",
    " THROTTLE {THR:3} %     CLIMB  {VS:6} FT/M   PITCH  {PIT:4}",
    " STATUS   {STAT:12}  GROUND  {GS:3} KT      BANK   {BNK:4}  {FPS:2} FPS",
    " {RWN:12} {RNG:5} M TO AIM  PAPI {PAPI:4} {GLD:9} {LIN:13}",
    " {MSG:62}",
    " Q/A NOSE O/P BANK T/G POWER SPC LEVEL R RWY F FINAL N NEXT D{DET:1}",
]
import re
text = []
fields = {}
for r, row in enumerate(rows):
    out = ''
    i = 0
    for m in re.finditer(r'\{(\w+):(\d+)\}', row):
        out += row[i:m.start()]
        fields[m.group(1)] = (r * 64 + len(out) + 512, int(m.group(2)))
        out += ' ' * int(m.group(2))
        i = m.end()
    out += row[i:]
    assert len(out) <= 64, (len(out), out)
    out = out.ljust(64)
    text.append(out)
paneltext = ''.join(text)
assert len(paneltext) == 512

# ---- locale files (assembled to load at LOCBUF), HOME embedded as the fallback
import areas as LC
LOCBUF = 0x5000; LOCEND = 0x7A00
os.makedirs(os.path.join(here, 'build'), exist_ok=True)
locbin = {}
for key, fn in LC.LOCALES.items():
    src_l = os.path.join(here, 'build', key + '.asm')
    open(src_l, 'w').write(fn().asm(LOCBUF))
    out_l = os.path.join(here, 'build', key + '.LOC')
    r = subprocess.run([sys.executable, os.path.join(here, 'tools', 'z80asm.py'), src_l, out_l], capture_output=True, text=True)
    if r.returncode:
        print(r.stdout, r.stderr); sys.exit(1)
    locbin[key] = open(out_l, 'rb').read()
    assert LOCBUF + len(locbin[key]) <= LOCEND, key
    print('%s.LOC: %d bytes' % (key, len(locbin[key])))

gen = []
gen.append('; ---- generated by build.py ----')
for k, (off, w) in fields.items():
    gen.append('F_%-6s equ %d' % (k, off))
gen.append('paneltext:')
for r in range(8):
    s = paneltext[r*64:(r+1)*64].replace('"', "'")
    gen.append('        db "%s"' % s)
gen.append('        align 256')
gen.append('sintab:')
vals = [int(round(127 * math.sin(2 * math.pi * i / 256))) for i in range(256)]
for i in range(0, 256, 16):
    gen.append('        db ' + ','.join(str(v & 0xff) for v in vals[i:i+16]))

