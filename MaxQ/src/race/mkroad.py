"""Builds road.asm: the pieces of the old engine that the raster road still uses + road_new.asm."""
L = open('engine.asm').read().split('\n')
def between(a, b):
    i = next(n for n, l in enumerate(L) if l.startswith(a))
    j = next(n for n, l in enumerate(L) if n > i and l.startswith(b))
    return L[i:j]
out = ['; ROAD.ASM - MAX Q raster road (generated by mkroad.py from engine.asm + road_new.asm)']
out += between('sext:', 'neg16:')
out += between('; quarter-square signed multiply', '; HL = HL / DE')
comp = between('compose:', '; gates: solid colour-3')
i = next(n for n, l in enumerate(comp) if 'push de                 ; speed stripes' in l)
j = next(n for n, l in enumerate(comp) if l.strip().startswith('ld iy,c2back'))
k = next(n for n, l in enumerate(comp) if l.startswith('.s5:'))
comp = comp[:i] + comp[j:]
comp[k:k + 1] = ['.s5:    ld c,a', '        ld a,(SPLITMODE)        ; a sky gradient moves with the horizon: draw it all',
                 '        dec a', '        ld a,c', '        jr nz,.s6', '        ld a,TOPROW', '.s6:    ld (crow),a']
out += comp[:-2]
out += between('; rect colour:', 'draw_gates:')
out += between('; rect: biased coords', '; MAKE_SKY_TOP')[:-1]
out += L[next(n for n, l in enumerate(L) if l.startswith('; MAKE_SKY_TOP')) - 1:]
out += open('road_new.asm').read().split('\n')
open('road.asm', 'w').write('\n'.join(out) + '\n')
