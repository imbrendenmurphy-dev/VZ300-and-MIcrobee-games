#!/usr/bin/env python3
"""ASTEROIDS II title music -> src/music.inc
Row = 3 bytes (ch0 bass, ch1 lead, ch2 drums/chord stabs), 16 rows per pattern.
byte: 0 nothing, 1..71 note (index from C2 = 1), $FE cut,
      $F1 kick, $F2 snare, $F3 hat, ch2: 1..71 minor chord arp, 101..171 major (note+100)."""
import os
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
NAMES = {'C':0,'C#':1,'D':2,'D#':3,'E':4,'F':5,'F#':6,'G':7,'G#':8,'A':9,'A#':10,'B':11}
def n(s):
    s = s.strip()
    if s in ('.', ''): return 0
    if s == '-': return 0xFE
    name, octv = s[:-1], int(s[-1])
    return (octv-2)*12 + NAMES[name] + 1

KICK, SNARE, HAT = 0xF1, 0xF2, 0xF3
def drums_with_chord(root, major, fill=False):
    """ch2 lane: kick/snare/hats on even rows, chord stabs on odd rows"""
    out = []
    for r in range(16):
        if r in (0, 8) or (fill and r in (10, 14)): out.append(KICK)
        elif r in (4, 12): out.append(SNARE)
        elif r % 2 == 0: out.append(HAT)
        else: out.append(n(root) + (100 if major else 0) if r in (3, 7, 11, 15) else 0)
    return out

def bass(root):
    r = n(root); o = r + 12
    return [r,0,o,0, r,0,o,0, r,0,o,0, r,0,o,0]

def lead(s):
    toks = s.split()
    assert len(toks) == 16, s
    return [n(t) for t in toks]

CH = {'Am':('A2',False), 'F':('F2',True), 'C':('C3',True), 'G':('G2',True),
      'Dm':('D3',False), 'E':('E2',True), 'Em':('E2',False)}
CHORD_OCT = {'A2':'A3','F2':'F3','C3':'C4','G2':'G3','D3':'D4','E2':'E3'}

def pattern(chord, melody=None, fill=False):
    root, major = CH[chord]
    b = bass(root)
    l = lead(melody) if melody else [0]*16
    d = drums_with_chord(CHORD_OCT[root], major, fill)
    return [x for r in range(16) for x in (b[r], l[r], d[r])]

M = {
 'Am1': 'A4 . C5 . E5 . A5 . G5 . E5 . C5 . D5 .',
 'F1':  'C5 . A4 . F4 . A4 . C5 . F5 . E5 . C5 .',
 'C1':  'E5 . G5 . C5 . G4 . E5 . D5 . C5 . B4 .',
 'G1':  'D5 . B4 . G4 . B4 . D5 . G5 . F5 . D5 .',
 'Am2': 'A4 . . A4 C5 . E5 . D5 . C5 . B4 . C5 .',
 'G2':  'D5 . B4 . G4 . . . G5 - F5 . E5 . D5 .',
 'Dm':  'F5 . E5 . D5 . A4 . D5 . F5 . A5 . F5 .',
 'AmB': 'E5 . C5 . A4 . C5 . E5 . A5 . G5 . E5 .',
 'E1':  'G#4 . B4 . E5 . G#5 . B5 . G#5 . E5 . B4 .',
 'E2':  'E5 . - . D5 . - . C5 . - . B4 . G#4 .',
}
pats = []
def P(*a, **k): pats.append(pattern(*a, **k)); return len(pats)-1
intro = [P('Am'), P('Am', fill=True)]
a1 = [P('Am', M['Am1']), P('F', M['F1']), P('C', M['C1']), P('G', M['G1'])]
a2 = [P('Am', M['Am2']), P('F', M['F1']), P('C', M['C1']), P('G', M['G2'], fill=True)]
b  = [P('Dm', M['Dm']), P('Am', M['AmB']), P('E', M['E1']), P('E', M['E2'], fill=True)]
order = intro + a1 + a2 + b + a1 + [0xFF]
loop_at = len(intro)

with open(os.path.join(ROOT, 'music.inc'), 'w') as f:
    f.write('; generated by tools/gen_music.py\n')
    f.write('mus_order_tab:\n    db ' + ','.join(str(x) for x in order) + '\n')
    f.write('MUS_LOOP equ %d\n' % loop_at)
    f.write('mus_pat_tab:\n' + '\n'.join('    dw mus_p%d' % i for i in range(len(pats))) + '\n')
    for i, p in enumerate(pats):
        f.write('mus_p%d:\n' % i)
        for r in range(0, 48, 12):
            f.write('    db ' + ','.join('$%02X' % x for x in p[r:r+12]) + '\n')
print('patterns', len(pats), 'bytes', len(pats)*48 + len(order))
