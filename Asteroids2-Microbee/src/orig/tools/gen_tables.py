import math, os
ROOT=os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
o=[]
sx=[round(math.sin(i*2*math.pi/64)*127) for i in range(64)]
cy=[round(-math.cos(i*2*math.pi/64)*127*2/3) for i in range(64)]
def db(n,v): o.append(n+':\n'+'\n'.join('    db '+','.join(str(x&255) for x in v[i:i+16]) for i in range(0,len(v),16)))
db('sinx',sx); db('cosy',cy)
# note frequency table (freq word = Hz*65536/16574), MIDI-ish from C2 (index 0) to B7
fs=3546894/214
nt=[]
for n in range(72):
    hz=65.406*2**(n/12); nt.append(min(65535,round(hz*65536/fs)))
o.append('note_frq:\n'+'\n'.join('    dw '+','.join(str(x) for x in nt[i:i+12]) for i in range(0,72,12)))
open(os.path.join(ROOT,'tables.inc'),'w').write('; generated by tools/gen_tables.py\n'+'\n'.join(o)+'\n')
print('ok')
