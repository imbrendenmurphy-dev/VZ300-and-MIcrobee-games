"""Build ASTEROIDS II for the Microbee Premium Plus -> build/AST2.DS8

  python3 tools/build.py [--base base.DS8]

Steps: simulation sources from the original VZ code (port_sim), artwork
(art), sprite compiler (sprc), assemble engine / simulation / loader (zasm),
then a DS80 CP/M disk (system tracks + CCP.SYS copied from the base disk).
"""
import argparse, json, struct, sys
from pathlib import Path
R = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(R / 'tools'))
import art, sprc, port_sim, zasm, disk

ART_BLOCK0 = 8
NEXT_BANK = 0x8006


def blk_port(b):
    return ((b & 0x1C) << 3) | ((b & 3) ^ 2) | 4      # ROMs off, video at F000


def compile_art():
    sprites = art.build()
    banks = [bytearray()]
    recs = []
    cache = {}
    for name, pix, mask, opaque in sprites:
        h, w = pix.shape
        single = name in art.TOPLEFT
        variants = []
        for s in range(4):
            if single and s:
                variants.append(variants[0]); continue
            cols, cdata = sprc.variant_columns(pix, mask, opaque, s * 2)
            if single:
                cols = (w + 7) // 8
                cdata = cdata[:cols]
            code = bytearray(); sp = bytearray()
            for i, (pb, mb) in enumerate(cdata):
                if i:
                    code += bytes([0x69, 0x24, 0xCC, NEXT_BANK & 255, NEXT_BANK >> 8])
                code += sprc.compile_column(pb, mb, opaque)
                a, n = sprc.spans(pb, mb, opaque)
                assert n <= 64, (name, n)
                sp += bytes([a, (0x80 - 2 * n) & 255])    # erase_chain entry (low byte)
            code += b'\xC9'
            blob = bytes(code + sp)
            if blob not in cache:
                if len(banks[-1]) + len(blob) > 32768:
                    banks.append(bytearray())
                cache[blob] = (len(banks) - 1, len(banks[-1]))
                banks[-1] += blob
            bi, addr = cache[blob]
            variants.append((blk_port(ART_BLOCK0 + bi), addr, addr + len(code)))
        hw, hh = (0, 0) if single else (w // 2, h // 2)
        recs.append((name, cols, h, hw, hh, variants))
    assert ART_BLOCK0 + len(banks) <= 15, 'art must fit blocks 8-14 (block 15 stages the program)'
    return sprites, banks, recs


def write_incs(recs):
    I = art.INDEX
    ids = ['; generated by tools/build.py']
    for k in ('bullet', 'dot'):
        ids.append('SPR_%s equ %d' % (k.upper(), I[k]))
    ids.append('SPR_FLAME equ %d' % I['flame0_0'])
    ids.append('SPR_RING equ %d' % I['ring0'])
    ids.append('SPR_LOGO equ %d' % I['logo0'])
    ids.append('SPR_COUNT equ %d' % len(recs))
    # sanity: same numbering as the original VZ sprite set
    assert I['ship0'] == 0 and I['shield0'] == 32 and I['rock_STONE_L_0'] == 34
    assert I['saucer0'] == 114 and I['jewel_TOPAZ_0'] == 128 and I['pick_SHIELD_0'] == 140 and I['ring0'] == 150
    (R / 'src/spr-ids.inc').write_text('\n'.join(ids) + '\n')
    gl = []
    for code in range(32, 96):
        ch = chr(code)
        gl.append(I.get('glyph_' + ch, 0))
    (R / 'src/sim-glyphs.inc').write_text('glyph_map:\n' + ''.join(
        '        db ' + ','.join(map(str, gl[i:i + 16])) + '\n' for i in range(0, 64, 16)))
    out = ['; generated by tools/build.py - sprite records', 'spr_ptr:']
    for i in range(0, len(recs), 8):
        out.append('        dw ' + ','.join('spr_%d' % j for j in range(i, min(i + 8, len(recs)))))
    for i, (name, cols, h, hw, hh, v) in enumerate(recs):
        out.append('spr_%d: ; %s' % (i, name))
        out.append('        db %d,%d,%d,%d' % (cols, h, hw, hh))
        for port, code, spans in v:
            out.append('        db $%02X : dw $%04X,$%04X' % (port, code, spans))
    (R / 'src/sprites.inc').write_text('\n'.join(out) + '\n')
    # front-end lists
    def ent(x, y, spr, col, frames=None):
        s = 'db %d,%d,%d,%d,%d' % (x & 255, x >> 8, y, spr, col)
        return s + (',%d' % frames if frames else '')
    L = ['; generated by tools/build.py - front-end display lists']
    L.append('logo_list: db 3')
    for i, c in enumerate((15, 14, 6)):        # cold chrome: white, cyan, dark teal
        L.append('        ' + ent(24, 32 + 16 * i, I['logo%d' % i], c, 1))
    roster = [(196, 56, I['saucer0'], 0x5D, 2), (196, 104, I['hunter0'], 0x09, 2), (196, 152, I['sting0'], 0x0B, 8),
              (196, 200, I['mine0'], 0x09, 2), (210, 232, I['rock_VOLATILE_S_0'], 0x19, 4), (210, 248, I['rock_ORE_S_0'], 0x3B, 4),
              (60, 120, I['rock_ORE_L_0'], 0x3B, 8), (60, 200, I['rock_CRYSTAL_M_0'], 0x6E, 8), (478, 120, I['rock_VOLATILE_L_0'], 0x19, 8),
              (452, 210, I['rock_STONE_M_0'], 0x87, 8)]
    L.append('roster_list: db %d' % len(roster))
    L += ['        ' + ent(*r) for r in roster]
    tre = [(88, 56, I['jewel_TOPAZ_0'], 11, 4), (88, 88, I['jewel_RUBY_0'], 9, 4), (88, 120, I['jewel_EMERALD_0'], 10, 4),
           (326, 56, I['pick_SHIELD_0'], 15, 1), (326, 104, I['pick_BOMB_0'], 15, 1), (326, 152, I['pick_SPREAD_0'], 15, 1),
           (326, 200, I['pick_RAPID_0'], 15, 1), (326, 232, I['pick_LIFE_0'], 15, 1),
           (210, 216, I['rock_ORE_L_0'], 0x3B, 8)]
    L.append('treasure_list: db %d' % len(tre))
    L += ['        ' + ent(*r) for r in tre]
    # controls page: a ship showing each action, all static
    F = I['flame0_0']
    ctl = [(96, 56, I['ship28'], 0x0F, 1),                  # rotate left
           (96, 88, I['ship4'], 0x0F, 1),                   # rotate right
           (96, 120, F + 8, 0x9B, 1), (96, 120, I['ship8'], 0x0F, 1),   # thrust
           (80, 152, I['ship8'], 0x0F, 1), (128, 151, I['bullet'], 14, 1),  # fire
           (96, 184, I['ship0'], 0x0F, 1), (96, 184, I['shield0'], 14, 1),  # hyperspace: shimmering
           (96, 216, I['ring2'], 11, 1), (96, 216, I['ship0'], 0x0F, 1)]    # smart bomb
    L.append('controls_list: db %d' % len(ctl))
    L += ['        ' + ent(*r) for r in ctl]
    (R / 'src/lists.inc').write_text('\n'.join(L) + '\n')


def assemble(src, sym):
    a = zasm.Asm().run(str(R / 'src' / src))
    import os
    cwd = os.getcwd(); os.chdir(R / 'src')
    try:
        a.write(str(R / 'build' / sym))
    finally:
        os.chdir(cwd)
    return a


def main():
    p = argparse.ArgumentParser()
    p.add_argument('--base', default='/mnt/user-data/uploads/outputs/Asteroids2-Microbee/build/AST2.DS8')
    a = p.parse_args()
    (R / 'build').mkdir(exist_ok=True)
    port_sim.generate()
    import retrofont
    (R / 'build/font.bin').write_bytes(retrofont.font_bytes())
    sprites, banks, recs = compile_art()
    write_incs(recs)
    for f in (R / 'build').glob('ART*.BNK'):
        f.unlink()
    for i, b in enumerate(banks):
        (R / 'build' / ('ART%d.BNK' % i)).write_bytes(b)
    eng = assemble('engine.asm', 'engine.sym')
    sim = assemble('sim.asm', 'sim.sym')
    hi = (R / 'build/AST2.HI').read_bytes(); lo = (R / 'build/GAME.BNK').read_bytes()
    assert len(hi) <= 0x5000 and len(lo) <= 0x3000, (len(hi), len(lo))
    t = (R / 'src/loader-template.asm').read_text()
    files = ['files:      DB 15, $50, "GAME    BNK"']
    files += ['            DB %d, 0, "ART%-5dBNK"' % (ART_BLOCK0 + i, i) for i in range(len(banks))]
    files += ['            DB 15, 0, "AST2    HI "', '            DB 0']
    t = t.replace('@FILES@', '\n'.join(files)).replace('@LO_LEN@', str(len(lo))).replace('@HI_LEN@', str(len(hi)))
    (R / 'src/loader.asm').write_text(t)
    assemble('loader.asm', 'loader.sym')
    base = Path(a.base).read_bytes()
    payload = {'CCP.SYS': disk.files(base)['CCP.SYS'], 'AST2.COM': (R / 'build/AST2.COM').read_bytes(),
               'AST2.HI': hi, 'GAME.BNK': lo}
    payload.update({'ART%d.BNK' % i: bytes(b) for i, b in enumerate(banks)})
    payload['README.TXT'] = (b'ASTEROIDS II for the Microbee Premium Plus (512K)\r\n'
                             b'Type AST2 at the A> prompt.\r\n'
                             b'U/I or arrows turn, O or up thrust, Z/SPACE fire, P hyperspace,\r\n'
                             b'B or down smart bomb, RETURN/1 start. Joystick works too.\r\n'
                             b'Title: M music on/off, C colour/monochrome.\r\n'
                             b'Vibed by BPM 2026 - original VZ300 game by the same author.\r\n\x1a')
    (R / 'build/AST2.DS8').write_bytes(disk.build(base, payload))
    man = {k: len(v) for k, v in payload.items()}
    man['art_blocks'] = len(banks); man['sprites'] = len(recs)
    man['engine_end'] = '%04X' % eng.sym['code_end']
    (R / 'build/manifest.json').write_text(json.dumps(man, indent=1))
    print(json.dumps(man))


if __name__ == '__main__':
    main()
