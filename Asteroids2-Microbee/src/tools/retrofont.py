def cell(ch):
    """16-byte Microbee cell for a character (lowercase folded, ~ -> ^)"""
    ch = ch.upper()
    if ch == '~':
        ch = '^'
    a = G.get(ch, G['?'])
    out = bytearray(16)
    for y in range(10):
        out[3 + y] = int(''.join('1' if v else '0' for v in a[y]) + '0', 2)
    return bytes(out)


def font_bytes():
    """ASCII 32..95, 16 bytes each"""
    return b''.join(cell(chr(c)) for c in range(32, 96))


def sheet(path):
    from PIL import Image
    chars = ''.join(chr(c) for c in range(32, 96))
    img = np.zeros((16 * 4, 8 * 16), np.uint8)
    for i, ch in enumerate(chars):
        b = cell(ch)
        for y in range(16):
            for x in range(8):
                if b[y] >> (7 - x) & 1:
                    img[(i // 16) * 16 + y, (i % 16) * 8 + x] = 255
    im = Image.fromarray(img)
    im.resize((im.width * 4, im.height * 6), Image.Resampling.NEAREST).save(path)


if __name__ == '__main__':
    import sys
    sheet(sys.argv[1])
