"""BELLARIUS music (public-domain classics arranged, plus original jingles; VIBED BY BPM 2026) for the two-voice
pin-pulse beeper engine (frame_wait loop: 127 T at 3.375 MHz). One step of
a song is one 25 Hz frame. Every note's last frame is silent, so notes stay
separate and gritty. Writes src/music.inc."""
import os

HERE = os.path.dirname(os.path.abspath(__file__))
LOOPRATE = 3375000.0 / 127
NAMES = {'C': 0, 'C#': 1, 'D': 2, 'D#': 3, 'E': 4, 'F': 5, 'F#': 6, 'G': 7, 'G#': 8, 'A': 9, 'A#': 10, 'B': 11}


def nidx(tok):
    return (int(tok[-1]) - 2) * 12 + NAMES[tok[:-1]] + 1


def build(out):
    L = ['; generated by tools/music.py', 'notetab:']
    steps = [0]
    for i in range(1, 73):
        f = 65.406 * 2 ** ((i - 1) / 12.0)
        steps.append(int(round(f * 65536 / LOOPRATE)))
    L.append('    dw ' + ','.join(str(s) for s in steps))

    def db(bs):
        bs = list(bs)
        for i in range(0, len(bs), 16):
            L.append('    db ' + ','.join('$%02X' % b for b in bs[i:i + 16]))

    def song(name, step, *chans, loop=False):
        for ci, txt in enumerate(chans):
            ev = []
            for t in txt.split():
                if t == '-':
                    ev[-1][1] += step
                elif t == 'r':
                    ev.append([0, step])
                else:
                    ev.append([nidx(t), step])
            o = []
            for n, d in ev:
                while d > 255:
                    o += [n, 255]
                    d -= 255
                o += [n, d]
            o.append(0xFE if loop else 0xFF)
            L.append('mus_%s_%d:' % (name, ci))
            db(o)

    # Parodius-style: public-domain classics, arranged for two beeper voices.
    # title: Offenbach, the Infernal Galop (the Can-can)
    t1 = """
C5 r C5 D5 F5 E5 D5 G5  G5 r G5 A5 E5 F5 D5 r
D5 r D5 F5 E5 D5 C5 C6  B5 A5 G5 F5 E5 D5 C5 r
C5 r C5 D5 F5 E5 D5 G5  G5 r G5 A5 E5 F5 D5 r
D5 r D5 F5 E5 D5 C5 G5  D5 E5 C5 r C6 r r r
"""
    t1b = """
C3 G3 C3 G3 C3 G3 C3 G3  G2 G3 G2 G3 G2 G3 G2 G3
G2 G3 G2 G3 C3 G3 C3 G3  G2 G3 G2 G3 C3 G3 C3 r
C3 G3 C3 G3 C3 G3 C3 G3  G2 G3 G2 G3 G2 G3 G2 G3
G2 G3 G2 G3 C3 G3 C3 G3  G2 G3 C3 r C3 r r r
"""
    song('title', 3, t1, t1b, loop=True)
    # stage 1, the office: Mozart, Eine kleine Nachtmusik - as lift muzak
    g1 = """
G5 - r D5 G5 - r D5  G5 D5 G5 B5 D6 - - r
C6 - r A5 C6 - r A5  C6 A5 F#5 A5 D5 - - r
G5 r G5 r B5 A5 G5 r  G5 r F#5 r F#5 r r r
A5 C6 F#5 A5 G5 r G5 r  B5 A5 G5 F#5 G5 - - r
"""
    g1b = """
G2 - r - G3 - r -  G2 - r - G3 - r -
D3 - r - D2 - r -  D3 - r - D2 - r -
G2 - r - G3 - r -  D3 - r - D2 - r -
D3 - r - G2 - r -  D3 - r - G2 - - r
"""
    song('game', 5, g1, g1b, loop=True)
    # bosses (stages 1-4): Bach, the Toccata in D minor
    b1 = """
A5 G5 A5 - - - - r  G5 F5 E5 D5 C#5 - D5 - - - - r
A4 G4 A4 - - - - r  E4 F4 C#4 - D4 - - - - - - r
A3 G3 A3 - - - - r  G3 F3 E3 D3 C#3 - D3 - - - - r
"""
    b1b = """
D3 - - - - - - r  D3 - - - A2 - D3 - - - - r
D3 - - - - - - r  A2 - A2 - D3 - - - - - - r
D2 - - - - - - r  A2 - - - A2 - D2 - - - - r
"""
    song('boss', 3, b1, b1b, loop=True)
    # stage 2, the candy shop: Joplin, The Entertainer
    g2 = """
D5 D#5 E5 C6 - E5 C6 -  E5 C6 - - - r r r
C6 D6 D#6 E6 C6 D6 E6 -  B5 D6 C6 - - - r r
D5 D#5 E5 C6 - E5 C6 -  E5 C6 - - - r r r
A5 G5 F#5 A5 C6 E6 - D6  C6 A5 D6 - - - r r
"""
    g2b = """
C3 r G3 r C3 r G3 r  C3 r G3 r E3 r G3 r
F3 r C4 r F3 r C4 r  G2 r G3 r C3 r G3 r
C3 r G3 r C3 r G3 r  C3 r G3 r E3 r G3 r
D3 r A3 r D3 r A3 r  G2 r G3 r G2 r r r
"""
    song('game2', 3, g2, g2b, loop=True)
    # stage 3, the toy box: Rimsky-Korsakov, Flight of the Bumblebee
    g3 = """
E6 D#6 D6 C#6 D6 C#6 C6 B5  C6 B5 A#5 A5 G#5 G5 F#5 F5
E5 D#5 D5 C#5 D5 C#5 C5 B4  C5 B4 A#4 A4 G#4 G4 F#4 F4
E5 D#5 D5 C#5 C5 F5 E5 D#5  E5 D#5 D5 C#5 C5 C#5 D5 D#5
E5 D#5 D5 C#5 C5 F5 E5 D#5  E5 F5 E5 D#5 E5 F#5 G5 G#5
"""
    g3b = """
A2 - - r A2 - - r  A2 - - r A2 - - r
A2 - - r A2 - - r  A2 - - r A2 - - r
A2 - - r D3 - - r  A2 - - r E3 - - r
A2 - - r D3 - - r  A2 - - r E2 - - r
"""
    song('game3', 2, g3, g3b, loop=True)
    # stage 4, the space opera: Rossini, the William Tell overture (the gallop)
    g4 = """
E5 E5 E5 r E5 E5 E5 r  E5 E5 A5 r B5 r C#6 r
E5 E5 E5 r E5 E5 A5 r  C#6 C#6 B5 r G#5 r E5 r
E5 E5 E5 r E5 E5 E5 r  E5 E5 A5 r B5 r C#6 r
A5 C#6 E6 r D6 r B5 r  G#5 r B5 r A5 - - r
"""
    g4b = """
A2 E3 A2 E3 A2 E3 A2 E3  A2 E3 A2 E3 E2 E3 E2 E3
A2 E3 A2 E3 A2 E3 A2 E3  E2 B2 E2 B2 E2 B2 E2 B2
A2 E3 A2 E3 A2 E3 A2 E3  A2 E3 A2 E3 E2 E3 E2 E3
A2 E3 A2 E3 D3 A3 D3 A3  E2 B2 E2 B2 A2 E3 A2 r
"""
    song('game4', 3, g4, g4b, loop=True)
    # stage 5, head office: Grieg, In the Hall of the Mountain King
    g5 = """
B3 C#4 D4 E4 F#4 D4 F#4 -  F4 C#4 F4 -  E4 C4 E4 -
B3 C#4 D4 E4 F#4 D4 F#4 B4  A4 F#4 D4 F#4 A4 - - -
B4 C#5 D5 E5 F#5 D5 F#5 -  F5 C#5 F5 -  E5 C5 E5 -
B4 C#5 D5 E5 F#5 D5 F#5 B5  A5 F#5 D5 F#5 B5 - - r
"""
    g5b = """
B2 r F#2 r B2 r F#2 r  C#3 r G#2 r C3 r G2 r
B2 r F#2 r B2 r F#2 r  F#2 r C#3 r F#2 r r r
B2 r F#2 r B2 r F#2 r  C#3 r G#2 r C3 r G2 r
B2 r F#2 r B2 r F#2 r  F#2 r C#3 r B2 r r r
"""
    song('game5', 3, g5, g5b, loop=True)
    # the CEO: Wagner, the Ride of the Valkyries
    v5 = """
F#4 B4 - F#4 B4 D5 - - B4 - -  D5 B4 - D5 F#5 - - D5 - -
F#5 D5 - F#5 A5 - - A4 - -  D5 A4 - D5 F#5 - - - - -
F#4 B4 - F#4 B4 D5 - - B4 - -  D5 B4 - D5 F#5 - - D5 - -
F#5 D5 - F#5 A5 - - F#5 - -  A5 F#5 - A5 C#6 - - - - r
"""
    v5b = """
B2 - - - - - - - F#2 - -  B2 - - - - - - - - -
D3 - - - - - - - A2 - -  D3 - - - - - - - - -
B2 - - - - - - - F#2 - -  B2 - - - - - - - - -
D3 - - - - - - - A2 - -  F#2 - - - - - - - - r
"""
    song('boss5', 2, v5, v5b, loop=True)
    # the ending: Beethoven, Ode to Joy
    o = """
E5 - E5 - F5 - G5 -  G5 - F5 - E5 - D5 -  C5 - C5 - D5 - E5 -  E5 - - D5 D5 - - -
E5 - E5 - F5 - G5 -  G5 - F5 - E5 - D5 -  C5 - C5 - D5 - E5 -  D5 - - C5 C5 - - r
"""
    ob = """
C3 - G3 - C3 - G3 -  C3 - G3 - G2 - G3 -  C3 - G3 - C3 - G3 -  G2 - G3 - G2 - r -
C3 - G3 - C3 - G3 -  C3 - G3 - G2 - G3 -  C3 - G3 - G2 - G3 -  G2 - - - C3 - - r
"""
    song('end', 4, o, ob)
    song('ready', 4, 'C5 E5 G5 C6 - - - r', 'C3 r C4 r C3 C4 C3 r')
    song('clear', 4, 'C5 E5 G5 C6 - E6 - G6 - - - r C6 - - - r',
         'C3 C3 C2 C3 C2 C3 C2 C3 G2 G3 G2 G3 C3 - - r')
    song('over', 8, 'G4 - F#4 - F4 - E4 - - - D4 - - - r', 'G2 - - - F2 - - - E2 - - - D2 - - r')
    open(out, 'w').write('\n'.join(L) + '\n')


if __name__ == '__main__':
    build(os.path.join(HERE, '..', 'src', 'music.inc'))
