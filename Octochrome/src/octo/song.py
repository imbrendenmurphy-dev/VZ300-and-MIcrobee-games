"""OCTOCHROME - the tune (original). Three voices, one sample every two scanlines (456 T).
One sixteenth = 6 fields. 32 bars, looping."""
import os, sys
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'tools'))
import music
music.RATE = 3546894 / 456.0
from music import compile_channel, note_steps

INSTR = list(music.INSTR) + [
    (90, 6, 24, 0),   # 12 synth bass
    (58, 2, 20, 0),   # 13 pluck lead
    (44, 1, 26, 0),   # 14 soft lead
]

BAR = 96


def bassline(chords):
    out = 'i12 '
    for root in chords:
        n, o = root[:-1], int(root[-1])
        hi = n + str(o + 1)
        out += '%s:2 %s:2 %s:1 %s:1 %s:2 %s:2 %s:2 %s:1 %s:1 %s:2 | ' % (root, hi, root, root, hi, root, hi, root, root, hi)
    return out


K, S, H, R = 'i7 C3:1 ', 'i3 C5:1 ', 'i8 C6:1 ', 'r:1 '
BEAT = (K + H + H + H + S + H + K + H + K + H + H + H + S + H + H + H + '| ')
FILL = (K + H + K + H + S + H + K + H + S + S + K + S + S + S + S + S + '| ')
SOFT = (K + R + H + R + H + R + H + R + K + R + H + R + H + R + H + R + '| ')


def drums(bar=BEAT, fill=FILL):
    return bar * 3 + fill


ARP = {
    'Am': 'A4 C5 E5 A5', 'F': 'F4 A4 C5 F5', 'C': 'C5 E5 G5 C6', 'G': 'G4 B4 D5 G5',
    'Dm': 'D5 F5 A5 D6', 'E': 'E4 G#4 B4 E5',
}


def arps(chords):
    out = 'i4 '
    for c in chords:
        ns = ARP[c].split()
        seq = ns + ns[::-1] + ns + ns[::-1]
        out += ' '.join(n + ':1' for n in seq) + ' | '
    return out


V1 = ['Am', 'F', 'C', 'G']
V2 = ['Am', 'F', 'Dm', 'E']
ROOTS = {'Am': 'A2', 'F': 'F2', 'C': 'C3', 'G': 'G2', 'Dm': 'D2', 'E': 'E2'}

MEL1 = ('i13 E5:3 E5:3 A5:2 G5:2 E5:2 D5:2 C5:2 | C5:3 C5:3 F5:2 E5:2 C5:2 A4:4 | '
        'G4:2 C5:2 E5:4 G5:2 E5:2 D5:2 C5:2 | B4:4 D5:4 G5:6 r:2 | ')
MEL2 = ('i13 E5:3 E5:3 A5:2 G5:2 E5:2 D5:2 C5:2 | C5:3 C5:3 F5:2 E5:2 C5:2 A4:4 | '
        'D5:2 F5:2 A5:4 C6:2 A5:2 F5:2 D5:2 | E5:4 G#5:4 B5:6 r:2 | ')
MEL3 = ('i14 A5:6 C6:2 B5:4 A5:4 | F5:6 A5:2 G5:4 F5:4 | E5:6 G5:2 C6:4 B5:4 | B5:8 D6:8 | ')
MEL4 = ('i14 A5:6 C6:2 B5:4 A5:4 | F5:6 A5:2 C6:4 D6:4 | E6:4 D6:4 C6:4 B5:4 | A5:12 r:4 | ')

SECTIONS = [
    (arps(V1), bassline([ROOTS[c] for c in V1]), drums(SOFT, BEAT)),
    (MEL1, bassline([ROOTS[c] for c in V1]), drums()),
    (MEL2, bassline([ROOTS[c] for c in V2]), drums()),
    (MEL3, bassline([ROOTS[c] for c in V1]), drums()),
    (MEL4, bassline([ROOTS[c] for c in V2]), drums()),
    (arps(V2), bassline([ROOTS[c] for c in V2]), drums(SOFT, FILL)),
    (MEL1, bassline([ROOTS[c] for c in V1]), drums()),
    (MEL4, bassline([ROOTS[c] for c in V2]), drums(BEAT, FILL)),
]
SONG = ['u6 ' + ''.join(s[k] for s in SECTIONS) for k in range(3)]


def asm():
    out = ['; generated by octo/song.py', 'instruments:']
    for ins in INSTR:
        out.append('            db %d,%d,%d,%d' % ins)
    out.append('note_steps:')
    st = note_steps()
    for i in range(0, len(st), 12):
        out.append('            dw ' + ','.join(str(v) for v in st[i:i + 12]))
    out.append('song_main: dw song_c0,song_c1,song_c2')
    lens = []
    for k, ch in enumerate(SONG):
        data, t = compile_channel(ch)
        lens.append(t)
        out.append('song_c%d:' % k)
        for i in range(0, len(data), 24):
            out.append('            db ' + ','.join(str(b) for b in data[i:i + 24]))
        out.append('            db 254')
        out.append('            dw song_c%d' % k)
    if len(set(lens)) != 1 or lens[0] != 32 * BAR:
        raise SystemExit('song lengths %s, expected %d' % (lens, 32 * BAR))
    return '\n'.join(out) + '\n'


if __name__ == '__main__':
    print(len(asm()))
