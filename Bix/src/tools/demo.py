# Attract-mode recording for World 1-1 (game frames at 25 fps).  L1 R2 U4 D8 J16
import os
L, R, U, D, J = 1, 2, 4, 8, 16
SEQ = [
 (0, 20), (R, 26), (R|J, 10), (R, 10), (0, 3), (D, 4), (D|R, 8), (R, 16), (R|J, 8),
 (R, 25), (R|J, 10), (R, 30), (R|J, 12), (R, 28), (R|J, 10), (R, 30), (R|J, 8), (R, 32),
 (R|J, 10), (R, 40), (R|J, 10), (R, 40), (0, 10),
]
out = ['; generated by demo.py', 'demo_data:']
for k, n in SEQ:
    while n > 0:
        m = min(n, 255); out.append(f'  db {k},{m}'); n -= m
out.append('  db $FF')
open(os.path.join(os.path.dirname(__file__), '..', 'build', 'demo.inc'), 'w').write('\n'.join(out) + '\n')
