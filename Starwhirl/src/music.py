def sfx(prio, steps):
    out = [prio]
    for s in steps:
        out += [s & 255, s >> 8]
    out += [0xFF, 0xFF]
    return out


def t(f):
    return step(f) if f else 0


def nz(f):
    return step(f) | 0x8000


