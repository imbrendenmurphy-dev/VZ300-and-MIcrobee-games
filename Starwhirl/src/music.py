"""STARWHIRL music + sound effects -> music.inc
The beeper runs a 16-bit phase accumulator while the CPU waits for the next
frame (182 T-states per sample at 3.5469 MHz).  A note is a 16-bit step;
bit 15 = pitched noise.
Music: (step word, frames); the last frame of each note is silent, so notes
stay separate.  SFX: one step word per game frame (25 Hz), $FFFF ends.
All tunes are original.
"""
import sys
RATE = 3546900 / 182.0
NOTE = {'C': 0, 'C#': 1, 'D': 2, 'D#': 3, 'E': 4, 'F': 5, 'F#': 6, 'G': 7,
        'G#': 8, 'A': 9, 'A#': 10, 'B': 11}


def freq(n):
    name, octv = n[:-1], int(n[-1])
    semis = NOTE[name] + 12 * (octv + 1) - 69
    return 440.0 * 2 ** (semis / 12.0)


def step(f):
    return max(1, min(0x7FFF, int(round(f * 65536 / RATE))))


def song(spec, e8=4):
    out = []
    for tok in spec.split():
        if ':' in tok:
            n, d = tok.split(':')
            d = float(d)
        else:
            n, d = tok, 1
        frames = max(1, int(round(d * e8)))
        s = 0 if n == '-' else step(freq(n))
        out += [s & 255, s >> 8, frames]
    out += [0xFF, 0xFF]
    return out


