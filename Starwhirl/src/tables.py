"""STARWHIRL tables -> tables.inc
 * the polar projection table (r = 0..63 by 33 angles per quadrant)
 * flight paths for the formations, precomputed in Python and stored as
   one byte per frame: high nibble = angle step + 8, low nibble = radius
   step + 8 (each -7..+7).  A high nibble of 0 is a command:
   $00 end -> fly to a slot in the holding ring, $01 end -> fly out and away,
   $02 fire here (if this enemy may fire), $03 end -> vanish at the centre.
 * the wave scripts for the five sectors, and the difficulty table.
Angles: 256 to a circle, 0 = right, 64 = down.  Radius: 0 = the centre,
56 = the player's orbit, 63 = the screen edge.
"""
import math
