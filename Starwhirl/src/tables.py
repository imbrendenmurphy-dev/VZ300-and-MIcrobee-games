out = ['; generated by tables.py - do not edit']


def db(label, data, per=16):
    s = [label + ':'] if label else []
    for i in range(0, len(data), per):
        s.append('    db ' + ','.join('$%02X' % (b & 255) for b in data[i:i + per]))
    return '\n'.join(s)


# ---------------------------------------------------------------- polar
pt = []
for r in range(64):
    for q in range(33):
        pt.append(int(round(r * math.cos(q * math.pi / 64))))
out.append('POLAR_STRIDE equ 33')
