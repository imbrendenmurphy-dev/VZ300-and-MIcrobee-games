out.append('    assert high ptrow == high (ptrow+127)')
out.append(db('polar', pt))
# 64-entry sine (one full turn), amplitude 64, signed bytes
out.append(db('sin64', [int(round(64 * math.sin(i * 2 * math.pi / 64))) for i in range(64)]))

# ---------------------------------------------------------------- paths
def ease_in(t):
    return t ** 1.7


def ease_out(t):
    return 1 - (1 - t) ** 1.7


def ease_io(t):
    return 0.5 - 0.5 * math.cos(math.pi * t)


class P:
    def __init__(self, r0):
        self.pts = [(0.0, float(r0))]
        self.cmds = {}

    @property
    def a(self):
        return self.pts[-1][0]

    @property
    def r(self):
        return self.pts[-1][1]

    def seg(self, n, r1, da=0.0, ease=ease_io, afun=None):
        a0, r0 = self.a, self.r
        for i in range(1, n + 1):
            t = i / n
            r = r0 + (r1 - r0) * ease(t)
            a = a0 + da * i if afun is None else a0 + afun(t)
            self.pts.append((a, r))
        return self

    def fire(self):
        self.cmds[len(self.pts) - 1] = 2
        return self

    def encode(self, end):
        b = [int(round(self.pts[0][1]))]
        ca, cr = 0, int(round(self.pts[0][1]))
        for i in range(1, len(self.pts)):
            ta, tr = int(round(self.pts[i][0])), int(round(self.pts[i][1]))
            da = max(-7, min(7, ta - ca))
            dr = max(-7, min(7, tr - cr))
            ca += da
            cr += dr
            b.append(((da + 8) << 4) | (dr + 8))
            if i in self.cmds:
                b.append(self.cmds[i])
        b.append(end)
        return b, ca, cr


