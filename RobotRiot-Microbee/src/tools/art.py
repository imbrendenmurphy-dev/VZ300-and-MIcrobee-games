"""ROBOT RIOT 2086 artwork (VIBED BY BPM 2026).

Every moving thing is a 12 x 12 pixel shape on a 4-pixel grid, so it always
covers 2 x 2 character cells; each frame becomes 16 PCG glyphs (4 grid
offsets x 4 cells). Sprites are two-tone: the top two cells take one
colour, the bottom two another. The gallery shows the same art at double
size (24 x 24, 3 x 3 cells). The Microbee's pixels are tall on a 4:3
screen, so round things are drawn squashed."""
import numpy as np

BLACK, RED, GREEN, BROWN, BLUE, MAGENTA, CYAN, GREY = range(8)
DGREY, BRED, BGREEN, YELLOW, BBLUE, BMAGENTA, BCYAN, WHITE = range(8, 16)


def art(rows):
    rows = [r.strip() for r in rows.strip('\n').split('\n')]
    assert len(rows) == 12, (len(rows), rows)
    a = np.zeros((12, 16), bool)
    for y, r in enumerate(rows):
        assert len(r) == 12, (r, len(r))
        for x, ch in enumerate(r):
            a[y, x] = ch == '#'
    return a


def mirror(a):
    b = np.zeros_like(a)
    b[:, :12] = a[:, :12][:, ::-1]
    return b


