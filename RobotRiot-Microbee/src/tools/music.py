"""ROBOT RIOT 2086 music (original, VIBED BY BPM 2026) for the two-voice
pin-pulse beeper engine (frame_wait loop: 127 T at 3.375 MHz). One step of
a tune is one 25 Hz frame. The sounds are built from per-frame pitch
moves: squelchy drops (each bass note starts an octave up and dives),
robotic arpeggios and zips. Writes src/music.inc."""
import os

HERE = os.path.dirname(os.path.abspath(__file__))
LOOPRATE = 3375000.0 / 127
NAMES = {'C': 0, 'C#': 1, 'D': 2, 'D#': 3, 'E': 4, 'F': 5, 'F#': 6, 'G': 7, 'G#': 8, 'A': 9, 'A#': 10, 'B': 11}


def nidx(tok):
    return (int(tok[-1]) - 2) * 12 + NAMES[tok[:-1]] + 1


class Chan:
    """a channel built frame by frame: list of [note index (0 rest), frames]"""

    def __init__(self):
        self.ev = []

    def put(self, n, d=1):
        if d <= 0:
            return self
        if self.ev and self.ev[-1][0] == n:
            self.ev[-1][1] += d
        else:
            self.ev.append([n, d])
        return self

    def rest(self, d):
        return self.put(0, d)

    def note(self, tok, d, gap=1):
        """a plain note, its last frame silent so notes stay apart"""
        self.put(nidx(tok), d - gap)
        return self.rest(gap)

    def squelch(self, tok, d, drop=12, fall=3):
        """starts `drop` semitones up and dives to the note in `fall` frames"""
        n = nidx(tok)
        for i in range(fall):
            self.put(min(72, n + drop - drop * i // fall), 1)
        self.put(n, d - fall - 1)
        return self.rest(1)

    def arp(self, toks, d, gap=1):
        """a robotic arpeggio: a different chord note every frame"""
        ns = [nidx(t) for t in toks]
        for i in range(d - gap):
            self.put(ns[i % len(ns)], 1)
        return self.rest(gap)

    def zip(self, a, b, d):
        """a straight slide from note a to note b over d frames"""
        na, nb = nidx(a), nidx(b)
        for i in range(d):
            self.put(round(na + (nb - na) * i / max(1, d - 1)), 1)
        return self

    def frames(self):
        return sum(d for n, d in self.ev)


def build(out):
    L = ['; generated by tools/music.py', 'notetab:']
    steps = [0]
    for i in range(1, 73):
        f = 65.406 * 2 ** ((i - 1) / 12.0)
        steps.append(int(round(f * 65536 / LOOPRATE)))
    L.append('    dw ' + ','.join(str(s) for s in steps))

    def db(bs):
        bs = list(bs)
        for i in range(0, len(bs), 16):
            L.append('    db ' + ','.join('$%02X' % b for b in bs[i:i + 16]))

    def emit(name, chans, loop=False):
        for ci, ch in enumerate(chans):
            o = []
            for n, d in ch.ev:
                while d > 255:
                    o += [n, 255]
                    d -= 255
                o += [n, d]
            o.append(0xFE if loop else 0xFF)
            L.append('mus_%s_%d:' % (name, ci))
            db(o)

    def song(name, step, *chans, loop=False):
        """the simple form: one token a step ('-' holds, 'r' rests)"""
        cs = []
        for txt in chans:
            c = Chan()
            toks = txt.split()
            i = 0
            while i < len(toks):
                t = toks[i]
                n = 1
                while i + n < len(toks) and toks[i + n] == '-':
                    n += 1
                if t == 'r':
                    c.rest(step * n)
                else:
                    c.note(t, step * n)
                i += n
            cs.append(c)
        emit(name, cs, loop)

    # ---- the title jingle: "Riot Engine" - squelchy acid bass, a robotic
    # arpeggio lead, a zip up and a power-down. About 6 seconds.
    lead, bass = Chan(), Chan()
    lead.zip('A2', 'A6', 10).rest(2)                      # power up
    bass.rest(12)
    chords = [('A', ['A4', 'C5', 'E5']), ('F', ['F4', 'A4', 'C5']), ('G', ['G4', 'B4', 'D5']), ('E', ['E4', 'G#4', 'B4'])]
    roots = {'A': 'A2', 'F': 'F2', 'G': 'G2', 'E': 'E2'}
    for rnd in range(2):
        for name, ch in chords:
            r = roots[name]
            up = r[:-1] + str(int(r[-1]) + 1)
            # bass: squelch on the beat, octave stab, squelch, squelch
            bass.squelch(r, 6).squelch(up, 4, drop=7, fall=2).squelch(r, 4).rest(2)
            # lead: stabs of arpeggio, a different shape the second time round
            if rnd == 0:
                lead.arp(ch, 5).rest(3).arp(ch, 3).rest(5)
            else:
                lead.arp([ch[2], ch[1], ch[0], ch[1]], 8).arp([c[:-1] + str(int(c[-1]) + 1) for c in ch], 8)
    lead.arp(['A5', 'E5', 'C5', 'A4'], 12, gap=0).zip('A5', 'A2', 14).rest(6)   # power down
    bass.squelch('A2', 10, drop=24, fall=6).zip('A3', 'C2', 16).rest(6)
    emit('title', [lead, bass])
    print('title jingle: %.1f s' % (max(lead.frames(), bass.frames()) / 25.0))

    # ---- the hall of legends: a triumphant robot fanfare
    lead, bass = Chan(), Chan()
    for t in ('C5', 'E5', 'G5'):
        lead.arp([t, t[:-1] + '6'], 5)
    lead.arp(['C6', 'G5', 'E5', 'G5'], 16).rest(2).zip('C5', 'C7', 8).rest(4)
    bass.squelch('C3', 5).squelch('E3', 5).squelch('G3', 5).squelch('C3', 10, drop=24, fall=5).squelch('G2', 8).squelch('C3', 12)
    emit('fame', [lead, bass])

    # in play: slow, sparse robotic blips so the game keeps its time
    ingame = """
A3 r r r r r r r  A3 r A3 r C4 r r r
r r r r r r r r  G3 r r r r r r r
A3 r r r r r r r  A3 r A3 r D4 r r r
r r r r r r r r  E4 r r r E3 r r r
"""
    ingb = """
r r r r A2 r r r  r r r r r r r r
F2 r r r r r r r  r r r r G2 r r r
r r r r A2 r r r  r r r r r r r r
D2 r r r r r r r  r r r r E2 r r r
"""
    song('game', 5, ingame, ingb, loop=True)
    # get ready: a zip up and a squelch
    lead, bass = Chan(), Chan()
    lead.zip('E3', 'E5', 8).arp(['A4', 'C5', 'E5', 'A5'], 12).rest(2)
    bass.squelch('A2', 8, drop=24, fall=4).squelch('A2', 6).squelch('E3', 6).rest(2)
    emit('ready', [lead, bass])
    # wave cleared
    lead, bass = Chan(), Chan()
    lead.arp(['A4', 'C5', 'E5'], 8).arp(['C5', 'E5', 'G5'], 8).arp(['E5', 'A5', 'C6'], 12)
    bass.squelch('A2', 8).squelch('C3', 8).squelch('E3', 12, drop=24, fall=5)
    emit('clear', [lead, bass])
    # game over: running down
    lead, bass = Chan(), Chan()
    lead.zip('E5', 'A3', 30).rest(4).note('A3', 6).note('E3', 6).zip('A3', 'A2', 20)
    bass.squelch('A2', 16).squelch('G2', 16).squelch('F2', 16).squelch('E2', 24, drop=24, fall=8)
    emit('over', [lead, bass])
    open(out, 'w').write('\n'.join(L) + '\n')


if __name__ == '__main__':
    build(os.path.join(HERE, '..', 'src', 'music.inc'))
