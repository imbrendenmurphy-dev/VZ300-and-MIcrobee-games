"""Pre-shift the six ingredient graphics (5x8 bytes) to the four even pixel
phases an ingredient can sit at (native x is always a multiple of 10).
Writes work/port/src/pieces.inc: 6 types x 4 phases x 8 rows x 6 bytes."""
import re
from pathlib import Path
src = Path('work/port/src/art.inc').read_text()
out = ['; generated by work/gen_pieces.py - do not edit', 'piece_shifted:']
for t in range(6):
    m = re.search(rf'^food{t}:\s*\n\s*db ([0-9,]+)', src, re.M)
    vals = [int(v) for v in m.group(1).split(',')]
    w, h = vals[0], vals[1]
    assert (w, h) == (5, 8), (t, w, h)
    rows = [vals[3 + r * 5: 3 + r * 5 + 5] for r in range(8)]
    for s in range(4):
        sh = 2 * s
        data = []
        for r in rows:
            bits = int.from_bytes(bytes(r + [0]), 'big') >> sh
            data.extend(bits.to_bytes(6, 'big'))
        out.append(f'; type {t} shift {sh}')
        out.append(' db ' + ','.join(map(str, data)))
Path('work/port/src/pieces.inc').write_text('\n'.join(out) + '\n')
print('pieces.inc written')
