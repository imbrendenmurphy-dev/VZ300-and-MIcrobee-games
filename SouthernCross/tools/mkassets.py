def gen_blits():
    t = []
    # frame buffer -> video RAM, 64 rows x 24 bytes, stack copy (308 T/row)
    t.append('; FB visible rows -> VRAM bytes 4..27 of each row.  Entered by JP with\n')
    t.append('; interrupts off and SP saved in isr_sp; exits by JP blit_done.\n')
    t.append('BLIT_PF:\n')
    for r in range(64):
        src = FB + (8 + r) * FBW
        dst = VRAM + r * 32 + 4
        t.append('        ld sp,$%04X\n        pop af\n        pop bc\n        pop de\n        pop hl\n'
                 '        exx\n        ex af,af\'\n        pop af\n        pop bc\n        pop de\n        pop hl\n'
                 '        ld sp,$%04X\n        push hl\n        push de\n        push bc\n        push af\n'
                 '        exx\n        ex af,af\'\n        push hl\n        push de\n        push bc\n        push af\n'
                 % (src, dst + 16))
        t.append('        ld sp,$%04X\n        pop af\n        pop bc\n        pop de\n        pop hl\n'
                 '        ld sp,$%04X\n        push hl\n        push de\n        push bc\n        push af\n'
                 % (src + 16, dst + 24))
    t.append('        jp blit_done\n\n')
    # HUD shadow -> panels (normal stack, LDI)
    t.append('; HUD shadow (64 x 8 bytes) -> the two side panels\nBLIT_HUD:\n        ld hl,HUDBUF\n')
    for r in range(64):
        t.append('        ld de,$%04X\n        ldi\n        ldi\n        ldi\n        ldi\n'
                 '        ld de,$%04X\n        ldi\n        ldi\n        ldi\n        ldi\n'
                 % (VRAM + r * 32, VRAM + r * 32 + 28))
    t.append('        ret\n\n')
    # LDI chain for strip -> FB (enter at LDICHAIN_END - 2*bytes)
    t.append('LDICHAIN:\n')
    for i in range(64 * FBW):
        t.append('        ldi\n')
    t.append('LDICHAIN_END:\n        ret\n')
    return ''.join(t)

# ------------------------------------------------------------------ paths
def path_from_points(pts):
    """positions (x,y) per frame -> dx,dy per frame in 1/16 px (signed bytes)"""
    out = []
    ax = ay = 0.0
    for (x0, y0), (x1, y1) in zip(pts, pts[1:]):
        dx = round((x1 - x0) * 16 + ax); ax += (x1 - x0) * 16 - dx
        dy = round((y1 - y0) * 16 + ay); ay += (y1 - y0) * 16 - dy
        dx = max(-127, min(127, dx)); dy = max(-127, min(127, dy))
        out.append((dx, dy))
    return out

def p_swoop(direction):
    # enter downwards, curve across, leave diagonally down
    pts = []
    x, y = 0.0, 0.0
    ang = math.pi / 2                    # down
    for t in range(150):
        if 22 <= t < 62:
            ang -= direction * (math.pi * 0.45) / 40
        if 90 <= t < 120:
            ang += direction * (math.pi * 0.30) / 30
        sp = 1.45
        x += math.cos(ang) * sp
        y += math.sin(ang) * sp * 0.75     # tall pixels: slower vertical motion looks even
        pts.append((x, y))
    return [(0, 0)] + path_from_points([(0, 0)] + pts)

def p_sine():
    pts = [(14 * math.sin(t * 2 * math.pi / 64), t * 0.62) for t in range(170)]
    return path_from_points(pts)

def p_dart():
    pts = []
    y = 0.0
    for t in range(40):
        y += 1.3 if t < 24 else 0.15
        pts.append((0, y))
    return path_from_points([(0, 0)] + pts)

def p_loop():
    pts = []
    for t in range(190):
        if t < 30:
            pts.append((0, t * 1.1))
        elif t < 110:
            a = (t - 30) / 80 * 2 * math.pi
            pts.append((12 * math.sin(a), 33 + 12 * (1 - math.cos(a)) * 0.75 - 0 + (t - 30) * 0.1))
        else:
            pts.append((0, 41 + (t - 110) * 1.2))
    return path_from_points(pts)

PATHS = [('PATH_SWOOPR', p_swoop(+1)), ('PATH_SWOOPL', p_swoop(-1)),
         ('PATH_SINE', p_sine()), ('PATH_DART', p_dart()), ('PATH_LOOP', p_loop())]

def gen_paths():
    t = ['PATHTAB:\n        dw ' + ','.join(n for n, _ in PATHS) + '\n']
    for name, steps in PATHS:
        t.append('%s:\n' % name)
        flat = []
        for dx, dy in steps:
            flat += [dx & 255, dy & 255]
        flat.append(0x80)
        for i in range(0, len(flat), 16):
            t.append('        db ' + ','.join('$%02X' % b for b in flat[i:i + 16]) + '\n')
    return ''.join(t)

# aim table: index (dxq 0..15, dyq 0..15) -> vx, vy (16-bit, 1/256 px per frame)
def gen_aim():
    t = ['AIMTAB:\n']
    speed = 1.35
    for dyq in range(16):
        for dxq in range(16):
            dx = (dxq - 8) * 8 + 4
            dy = (dyq * 8 + 4) / 1.5          # tall pixels: compare in screen space
            d = math.hypot(dx, dy) or 1
            vx = int(round(dx / d * speed * 256))
            vy = int(round(dy / d * speed * 256 / 1.5 * 1.15))
            t.append('        dw %d,%d\n' % (vx, vy))
    return ''.join(t)

