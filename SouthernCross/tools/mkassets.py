def explosion_frames():
    frames = []
    rnd = random.Random(5)
    for f in range(4):
        rows = [['.'] * 8 for _ in range(8)]
        rad = [1.2, 2.4, 3.4, 3.9][f]
        for y in range(8):
            for x in range(8):
                dx, dy = x - 3.5, (y - 3.5) * 1.3
                d = math.hypot(dx, dy)
                if f == 0 and d < rad + 0.4:
                    rows[y][x] = 'y'
                elif f == 1 and d < rad:
                    rows[y][x] = 'y' if d < 1.4 else 'r'
                elif f == 2 and rad - 1.3 < d < rad and rnd.random() < 0.75:
                    rows[y][x] = 'r' if rnd.random() < 0.6 else 'y'
                elif f == 3 and rad - 0.8 < d < rad + 0.2 and rnd.random() < 0.35:
                    rows[y][x] = 'r'
        frames.append([''.join(r) for r in rows])
    return frames
