NOTE_NAMES = ['C', 'C#', 'D', 'D#', 'E', 'F', 'F#', 'G', 'G#', 'A', 'A#', 'B']
def note_index(n):
    """'D5' -> index 1..72 (C1 = 1)"""
    name, octv = n[:-1], int(n[-1])
    return (octv - 1) * 12 + NOTE_NAMES.index(name) + 1

def gen_notes():
    t = ['NOTE_STEP:\n        dw 0\n']
    for i in range(1, 73):
        midi = 24 + (i - 1)           # C1 = MIDI 24
        f = 440.0 * 2 ** ((midi - 69) / 12)
        step = int(round(f * 65536 / FSAMP))
        t.append('        dw %d\n' % min(step, 65535))
    return ''.join(t)

