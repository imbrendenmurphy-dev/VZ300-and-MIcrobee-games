def text_rows(s, fg='y', edge='b'):
    """text with a 1-pixel edge so it reads over any scenery"""
    w = len(s) * 4 + 1
    grid = [['.'] * w for _ in range(7)]
    on = set()
    for i, ch in enumerate(s):
        g = F35[ch]
        for j in range(5):
            for k in range(3):
                if g[j * 3 + k] == '1':
                    on.add((1 + i * 4 + k, 1 + j))
    for (x, y) in on:
        for dx in (-1, 0, 1):
            for dy in (-1, 0, 1):
                if 0 <= x + dx < w and 0 <= y + dy < 7:
                    grid[y + dy][x + dx] = edge
    for (x, y) in on:
        grid[y][x] = fg
    return [''.join(r) for r in grid]

