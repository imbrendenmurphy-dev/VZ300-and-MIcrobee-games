def cpu_bar(v):
    """v = 0..13 pixels of spare CPU"""
    img = [[PANEL_BG] * 16 for _ in range(2)]
    for y in range(2):
        img[y][0] = R; img[y][1] = G if (y + 57) % 2 else B
        for x in range(13):
            img[y][2 + x] = (Y if x < v else G) if True else B
            if x >= v:
                img[y][2 + x] = B if (x + y) % 2 else G
            elif v <= 3:
                img[y][2 + x] = R
    return [[pack(img[y][i:i + 4]) for i in range(0, 16, 4)] for y in range(2)]

