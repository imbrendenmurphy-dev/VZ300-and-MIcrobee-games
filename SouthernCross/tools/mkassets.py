def pack(px):
    """4 pixels (colour indices) -> byte, leftmost pixel in bits 7-6"""
    return (px[0] << 6) | (px[1] << 4) | (px[2] << 2) | px[3]

def dbrows(f, data, per=16):
    for i in range(0, len(data), per):
        f.write('        db ' + ','.join('$%02X' % b for b in data[i:i + per]) + '\n')

def emit(name, text):
    with open(os.path.join(OUT, name), 'w') as f:
        f.write('; generated by tools/mkassets.py - do not edit\n')
        f.write(text)

# ------------------------------------------------------------------ noise
def h2(ix, iy, seed):
    n = (ix * 374761393 + iy * 668265263 + seed * 1442695041) & 0xffffffff
    n = ((n ^ (n >> 13)) * 1274126177) & 0xffffffff
    return ((n ^ (n >> 16)) & 0xffff) / 65535.0

def vnoise(x, y, seed, py):
    """value noise, periodic in y with period py cells"""
    x0, y0 = math.floor(x), math.floor(y)
    fx, fy = x - x0, y - y0
    fx, fy = fx * fx * (3 - 2 * fx), fy * fy * (3 - 2 * fy)
    a = h2(x0, y0 % py, seed); b = h2(x0 + 1, y0 % py, seed)
    c = h2(x0, (y0 + 1) % py, seed); d = h2(x0 + 1, (y0 + 1) % py, seed)
    return (a + (b - a) * fx) * (1 - fy) + (c + (d - c) * fx) * fy

STRIP_ROWS = 256

def reef():
    """Coral Sea strip, 96 x 256, seamless top-to-bottom"""
    img = [[B] * PFW for _ in range(STRIP_ROWS)]
    for y in range(STRIP_ROWS):
        for x in range(PFW):
            # cells: 32x16, 16x8, 8x4 pixels (pixels are 1.5x taller than wide)
            n = (0.6 * vnoise(x / 26.0, y / 16.0, 3, STRIP_ROWS // 16)
                 + 0.3 * vnoise(x / 12.0, y / 8.0, 10, STRIP_ROWS // 8)
                 + 0.1 * vnoise(x / 5.0, y / 4.0, 16, STRIP_ROWS // 4))
            n -= 0.15 * math.exp(-((x - 48) / 18.0) ** 2)     # open channel
            if n > 0.70:
                c = Y
                if n > 0.74 and vnoise(x / 3.0, y / 2.0, 33, STRIP_ROWS // 2) > 0.62:
                    c = G                                       # scrub on the cay
            elif n > 0.645:
                c = G
                if (x + y) % 2 == 0 and vnoise(x / 3.0, y / 1.5, 9, 0x7fffffff) > 0.62:
                    c = Y
            elif n > 0.60:
                c = G if (x + y) % 2 == 0 else B
            elif n > 0.565:
                c = G if (x % 2 == 0 and y % 2 == 0) else B
            else:
                c = B
                if vnoise(x / 6.0, y / 2.0, 50, STRIP_ROWS // 2) > 0.74 and x % 4 != 3:
                    c = G if y % 3 == 0 else B
            img[y][x] = c
    # wrecked trawler on a sand bar
    wreck = ["..yyyy.....",
             ".yggggyy...",
             "yggyyggyyy.",
             ".yyyyyyyyyy",
             "...g..g...."]
    for j, row in enumerate(wreck):
        for i, ch in enumerate(row):
            if ch != '.':
                img[(60 + j) % STRIP_ROWS][76 + i] = CH[ch]
    # a lighthouse beacon on a cay
    beacon = ["..r..", ".yry.", "yyyyy", ".yry.", "..y.."]
    for j, row in enumerate(beacon):
        for i, ch in enumerate(row):
            if ch != '.':
                img[(170 + j) % STRIP_ROWS][10 + i] = CH[ch]
    return img

