# HUD shadow: 64 rows x 8 bytes (0-3 left panel, 4-7 right panel)
PANEL_BG = B
def hud_static():
    img = [[PANEL_BG] * 32 for _ in range(64)]      # 16 px left + 16 px right
    def put(x, y, c):
        if 0 <= x < 32 and 0 <= y < 64:
            img[y][x] = c
    def text(x, y, s, c=Y):
        for i, ch in enumerate(s):
            g = F35[ch]
            for j in range(5):
                for k in range(3):
                    if g[j * 3 + k] == '1':
                        put(x + i * 4 + k, y + j, c)
    # inner rules next to the playfield
    for y in range(64):
        put(15, y, R); put(16, y, R)
        put(17, y, G if y % 2 else B)
    # top and bottom caps
    for x in range(32):
        put(x, 0, R); put(x, 63, R)
    text(0, 2, "1UP", R)
    text(0, 22, "HI", R)
    text(0, 43, "STG", R)
    text(16 + 2, 50, "CPU", G)      # right panel x offset 16 (inner rule at 16)
    return img

def img_to_hud(img):
    out = []
    for y in range(64):
        row = img[y]
        out += [pack(row[i:i + 4]) for i in range(0, 32, 4)]
    return out

def glyph_byte_rows(ch, fg=Y, bg=PANEL_BG):
    g = F35[ch]
    return [pack([fg if g[j * 3 + k] == '1' else bg for k in range(3)] + [bg]) for j in range(5)]

def star_diagram(mask):
    """right panel rows 2..16 (15 rows) x 4 bytes, but leave pixel 0 (rule) alone:
       drawn in pixel columns 2..15 of the right panel"""
    img = [[PANEL_BG] * 16 for _ in range(15)]
    for y in range(15):
        img[y][0] = R
        img[y][1] = G if (y + 2) % 2 else B
    def plus(cx, cy, lit):
        c = Y if lit else G
        for (dx, dy) in ((0, 0), (1, 0), (-1, 0), (0, 1), (0, -1)):
            img[cy + dy][cx + dx] = c
        if not lit:
            img[cy][cx] = B
    # Southern Cross: N, W, E, S stars around the ship (centre)
    plus(9, 1, mask & 1)      # gamma (top)
    plus(4, 6, mask & 2)      # delta? (left)
    plus(14, 5, mask & 4)     # beta (right)
    plus(9, 12, mask & 8)     # alpha (bottom)
    # ship marker in the centre (always lit) - small epsilon/ship
    img[7][9] = R; img[6][9] = Y; img[8][8] = Y; img[8][10] = Y
    return [[pack(img[y][i:i + 4]) for i in range(0, 16, 4)] for y in range(15)]

