def flash_variant(rows):
    return [''.join('y' if c != '.' else '.' for c in r) for r in rows]

def sprite_bytes(rows, only=None):
    """-> (h, wb, [data for shift 0..3]) ; data = (mask,gfx) pairs"""
    h = len(rows)
    w = max(len(r) for r in rows)
    wb = (w + 3 + 3) // 4 if only is None else (w + only + 3) // 4
    out = []
    for s in (range(4) if only is None else [only]):
        d = []
        for r in rows:
            r = r.ljust(w, '.')
            px = ['.'] * s + list(r) + ['.'] * (wb * 4 - s - w)
            for b in range(wb):
                m = g = 0
                for k in range(4):
                    ch = px[b * 4 + k]
                    m <<= 2; g <<= 2
                    if ch == '.':
                        m |= 3
                    else:
                        g |= CH[ch]
                d += [m, g]
        out.append(d)
    return h, wb, out

