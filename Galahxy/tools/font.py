def rows(ch):
    out = []
    for r in GLYPHS.get(ch, GLYPHS['?']).split():
        v = 0
        for i, c in enumerate(r):
            if c == '#': v |= 4 >> i
        out.append(v)
    return out
def asm():
    L = ['font:']
    for c in range(32, 96):
        L.append('            db ' + ','.join(str(v) for v in rows(chr(c))) + '   ; ' + repr(chr(c)))
    return '\n'.join(L) + '\n'
