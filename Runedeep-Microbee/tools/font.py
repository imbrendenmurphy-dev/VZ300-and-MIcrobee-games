def load():
    lines = [l for l in GLYPHS.strip('\n').split('\n')]
    out = {}
    i = 0
    while i < len(lines):
        name = lines[i]
        rows = lines[i + 1:i + 11]
        assert all(len(r) == 8 for r in rows), name
        ch = ' ' if name == 'SPACE' else name
        out[ch] = bytes(int(r.replace('.', '0').replace('#', '1'), 2) for r in rows)
        i += 11
    return out


FONT = load()
assert len(FONT) == 95, len(FONT)


def glyphs():
    """96 glyphs for codes 32..127 (127 = a solid block)"""
    g = [FONT[chr(c)] for c in range(32, 127)]
    g.append(bytes([0xFF] * 10))
    return g
