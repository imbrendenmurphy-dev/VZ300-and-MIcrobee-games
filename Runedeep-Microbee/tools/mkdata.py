KINDS = ['A', 'B', 'D', 'G', 'V']          # kind 1..5
FACING = [(0, -1), (1, 0), (0, 1), (-1, 0)]  # N E S W
MAPW = 32
SPRITE_BASE = 0x4800                       # sprite index in the A block


def map_off(dx, dz, d):
    fx, fy = FACING[d]
    rx, ry = -fy, fx
    return (fy * dz + ry * dx) * MAPW + (fx * dz + rx * dx)


def gen_inc(sprite_squares, decor_faces):
    L = ['; generated by tools/mkdata.py - do not edit', 'NSLOT EQU %d' % len(V.SLOTS)]
    L.append('slot_tab:\t; c0, c1, key, dx, dz (near to far)')
    for s in V.SLOTS:
        L.append('\tdb %d,%d,%d,%d,%d\t; %s' % (s.c0, s.c1, s.key, s.dx & 255, s.dz, s.name()))
    L.append('slot_offp:	dw slot_off0,slot_off1,slot_off2,slot_off3')
    for d in range(4):
        L.append('slot_off%d:	dw ' % d + ','.join(str(map_off(s.dx, s.dz, d) & 0xFFFF) for s in V.SLOTS))
    L.append('NSQ EQU %d' % len(sprite_squares))
    L.append('sq_tab:\t; squares where sprites stand, far to near: dz, key, column shift')
    for dx, dz in sprite_squares:
        L.append('\tdb %d,%d,%d' % (dz, 4 * dz + 1, (dx * V.SPR_LAT[dz]) & 255))
    L.append('sq_offp:	dw sq_off0,sq_off1,sq_off2,sq_off3')
    for d in range(4):
        L.append('sq_off%d:	dw ' % d + ','.join(str(map_off(dx, dz, d) & 0xFFFF) for dx, dz in sprite_squares))
    L.append('NDF EQU %d' % len(decor_faces))
    L.append('df_tab:\t; front faces that can carry a decoration: slot, dz, column shift')
    for si, dz, sh in decor_faces:
        L.append('\tdb %d,%d,%d' % (si, dz, sh & 255))
    L.append('df_offp:	dw df_off0,df_off1,df_off2,df_off3')
    for d in range(4):
        L.append('df_off%d:	dw ' % d + ','.join(str(map_off(V.SLOTS[si].dx, dz, d) & 0xFFFF) for si, dz, sh in decor_faces))
    L.append('row24:	dw ' + ','.join(str(i * 24) for i in range(V.VH)))
    L.append('row40:	dw ' + ','.join(str((i + 1) * 40 + 1) for i in range(V.VH)))
    (BUILD / 'gen.inc').write_text('\n'.join(L) + '\n')


def sprite_squares():
    out = []
    for dz in (3, 2, 1):
        for dx in (-1, 1, 0):
            out.append((dx, dz))
    return out


def decor_faces():
    out = []
    for si, s in enumerate(V.SLOTS):
        if s.kind == 'F' and 1 <= s.dz <= 3 and abs(s.dx) <= 1:
            w = (s.x1 - s.x0) // 8
            out.append((si, s.dz, s.dx * w))
    out.sort(key=lambda t: -t[1])
    return out


def colsets(D, theme, kind, blob, back=None):
    """the wall tile lists of one kind: one pointer per slot. Each column
    is full height: the face, and the floor (backdrop) above and below"""
    if back is None:
        back = W.floor_cells(theme)
    ptrs = []
    for s in V.SLOTS:
        if kind in 'DGV' and s.kind == 'S':
            ptrs.append(None)
            continue
        fc = W.face_cells(s, theme, kind)
        out = bytearray()
        for c in range(s.c0, s.c1):
            rows = sorted(r for (cc, r) in fc if cc == c)
            if not rows:
                out += bytes([0, 0])
                continue
            r0, r1 = rows[0], rows[-1]
            tl = []
            for r in range(V.VH):
                if r0 <= r <= r1:
                    pat, col = fc.get((c, r), (bytes(10), 0))
                else:
                    pat, col = back.get((c, r), (bytes(10), 0))
                tl.append(D.tile(pat, col))
            out += bytes([0, V.VH]) + bytes(t[0] for t in tl) + bytes(t[1] for t in tl) + bytes(t[2] for t in tl)
        ptrs.append(blob.put(bytes(out)))
    return ptrs




def main():
    import uiart
    import levels as LV
    import mklevel as ML
    gen_inc(sprite_squares(), decor_faces())
    with open(BUILD / 'gen.inc', 'a') as f:
        f.write('\n'.join(ML.sprite_inc() + uiart.inc_lines()) + '\n')
    ui = T.Blob()
    b14, _ = uiart.bank14()
    b15, _ = uiart.bank15()
    ui.put(b''.join(b14))
    ui.data += bytes(128 * 10 - len(ui.data))
    ui.put(b''.join(b15))
    (BUILD / 'UI.BNK').write_bytes(ui.bytes())
    ok = True
    for n, L in enumerate(LV.LEVELS):
        LV.check(L, n)
        ok &= ML.solve(L, n)
        A, B = ML.build_level(n, L)
        (BUILD / ('L%dA.BNK' % (n + 1))).write_bytes(A.bytes())
        (BUILD / ('L%dB.BNK' % (n + 1))).write_bytes(B.bytes())
    print('all levels finishable' if ok else 'SOME LEVEL CANNOT BE FINISHED')


if __name__ == '__main__':
    main()
