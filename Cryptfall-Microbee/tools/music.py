"""CRYPTFALL music (original, VIBED BY BPM 2026) for the two-voice pin-pulse
beeper engine (127 T loop at 3.375 MHz).  One time unit is one 50 Hz field.
Every note ends with a silent field, so notes stay separate and gritty.
There is no tune in the crypts themselves: the title, the fanfares and the
ending have music, the caves have their own sounds.  Writes src/music.inc."""
import os

HERE = os.path.dirname(os.path.abspath(__file__))
LOOPRATE = 3375000.0 / 127
NAMES = {'C': 0, 'C#': 1, 'D': 2, 'D#': 3, 'E': 4, 'F': 5, 'F#': 6, 'G': 7, 'G#': 8, 'A': 9, 'A#': 10, 'B': 11}


def nidx(tok):
    return (int(tok[-1]) - 2) * 12 + NAMES[tok[:-1]] + 1


def build(out):
    L = ['; generated by tools/music.py', 'notetab:']
    steps = [0]
    for i in range(1, 73):
        f = 65.406 * 2 ** ((i - 1) / 12.0)
        steps.append(int(round(f * 65536 / LOOPRATE)))
    L.append('    dw ' + ','.join(str(s) for s in steps))

    def db(bs):
        bs = list(bs)
        for i in range(0, len(bs), 16):
            L.append('    db ' + ','.join('$%02X' % b for b in bs[i:i + 16]))

    def song(name, step, *chans, loop=False, blip=0):
        for ci, txt in enumerate(chans):
            ev = []
            for t in txt.split():
                if t == '|':
                    continue
                if t == '-':
                    ev[-1][1] += step
                elif t == 'r':
                    ev.append([0, step])
                elif blip:
                    ev.append([nidx(t), blip])
                    ev.append([0, step - blip])
                else:
                    ev.append([nidx(t), step])
            # merge rests
            m = []
            for n, d in ev:
                if m and n == 0 and m[-1][0] == 0:
                    m[-1][1] += d
                else:
                    m.append([n, d])
            o = []
            for n, d in m:
                while d > 255:
                    o += [n, 255]
                    d -= 255
                o += [n, d]
            o.append(0xFE if loop else 0xFF)
            L.append('mus_%s_%d:' % (name, ci))
            db(o)

    # title: "Cryptfall" - a creeping D minor march
    title = """
D4 r F4 A4 D5 - A4 r | C5 r A4 F4 E4 - - r
D4 r F4 A4 D5 - F5 r | E5 - C#5 - A4 - - r
A#4 r D5 F5 A#5 - A5 G5 | F5 r D5 r A4 - - r
G4 r A#4 D5 G5 - F5 E5 | D5 - - r D4 - - r
A4 r A4 r D5 - C5 A#4 | A4 r F4 r D4 - - r
G4 r G4 r C5 - A#4 A4 | G4 r E4 r C#4 - - r
D4 r F4 A4 D5 - A4 r | A#4 r G4 r E4 - C#4 r
D4 - - r A3 - - r | D4 - - - - - - r
"""
    bass = """
D2 r A2 r D2 r A2 r | F2 r C3 r A2 r E2 r
D2 r A2 r D2 r A2 r | A2 r E3 r A2 r C#3 r
A#2 r F3 r A#2 r F3 r | D3 r A2 r D2 r A2 r
G2 r D3 r G2 r D3 r | D2 r A2 r D2 - - r
D2 r r D2 F2 r r F2 | D2 r r D2 A2 r r A2
C3 r r C3 E2 r r E2 | A2 r r A2 A2 r C#3 r
D2 r A2 r D2 r A2 r | G2 r D3 r A2 r A2 r
D2 r A2 r F2 r A2 r | D2 - - - - - - r
"""
    song('title', 9, title, bass, loop=True)
    song('ready', 6, 'D4 F4 A4 D5 - - r', 'D2 r D3 r D2 D3 r')
    song('clear', 6, 'D5 F#5 A5 D6 - F#6 - A6 - - - r D6 - - - r',
         'D3 D3 D2 D3 D2 D3 D2 D3 A2 A3 A2 A3 D3 - - r')
    song('over', 14, 'A4 - G4 - F4 - E4 - - - D4 - - - r', 'D3 - - - A#2 - - - A2 - - - D2 - - r')
    song('won', 7, 'D5 r D5 F#5 A5 - F#5 A5 D6 - - r B5 r G5 B5 D6 - - r A5 - F#5 - D5 - - - - r',
         'D3 r A2 r D3 r A2 r D3 r A3 r G2 r D3 r G2 r D3 r A2 r A3 r D3 - - - - r')
    song('hi', 8, 'A4 D5 F5 A5 - F5 A5 D6 - - - r', 'D3 r A2 r D3 r A2 r D2 - - r')
    open(out, 'w').write('\n'.join(L) + '\n')


if __name__ == '__main__':
    build(os.path.join(HERE, '..', 'src', 'music.inc'))
