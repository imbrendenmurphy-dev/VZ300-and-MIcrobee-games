SRC = os.path.join(ROOT, 'src')
sys.path.insert(0, HERE)
os.makedirs(BUILD, exist_ok=True)

import art as A

import tiles as TL


def cells(bits):
    """a 16 wide x 20 high picture -> 40 bytes: cells TL, TR, BL, BR of 10 rows"""
    out = bytearray()
    for cy, cx in ((0, 0), (0, 1), (1, 0), (1, 1)):
        for y in range(10):
            v = 0
            for x in range(8):
                if bits[cy * 10 + y, cx * 8 + x]:
                    v |= 128 >> x
            out.append(v)
    return bytes(out)


def dbs(L, data):
    for i in range(0, len(data), 16):
        L.append('\tdb ' + ','.join('$%02X' % b for b in data[i:i + 16]))


def build_gfx():
    S = A.slots()
    E = ['; generated by tools/build.py from tools/tiles.py: tile and picture numbers']
    for i, (n, ch, art, fl) in enumerate(TL.TILES):
        E.append('T_%s equ %d' % (n, i))
    E.append('T_ACTIVE equ %d' % TL.T_ACTIVE)
    E.append('NTILES equ %d' % len(TL.TILES))
    for i, n in enumerate(TL.ARTS):
        E.append('ART_%s equ %d' % (n, i))
    E.append('NARTS equ %d' % len(TL.ARTS))
    for i, n in enumerate(A.POSES):
        E.append('POSE_%s equ %d' % (n, i))
    for n, v in (('F_ROUND', 1), ('F_HARD', 2), ('F_ENEMY', 4), ('F_SOFT', 8), ('F_PICKUP', 16), ('F_GEM', 32), ('F_SOLID', 64)):
        E.append('%s equ %d' % (n, v))
    D = ['; generated by tools/build.py: the picture library (40 bytes a frame), fonts, tile table']
    D.append('art_tab:')
    for n in TL.ARTS:
        D.append('\tdw an_%s' % n)
    for n in TL.ARTS:
        s = S[n]
        D.append('an_%s:' % n)
        D.append('\tdw ' + ','.join('fr_%s_%d' % (n, k) for k in range(len(s.frames))))
        for k, f in enumerate(A.tall(s.frames)):
            D.append('fr_%s_%d:' % (n, k))
            dbs(D, cells(f))
    D.append('font_data:')
    for g in A.font_glyphs():
        dbs(D, g)
    for g in A.map_glyphs():
        dbs(D, g)
    D.append('; each tile: its picture ($FF none) and the colours of its four cells')
    D.append('tile_def:')
    for n, ch, art, fl in TL.TILES:
        if art is None:
            D.append('\tdb $FF,0,0,0,0')
        else:
            c = TL.COLOURS.get(n) or S[art].cols
            D.append('\tdb %d,%s' % (TL.ART[art], ','.join(str(x) for x in c)))
    D.append('; the pictures the title and help pages use')
    D.append('fe_slots:')
    D.append('\tdb ' + ','.join(str(TL.ART[n]) for n in TL.FE_SLOTS) + ',$FF')
    open(os.path.join(SRC, 'tiles.inc'), 'w').write('\n'.join(E) + '\n')
    open(os.path.join(SRC, 'gfxdata.inc'), 'w').write('\n'.join(D) + '\n')
    F = ['; generated by tools/build.py: flags of each tile (64 entries)']
    fl = [f for n, ch, art, f in TL.TILES] + [0] * (64 - len(TL.TILES))
    dbs(F, bytes(fl))
    open(os.path.join(SRC, 'tflags.inc'), 'w').write('\n'.join(F) + '\n')
    print('gfx: %d pictures, %d tiles' % (len(TL.ARTS), len(TL.TILES)))


def build_hidef():
    import hiscore
    L = ['; generated by tools/build.py: the roll as it starts (see tools/hiscore.py)']
    dbs(L, hiscore.default_record()[:106])
    open(os.path.join(SRC, 'hidef.inc'), 'w').write('\n'.join(L) + '\n')


def assemble():
    build_hidef()
    zasm = os.path.join(HERE, 'zasm.py')
    subprocess.check_call([sys.executable, os.path.join(HERE, 'fixjr.py')])
    subprocess.check_call([sys.executable, zasm, 'shell.asm'], cwd=SRC)


def disk():
    import build_disk as BD
    import caves
    import mkdemo
    caves.build()
    demo = os.path.join(BUILD, 'DEMO.DAT')
    if os.path.exists(demo):
        os.remove(demo)
    BD.main()                   # a disk without the demo, to record the demo on
    mkdemo.build()
    BD.main()
    # the same disk without SHELL.SYS: boots to the A> prompt, type CRYPT
    BD.main(out=os.path.join(BUILD, 'CRYPTCMD.DS8'), autorun=False)


if __name__ == '__main__':
    if '--quick' not in sys.argv:
        build_gfx()
        import music
        music.build(os.path.join(SRC, 'music.inc'))
        if os.path.exists(os.path.join(HERE, 'title.py')):
            import title
            title.build()
    assemble()
    disk()
