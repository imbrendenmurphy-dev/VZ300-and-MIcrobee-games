def g8(rows):
    return bytes(int(r, 2) for r in rows)


# ---- the screen's cells are 10 lines high (40 x 25 cells = 320 x 250, a full
# PAL picture).  The pictures are drawn 16 x 16 and made 16 x 20 here: each
# quarter of a picture gains one line, the line whose repeat shows least
# (the same lines in every frame of a picture, so nothing jumps about).
GLH = 10


def rowmap(frames):
    out = []
    for band in range(4):
        best = None
        for r in (band * 4 + 1, band * 4 + 2, band * 4, band * 4 + 3):
            c = sum(int((f[r] != f[(r + 1) % 16]).sum()) for f in frames)
            if best is None or c < best[0]:
                best = (c, r)
        for r in range(band * 4, band * 4 + 4):
            out.append(r)
            if r == best[1]:
                out.append(r)
    return out


def tall(frames):
    """16 x 16 frames -> 20 x 16"""
    rm = rowmap(frames)
    return [f[rm] for f in frames]


def text10(g):
    """a font glyph of 8 lines, set a line down in its 10-line cell"""
    return bytes([0]) + bytes(g) + bytes([0])


def pic10(g):
    """8 lines of a picture -> 10 (lines 2 and 6 doubled)"""
    return bytes(g[i] for i in (0, 1, 2, 2, 3, 4, 5, 6, 6, 7))


