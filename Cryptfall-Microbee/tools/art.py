def inbox(k):
    def f(x, y):
        d = max(abs(x - 7.5), abs(y - 7.5))
        return int(d + k * 2) % 4 < 2
    return mk(f)


def magic(k):
    # an enchanted grate: brick with a rune that crawls when it is awake
    a = wall()
    for i in range(16):
        x = (i * 3 + k * 4) % 16
        a[i, x] = not a[i, x]
        a[i, (x + 8) % 16] = not a[i, (x + 8) % 16]
    return a


def slime(k):
    def f(x, y):
        # bubbling ectoplasm: blobs with dark bubbles that drift
        bx, by = (x + k * 3) % 8, (y + k * 5) % 8
        bub = (bx - 3.5) ** 2 + (by - 3.5) ** 2 < 3.2 and hsh(x // 8, y // 8, 3 + k) % 2 == 0
        bub2 = (x - 11 + k * 2) ** 2 + (y - 4 - k) ** 2 < 2.5
        return not (bub or bub2) and not ((x + y) % 7 == 0 and hsh(x, y, k) % 3 == 0)
    return mk(f)


def expl(k):
    # a burst of dust and stone, three sizes
    def f(x, y):
        dx, dy = x - 7.5, y - 7.5
        r = (dx * dx + dy * dy) ** 0.5
        ang = np.arctan2(dy, dx)
        spike = np.cos(ang * 6 + k) * 1.6
        if k == 0:
            return r < 4 + spike * 0.6 and hsh(x, y, 1) % 5 != 0
        if k == 1:
            return r < 7.3 + spike and (r > 2.2 or hsh(x, y, 2) % 2) and hsh(x, y, 3) % 6 != 0
        return 4.5 < r < 8.2 + spike and hsh(x, y, 4) % 3 != 0
    return mk(f)


