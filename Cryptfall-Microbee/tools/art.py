def font_glyphs():
    out = []
    for i in range(64):
        ch = chr(32 + i)
        if ch in ICON:
            out.append(text10(ICON[ch]))
            continue
        if ch in RF:
            out.append(text10(bytes([int(r.replace('#', '1').replace('.', '0').ljust(8, '0'), 2) for r in RF[ch].split()] + [0])))
            continue
        rows = FD.get(ch)
        if rows is None:
            out.append(bytes(10))
            continue
        out.append(text10(bytes([int(r, 2) << 2 for r in rows.split()] + [0])))
    return out


def map_glyphs():
    """16 quarter-block characters for the pause map: bit 0 top left, 1 top
    right, 2 bottom left, 3 bottom right (each quarter drawn a pixel short,
    so neighbouring tiles stay apart)"""
    out = []
    for b in range(16):
        g = []
        for y in range(10):
            v = 0
            if y not in (4, 9):
                top = y < 5
                if b & (1 if top else 4):
                    v |= 0xE0
                if b & (2 if top else 8):
                    v |= 0x0E
            g.append(v)
        out.append(bytes(g))
    return out
