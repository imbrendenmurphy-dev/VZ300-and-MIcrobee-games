def twinkle(base, glints, stars):
    out = []
    for k in range(4):
        a = base.copy()
        for x, y in glints[k]:
            a[y, x] = not a[y, x]
        tx, ty = stars[k]
        for dx, dy in ((0, 0), (-1, 0), (1, 0), (0, -1), (0, 1)):
            if 0 <= ty + dy < 16 and 0 <= tx + dx < 16:
                a[ty + dy, tx + dx] = True
        out.append(a)
    return out


