"""CRYPTFALL art: every tile is 16 x 16 pixels = 2 x 2 character cells of
8 x 8, each cell with one ink and one paper colour.  Papers are always
black, so the picture reads the same on a monochrome monitor (which shows
only the pixel bits).   VIBED BY BPM 2026
"""
import numpy as np

BLACK, RED, GREEN, BROWN, BLUE, MAGENTA, CYAN, GREY = range(8)
DGREY, BRED, BGREEN, YELLOW, BBLUE, BMAGENTA, BCYAN, WHITE = range(8, 16)


def art(rows):
    assert len(rows) == 16, len(rows)
    for r in rows:
        assert len(r) == 16, (r, len(r))
    return np.array([[c == '#' for c in r] for r in rows], bool)


def mirror(a):
    return a[:, ::-1].copy()


def hsh(x, y, s=0):
    v = (x * 374761393 + y * 668265263 + s * 2246822519) & 0xFFFFFFFF
    v = ((v ^ (v >> 13)) * 1274126177) & 0xFFFFFFFF
    return (v ^ (v >> 16)) & 0xFFFF


def mk(fn):
    return np.array([[bool(fn(x, y)) for x in range(16)] for y in range(16)], bool)


# ------------------------------------------------------------ scenery
def dirt():
    # loose grave earth: a sparse scatter of crumbs, so everything solid
    # stands out against it (on a monochrome monitor too)
    def f(x, y):
        if (x + 2 * y) % 4 == 0 and hsh(x, y, 7) % 4 != 0:
            return True
        return hsh(x, y, 9) % 100 < 5
    a = mk(f)
    for (px, py) in ((3, 4), (11, 2), (7, 10), (13, 12), (1, 13)):
        a[py:py + 2, px:px + 3] = False
        a[py, px + 1] = True
        a[py + 1, px:px + 3] = True
    return a


def wall():
    # castle brick: two courses a cell, mortar lines dark
    def f(x, y):
        row = y // 4
        if y % 4 == 3:
            return False
        off = 0 if row % 2 == 0 else 4
        if (x + off) % 8 == 7:
            return False
        if y % 4 == 0 and (x + off) % 8 == 0:
            return False        # chipped corner
        return True
    return mk(f)


def cracked():
    a = wall()
    # a jagged crack from the top to the bottom and some missing chips
    path = [(7, 0), (7, 1), (8, 2), (8, 3), (9, 4), (8, 5), (7, 6), (7, 7), (6, 8), (7, 9), (8, 10), (8, 11), (9, 12), (9, 13), (8, 14), (8, 15)]
    for x, y in path:
        a[y, x] = False
        a[y, x - 1] = False
    for x, y in ((3, 5), (4, 5), (12, 9), (13, 9), (12, 10), (2, 13), (3, 13), (13, 1), (12, 2)):
        a[y, x] = False
    return a


def steel():
    # an iron-bound block: frame, rivets
    def f(x, y):
        if x in (0, 15) or y in (0, 15):
            return True
        if x in (1, 14) or y in (1, 14):
            return False
        if (x in (3, 12)) and (y in (3, 12)):
            return False
        if x in (2, 13) or y in (2, 13):
            return True
        return ((x + y) % 4 == 0) or ((x - y) % 4 == 0)
    return mk(f)


def cover(k):
    # the stone shutter that hides a crypt before it is revealed
    def f(x, y):
        return ((x + y + k * 2) % 8 < 4) != (y % 8 < 1)
    return mk(f)


