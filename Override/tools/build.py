LATCH_GAME = 0x09


def db_lines(data, per=16):
    out = []
    for i in range(0, len(data), per):
        out.append('            db ' + ','.join('$%02X' % b for b in data[i:i + per]))
    return '\n'.join(out)


def write(name, text):
    p = os.path.join(GEN, name)
    old = open(p).read() if os.path.exists(p) else None
    if old != text:
        open(p, 'w').write(text)


# ---------------------------------------------------------------- copy code
def gen_copy():
    """unrolled stack copy: back buffer (40-byte rows, +4 guard) -> video RAM,
    one effects sample every three 16-byte chunks"""
    BB, BBW = 0xB800, 40
    L = ['; generated by tools/build.py - the field ISR screen copy']
    def chunk(src, dst):
        L.append('            ld sp,$%04X' % src)
        L.append('            pop af\n            pop bc\n            pop de\n            pop hl')
        L.append("            exx\n            ex af,af'")
        L.append('            pop af\n            pop bc\n            pop de\n            pop hl')
        L.append('            ld sp,$%04X' % (dst + 16))
        L.append('            push hl\n            push de\n            push bc\n            push af')
        L.append("            exx\n            ex af,af'")
        L.append('            push hl\n            push de\n            push bc\n            push af')
    ns = [0]
    def sample():
        # precomputed by sound_tick: one latch value a sample (26 T)
        # the next sample from the ring (59 T)
        L.append('            ld hl,snd_rd\n            ld a,(hl)\n            inc (hl)\n            ld l,a')
        L.append('            ld h,HIGH(SNDBUF)\n            ld a,(hl)\n            ld (LATCH),a')
        ns[0] += 1
    L.append('copy_hud:')
    for r in range(0, 10):
        for h in (0, 16):
            chunk(BB + r * BBW + 4 + h, 0x7000 + r * 32 + h)
    L.append('copy_view:')
    n = 0
    for r in range(10, 64):
        for h in (0, 16):
            chunk(BB + r * BBW + 4 + h, 0x7000 + r * 32 + h)
            n += 1
            if n % 4 == 0: sample()
    L.append('            jp isr_back')
    L.append('ISR_NSND    equ %d' % ns[0])
    write('copy.inc', '\n'.join(L) + '\n')


