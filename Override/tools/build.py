def gen_sfx():
    L = ['; generated sound effects']
    for i, (n, p, seq) in enumerate(SFX):
        L.append('SFX_%s equ %d' % (n, i))
    L.append('sfx_tab:    dw ' + ','.join('sfx_%s' % n.lower() for n, p, s in SFX))
    L.append('sfx_prio:   db ' + ','.join(str(p) for n, p, s in SFX))
    for n, p, seq in SFX:
        b = bytearray()
        for fr, f, m, noise in seq:
            s = step(f)
            b += bytes([fr, s & 255, s >> 8, m | (0x80 if noise else 0)])
        b.append(0)
        L.append('sfx_%s:' % n.lower())
        L.append(db_lines(b))
    write('sfx.inc', '\n'.join(L) + '\n')


# ---------------------------------------------------------------- tables
def bcd(n):
    s = '%04d' % n
    return int(s[2:], 16), int(s[:2], 16)


def gen_tables():
    L = ['; generated: droid types, weapons, shot velocities, tile attributes']
    L.append('types:')
    for num, name, en, spd, w, aggr, blurb in roster.ROSTER:
        lo, hi = bcd(roster.score_value(num))
        L.append('            db %d,%d,%d,%d,%d,%d,%d,$%02X,$%02X,%d   ; %03d %s' %
                 (num & 255, num >> 8, en, spd, w, aggr, roster.cls(num), lo, hi,
                  1 if num in roster.IMMUNE else 0, num, name))
    L.append('weapons:')
    for k in range(len(roster.WEAPONS)):
        sp, dmg, rel, life = roster.WEAPONS[k]
        L.append('            db %d,%d,%d,%d' % (sp, dmg, rel, life))
    L.append('shotvel:')
    dirs = [(1, 0), (0.7071, 0.7071), (0, 1), (-0.7071, 0.7071), (-1, 0), (-0.7071, -0.7071), (0, -1), (0.7071, -0.7071)]
    for s in range(8):
        row = []
        for dx, dy in dirs:
            vx = int(round(dx * s * 4)); vy = int(round(dy * s * 4 * 2 / 3))
            row += [vx & 255, vy & 255]
        L.append('            db ' + ','.join('$%02X' % v for v in row))
    L.append('tattr:')
    L.append(db_lines(bytes(gfx.attr)))
    L.append('type_nums:  dw ' + ','.join(str(r[0]) for r in roster.ROSTER))
    L.append('font:')
    L.append(db_lines(gfx.font_bytes()))
    write('tables.inc', '\n'.join(L) + '\n')


def gen_consts(build_id):
    L = ['; generated constants']
    for k in dir(gfx):
        if (k.startswith('T_') or k.startswith('A_')) and isinstance(getattr(gfx, k), int):
            L.append('%-12s equ %d' % (k, getattr(gfx, k)))
    for i, n in enumerate(['W_NONE', 'W_ZAP', 'W_LASER', 'W_TWIN', 'W_RAPID', 'W_CANNON', 'W_SCATTER', 'W_DISRUPT']):
        L.append('%-12s equ %d' % (n, i))
    L.append('NTYPES      equ %d' % roster.NTYPES)
    L.append('DIS_DAMAGE  equ %d' % roster.DISRUPT_DAMAGE)
    L.append('BUILD_ID    equ $%04X' % build_id)
    write('consts.inc', '\n'.join(L) + '\n')


# ---------------------------------------------------------------- sprites
def interleaved(rows, h=8, wb=4):
    """4 phases x h rows x wb x (mask, data)"""
    out = bytearray()
    for p in range(4):
        for r in rows:
            rr = ([-1] * p + r + [-1] * 16)[:wb * 4]
            d = pack_row([0 if c < 0 else c for c in rr])
            m = pack_row([3 if c < 0 else 0 for c in rr])
            for k in range(wb):
                out += bytes([m[k], d[k]])
    return bytes(out)


def gen_gfxdata():
    L = ['; generated graphics for upper bank 1']
    L.append('            align 256')
    L.append('tiles_norm:')
    L.append(db_lines(gfx.tileset_bytes(False)))
    L.append('            align 256')
    L.append('tiles_dim:')
    L.append(db_lines(gfx.tileset_bytes(True)))
    L.append('            align 256')
    L.append('expld:')
    for f in gfx.EXPL:
        rows = [[-1 if ch == '.' else gfx.C[ch] for ch in ln] for ln in f]
        L.append(db_lines(interleaved(rows)))
    L.append('dimg:       ; per type: enemy then player colours; 32 data + 32 mask bytes, phase 0')
    for num, name, *_ in roster.ROSTER:
        for band, digit in ((3, 1), (1, 2)):
            rows = gfx.droid_image(num, band, digit)
            d, m = gfx.sprite_phase0(rows)
            L.append(db_lines(d + m))
    L.append('tnames:')
    for num, name, *_ in roster.ROSTER:
        L.append('            db "%s"' % name.ljust(11)[:11] + ',0')
    write('gfxdata.inc', '\n'.join(L) + '\n')


# ---------------------------------------------------------------- files
def chunk(m, dest, data):
    data = bytes(data)
    return bytes([m, dest & 255, dest >> 8, len(data) & 255, len(data) >> 8]) + data


def datfile(name, chunks, sym, build_id):
    chunks = list(chunks) + [chunk(7, sym['dat_id'], bytes([build_id & 255, build_id >> 8]))]
    d = b''.join(chunks) + b'\0'
    d += b'\0' * ((-len(d)) % 512)
    open(os.path.join(SD, name + '.DAT'), 'wb').write(d)
    return len(d)


def assemble(src, extra_sym=None):
    a = zasm.Asm()
    if extra_sym:
        a.sym.update(extra_sym)
    out = a.assemble(os.path.join(SRC, src))
    return a, out


def span(out, lo, hi):
    keys = [k for k in out if lo <= k < hi]
    if not keys: return None, b''
    a, b = min(keys), max(keys) + 1
    return a, bytes(out.get(i, 0) for i in range(a, b))


def ship_files(sym, fsym, build_id):
    import music, fedata
    total = 0
    for si, spec in enumerate(ships.SHIPS):
        decks = ships.make_ship(spec)
        # ship header
        h = bytearray(sym['SISZ'])
        nm = spec['name'].encode()[:15]
        h[0:len(nm)] = nm
        h[16] = len(decks); h[17] = spec['start']; h[18] = len(spec['shafts'])
        for k, sx in enumerate(spec['shafts']): h[19 + k] = sx
        for di, d in enumerate(decks):
            o = 24 + di * 18
            n = d.name.encode()[:12]
            h[o:o + len(n)] = n
            h[o + 13] = d.W; h[o + 14] = d.H; h[o + 15] = d.off; h[o + 16] = len(d.droids)
            m = 0
            for s in d.shaft_of: m |= 1 << s
            h[o + 17] = m
        # the ship's look and sound: its tile theme, its two tunes, its silhouette
        th = spec['theme']
        tunes = music.gship_bytes(spec['tunes'], sym['GSBUF'])
        assert len(tunes) <= sym['GSBUF_SZ'], (spec['name'], len(tunes))
        art = fedata.ship_shifts(fedata.SHIP_ARTS[th]())
        assert len(art) == 0xE800 - fsym['SHIPART']
        total += datfile('OV%d' % (si + 1), [chunk(7, sym['shipinfo'], h),
                                             chunk(7, sym['tiles_norm'], gfx.tileset_bytes(False, th)),
                                             chunk(7, sym['tiles_dim'], gfx.tileset_bytes(True, th)),
                                             chunk(7, sym['GSBUF'], tunes),
                                             chunk(3, fsym['SHIPART'], art)], sym, build_id)
        for di, d in enumerate(decks):
            mp = bytearray(64 * d.H)
            for y in range(d.H):
                for x in range(d.W):
                    mp[y * 64 + x] = d.tiles[y][x]
            info = bytearray(sym['DISZ'])
            n = d.name.encode()[:12]
            info[0:len(n)] = n
            info[13] = d.W; info[14] = d.H; info[15] = len(d.nodes); info[16] = len(d.droids)
            info[17] = len(d.lifts)
            for k, ((tx, ty), s) in enumerate(zip(d.lifts, d.shaft_of)):
                info[18 + k * 3:21 + k * 3] = bytes([s, tx, ty])
            for k, (t, w) in enumerate(d.droids):
                info[27 + k * 2] = t; info[28 + k * 2] = w
            info[59] = len(d.consoles)
            for k, (cx, cy) in enumerate(d.consoles[:2]):
                info[60 + k * 2] = cx; info[61 + k * 2] = cy
            wp = bytearray()
            for i, (x, y) in enumerate(d.nodes):
                adj = d.adj[i][:5]
                wp += bytes([x, y, len(adj)] + adj + [0] * (5 - len(adj)))
            assert len(wp) <= 80 * 8
            total += datfile('OV%dD%d' % (si + 1, di), [chunk(7, 0xC200, mp), chunk(7, sym['dinfo'], info),
                                                       chunk(7, sym['WPT'], wp)], sym, build_id)
    return total


def main():
    build_id = (int(time.time()) & 0xFFFF) | 1
    gen_copy(); gen_sfx(); gen_tables(); gen_consts(build_id); gen_gfxdata()
    import music, fedata
    write('songs.inc', music.asm())
    write('gsongs.inc', music.gasm())
    write('fedata.inc', fedata.asm())
    write('bigfont.inc', fedata.bigfont_asm())
    write('ovsongs.inc', music.ov_asm())
    write('ovdata.inc', fedata.ov_asm())
    a, out = assemble('main.asm')
    sym = a.sym
    lo, code = span(out, 0x8000, sym['VARS'])
    assert lo == 0x8000
    ulo, upper1 = span(out, 0xB800, 0x10000)
    print('main code $8000-$%04X (%d bytes free)' % (sym['code_end'] - 1, sym['VARS'] - sym['code_end']))
    print('upper bank 1 data $%04X-$%04X (%d free below WPT)' % (ulo, ulo + len(upper1) - 1, sym['WPT'] - (ulo + len(upper1))))
    # front end (upper bank 0) assembled against the main symbols
    ms = ['; generated: main program symbols for the front end']
    for k, v in sorted(sym.items()):
        if '.' in k: continue
        ms.append('%-24s equ $%04X' % (k, v & 0xFFFF))
    write('mainsym.inc', '\n'.join(ms) + '\n')
    fa, fout = assemble('fe.asm')
    flo, fe = span(fout, 0xB800, 0xF000)
    assert flo == 0xB800, hex(flo or 0)
    print('front end $B800-$%04X (%d free)' % (0xB800 + len(fe) - 1, 0xE800 - 0xB800 - len(fe)))
    # check the front end's jump table matches what main expects
    for k in ('fe_main', 'fe_transfer', 'fe_lift', 'fe_console', 'fe_shipcard', 'fe_shipdone', 'fe_gameover', 'fe_ending'):
        assert fa.sym['j_' + k] == sym[k], k
    clo, code2 = span(out, sym['CODE2'], sym['DIV6'])
    assert clo == sym['CODE2']
    print('play code $%04X-$%04X (%d free below DIV6)' % (clo, clo + len(code2) - 1, sym['DIV6'] - clo - len(code2)))
    n = datfile('OVCOM', [chunk(7, ulo, upper1), chunk(3, 0xB800, fe), chunk(7, clo, code2)], sym, build_id)
    print('OVCOM.DAT %d bytes' % n)
    # the overlay (intro, title, attract pages, cards): assembled against
    # main + front-end symbols, into low bank 3 below the sprite cache
    fs = ['; generated: front-end symbols for the overlay']
    for k, v in sorted(fa.sym.items()):
        if '.' in k or k in sym: continue
        fs.append('%-24s equ $%04X' % (k, v & 0xFFFF))
    write('fesym.inc', '\n'.join(fs) + '\n')
    oa, oout = assemble('ovl.asm')
    olo, ov = span(oout, 0x4000, 0x6000)
    assert olo == 0x4000
    print('overlay $4000-$%04X (%d free)' % (0x4000 + len(ov) - 1, 0x2000 - len(ov)))
    print('OVTTL.DAT %d bytes' % datfile('OVTTL', [chunk(3, 0x4000, ov)], sym, build_id))
    old = os.path.join(SD, 'OVATT.DAT')
    if os.path.exists(old): os.remove(old)
    print('ship files %d bytes' % ship_files(sym, fa.sym, build_id))
    hdr = b'VZF0' + b'OVERRIDE'.ljust(17, b'\0') + bytes([0xF1, 0x00, 0x80])
    open(os.path.join(SD, 'OVERRIDE.VZ'), 'wb').write(hdr + code)
    print('OVERRIDE.VZ %d bytes' % (len(code) + 24))
    with open(os.path.join(BUILD, 'override.sym'), 'w') as f:
        for k, v in sorted(sym.items(), key=lambda x: x[1]):
            f.write('%04X %s\n' % (v & 0xFFFF, k))
        for k, v in sorted(fa.sym.items(), key=lambda x: x[1]):
            if k not in sym: f.write('%04X %s\n' % (v & 0xFFFF, k))
        for k, v in sorted(oa.sym.items(), key=lambda x: x[1]):
            if k not in sym and k not in fa.sym: f.write('%04X %s\n' % (v & 0xFFFF, k))


if __name__ == '__main__':
    main()
