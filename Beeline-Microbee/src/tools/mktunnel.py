#!/usr/bin/env python3
"""
mktunnel.py - the inside of a tunnel, seen from the road, for the sky rows
(screen rows 1-9 above the horizon row 10)  -> build/tunnel.inc, tunnel.bin
ViBED by BPM 2026

Perspective from the vanishing point: ceiling (sparse dither) between two
bright diagonals, walls (checker) either side, the far end black.  Ceiling
lights run down the centre towards you in 4 phases (animated by swapping the
codes of the centre columns as the car moves).

Characters go to PCG banks 13 and 14 (index i -> code 80h + (i & 127),
bank 13 + (i >> 7)); index 0 is blank.
  TUNI   9 x 64 character indices of the picture (phase 0)
  TUNL   4 phases x 9 rows x LCN centre columns (from column LC0)
"""
import os, sys

W, H = 512, 144          # rows 1-9: screen lines 16..159
VX, VY = 256, 128        # vanishing point (local y; horizon line 160 = local 144)
FW, FH = 64, 32          # far end rectangle: x 224..287, local y 112..143
LC0, LCN = 29, 6         # light columns

def classify(x, y, phase):
    dx, dy = x + 0.5 - VX, y + 0.5 - VY
    if abs(dx) < FW / 2 and dy > -FH / 2:
        return 0                                      # far end: black
    # lights on the ceiling centre line
    for i in range(1, 9):
        z = 2.0 * (i + phase / 4.0) + 0.6
        ly = VY - 16 * (FH / 2) / z / 1.0 * 1.0       # ceiling at depth z
        ly = VY - (FH / 2) * 16.0 / z
        hw = 34.0 / z
        hh = max(0.6, 7.0 / z)
        if abs(dx) <= hw and abs(y + 0.5 - ly) <= hh:
            return 1
    ceiling = dy < 0 and abs(dx) / (FW / 2) < abs(dy) / (FH / 2)
    # bright diagonals between ceiling and walls
    if dy < 0:
        r = abs(dx) / (FW / 2) - abs(dy) / (FH / 2)
        d = abs(r) * (FH / 2)
        if d < 1.2: return 1
    if ceiling:
        return 1 if (y % 4 == 0 and x % 4 == (y // 4 % 2) * 2) else 0
    return 1 if (x + y) % 2 == 0 else 0               # walls: checker

def picture(phase):
    rows = []
    for r in range(9):
        cells = []
        for c in range(64):
            data = []
            for l in range(16):
                b = 0
                for k in range(8):
                    if classify(c * 8 + k, r * 16 + l, phase): b |= 0x80 >> k
                data.append(b)
            cells.append(tuple(data))
        rows.append(cells)
    return rows

def main(out):
    chars = [tuple([0] * 16)]
    index = {chars[0]: 0}
    def idx(d):
        if d not in index:
            index[d] = len(chars); chars.append(d)
        return index[d]
    pics = [picture(p) for p in range(4)]
    tuni = [[idx(d) for d in row] for row in pics[0]]
    tunl = [[[idx(pics[p][r][LC0 + j]) for j in range(LCN)] for r in range(9)] for p in range(4)]
    assert len(chars) <= 256, len(chars)
    open(os.path.join(out, 'tunnel.bin'), 'wb').write(bytes(b for ch in chars for b in ch))
    L = ['; generated by tools/mktunnel.py', 'TUN_NCH  equ %d' % len(chars),
         'TUN_LC0  equ %d' % LC0, 'TUN_LCN  equ %d' % LCN, 'TUNI:']
    for row in tuni: L.append('        db ' + ','.join(str(v) for v in row))
    L.append('TUNL:')
    for p in tunl:
        for row in p: L.append('        db ' + ','.join(str(v) for v in row))
    open(os.path.join(out, 'tunnel.inc'), 'w').write('\n'.join(L) + '\n')
    # preview
    from PIL import Image
    im = Image.new('RGB', (W, H * 2 * 4 + 12), (40, 40, 40))
    for p in range(4):
        for y in range(H):
            for x in range(W):
                if classify(x, y, p):
                    im.putpixel((x, p * (H * 2 + 4) + y * 2), (190, 190, 190))
                    im.putpixel((x, p * (H * 2 + 4) + y * 2 + 1), (190, 190, 190))
    im.save(os.path.join(out, 'tunnel_preview.png'))
    print('tunnel: %d characters' % len(chars), file=sys.stderr)

if __name__ == '__main__':
    main(sys.argv[1] if len(sys.argv) > 1 else 'build')
