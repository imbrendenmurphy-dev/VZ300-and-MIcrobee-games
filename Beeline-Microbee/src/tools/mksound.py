#!/usr/bin/env python3
"""
mksound.py - BEELINE beeper sounds and music -> build/sound.inc
ViBED by BPM 2026

The Microbee speaker (port 02h bit 6) is toggled by the frame-wait loop
(snd_wait in snd.asm): sound only plays while the CPU would otherwise idle
waiting for the next page flip, so it costs no frame time.  Every half cycle
costs HPOVER T-states of loop overhead plus 26 per delay count.

A sound is a list of steps (half-period count, half cycles); noise steps set
bit 15 of the half-period (the loop adds a random jitter).  Music is a list of
(step, fields) pairs: a short blip of the note, then silence for that many
50 Hz fields - "dink, dink-dink-dink", slow and suspenseful.
"""
import os, sys

CLK = 3375000
HPOVER = 190            # T-states per half cycle outside the delay loop
LOOPT = 26

def hp_count(freq):
    t = CLK / (2.0 * freq)
    return max(1, int(round((t - HPOVER) / LOOPT)))

def step(freq, ms, noise=False):
    n = hp_count(freq)
    th = HPOVER + LOOPT * n
    if noise: th += LOOPT * 64            # average jitter
    hc = max(2, int(round(ms / 1000.0 * CLK / th)))
    return (n | (0x8000 if noise else 0), hc)

def note(name):
    names = {'C': -9, 'D': -7, 'E': -5, 'F': -4, 'G': -2, 'A': 0, 'B': 2}
    s = names[name[0]]
    i = 1
    if name[i] == '#': s += 1; i += 1
    elif name[i] == 'b': s -= 1; i += 1
    octv = int(name[i:])
    return 440.0 * 2 ** ((s + 12 * (octv - 4)) / 12.0)

# steps of about 3 ms: one is always heard per frame, more when there is time
S = 3
SFX = {
    'count':  [step(note('A5'), S), step(note('A5'), S)],
    'go':     [step(note(n), S) for n in ('A5', 'C#6', 'E6', 'A6', 'A6', 'A6')],
    'warn':   [step(note('E7'), S)],
    'pass':   [step(note('E6'), S), step(note('B6'), S)],
    'crash':  [step(f, S, True) for f in (420, 340, 280, 240, 210, 190)],  # half periods stay < 9000 T: vblank polling
    'check':  [step(note(n), S) for n in ('C6', 'E6', 'G6', 'C7', 'G6', 'C7', 'C7')],
    'timeup': [step(note(n), S) for n in ('G5', 'G5', 'E5', 'E5', 'C5', 'C5', 'G4', 'G4')],
    'finish': [step(note(n), S) for n in ('C6', 'E6', 'G6', 'C7', 'C7', 'G6', 'C7', 'C7', 'C7')],
    'tally':  [step(note('C7'), 2)],
    'turbo':  [step(f, S, True) for f in (250, 320, 400, 500, 620, 760)],
    'slip':   [step(note(n), S) for n in ('C6', 'D6', 'E6', 'G6', 'A6', 'C7')],
}

BLIP_MS = 3
def tune(seq):
    """seq: list of (note or None, fields)"""
    out = []
    for n, f in seq:
        if n is None: out.append((0, 0, f))
        else:
            hp, hc = step(note(n), BLIP_MS)
            out.append((hp, hc, f))
    return out

# race: A minor riff, a note every 8 fields at most - dink . . dink-dink-dink
R = 8
RACE = tune([
    ('A5', 3*R), ('A5', R), ('C6', R), ('E6', 3*R),
    ('G5', 3*R), ('G5', R), ('B5', R), ('D6', 3*R),
    ('F5', 3*R), ('F5', R), ('A5', R), ('C6', 3*R),
    ('E5', 3*R), ('E5', R), ('G#5', R), ('B5', 2*R), ('E6', R),
])
# title: brighter, slower
T = 10
TITLE = tune([
    ('E5', T), ('A5', T), ('C6', T), ('E6', 3*T),
    ('D6', T), ('C6', T), ('B5', 2*T), ('G5', 2*T),
    ('F5', T), ('A5', T), ('C6', T), ('F6', 3*T),
    ('E6', T), ('D6', T), ('B5', 2*T), ('G#5', 2*T),
])

def main(out):
    L = ['; generated by tools/mksound.py']
    L.append('SFX_TABLE:')
    names = list(SFX)
    for n in names: L.append('        dw SFX_%s' % n.upper())
    for i, n in enumerate(names): L.append('SND_%s equ %d' % (n.upper(), i))
    for n in names:
        L.append('SFX_%s:' % n.upper())
        for hp, hc in SFX[n]:
            L.append('        dw %d,%d' % (hp, hc))
        L.append('        dw 0')
    for name, t in (('MUS_RACE', RACE), ('MUS_TITLE', TITLE)):
        L.append(name + ':')
        for hp, hc, f in t:
            L.append('        dw %d,%d' % (hp, hc))
            L.append('        db %d' % f)
        L.append('        dw 0FFFFh')
    open(os.path.join(out, 'sound.inc'), 'w').write('\n'.join(L) + '\n')

if __name__ == '__main__':
    main(sys.argv[1] if len(sys.argv) > 1 else 'build')
