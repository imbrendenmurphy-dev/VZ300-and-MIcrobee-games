GEN = os.path.join(ROOT, 'gen')
OUT = os.path.join(ROOT, 'out')
os.makedirs(GEN, exist_ok=True)
os.makedirs(OUT, exist_ok=True)

import gfx, songs


def db(data, per=16):
    data = bytes(data)
    return '\n'.join('            db ' + ','.join('$%02X' % b for b in data[i:i + per])
                     for i in range(0, len(data), per))


def centre(s, w):
    assert len(s) <= w, s
    p = (w - len(s)) // 2
    return ' ' * p + s + ' ' * (w - len(s) - p)


def blank_spaces(codes):
    """6847 text codes with spaces turned into black semigraphic cells."""
    return bytes(0x80 if b == 0x20 else b for b in codes)


