def gen_data():
    L = ['; generated by tools/build.py - tables, graphics and texts']
    L.append('            ALIGN 256')
    L.append('sintab:')
    L.append(db(gfx.sin_table()))
    L.append('pl_ctab:')
    L.append(db(gfx.plasma_colours()))
    L.append('tun_tex:')
    L.append(db(gfx.tunnel_texture()))
    tm = bytearray()
    for b in range(256):
        m = 0
        for k in range(4):
            if (b >> (k * 2)) & 3 == 0:
                m |= 3 << (k * 2)
        tm.append(m)
    L.append('tmask:')
    L.append(db(tm))
    L.append('logo:')
    L.append(db(gfx.logo_cells()))
    L.append('rainbow:    db $90,$F0,$B0,$E0,$A0,$D0,$80,$C0')
    L.append('pmask:      db $C0,$30,$0C,$03')
    L.append('            ALIGN 8')
    L.append('font1:')
    L.append(db(gfx.font_mode1()))
    rx = bytearray(); ry = bytearray()
    for zz in range(128):
        v = min(127, int(round(64.0 * 64.0 / zz))) if zz else 127
        rx.append(v)
        ry.append(int(round(v * 2.0 / 3.0)))
    L.append('cu_rx:')
    L.append(db(rx))
    L.append(db(ry))
    L.append('TUN_W       equ %d' % gfx.TUN_W)
    L.append('tun_tab:')
    L.append(db(gfx.tunnel_table()))
    dark = gfx.tunnel_dark()
    L.append('TUN_DARK_N  equ %d' % len(dark))
    L.append('tun_dark:   dw ' + ','.join(str(d) for d in dark))
    # texts
    tw = bytearray()
    for row, s in TITLE_LINES:
        a = 0x7000 + row * 32 + (32 - len(s)) // 2
        tw += bytes([0xFE, a & 255, a >> 8]) + blank_spaces(gfx.vz_text(s))
    tw.append(0xFF)
    L.append('tw_title:')
    L.append(db(tw))
    L.append('pl_text:')
    L.append(db(blank_spaces(gfx.vz_text(PLASMA_TEXT)) + b'\xFF'))
    L.append('st_label:')
    L.append(db(gfx.text_codes(STAR_LABEL) + b'\xFF'))
    L.append('cu_label:')
    L.append(db(gfx.text_codes(CUBE_LABEL) + b'\xFF'))
    st = ' ' * 16 + SCROLL_TEXT + ' ' * 16
    L.append('SC_LEN      equ %d' % len(st))
    L.append('sc_text:')
    L.append(db(gfx.text_codes(st)))
    cr = bytearray()
    for line in CREDITS:
        assert len(line) <= 28, line
        cr += bytes([len(line)]) + blank_spaces(gfx.vz_text(line))
    cr.append(0xFF)
    L.append('cr_text:')
    L.append(db(cr))
    return '\n'.join(L) + '\n'


def write(name, text):
    with open(os.path.join(GEN, name), 'w') as f:
        f.write(text)


def main():
    write('data.inc', gen_data())
    write('songs.inc', songs.asm())
    binf = os.path.join(OUT, 'chunky.bin')
    r = subprocess.run([sys.executable, os.path.join(HERE, 'zasm.py'), os.path.join(ROOT, 'src', 'main.asm'),
                        '-o', binf, '--sym', os.path.join(OUT, 'chunky.sym'),
                        '--lst', os.path.join(OUT, 'chunky.lst')], capture_output=True, text=True)
    print(r.stdout.strip(), r.stderr.strip())
    if r.returncode:
        sys.exit(1)
    syms = {}
    for line in open(os.path.join(OUT, 'chunky.sym')):
        a, n = line.split()
        syms[n] = int(a, 16)
    size = os.path.getsize(binf)
    print('code+data $8000-$%04X, variables to $%04X, stack top $B800' % (0x8000 + size - 1, syms['vars_end']))
    subprocess.run([sys.executable, os.path.join(HERE, 'mkvz.py'), binf, os.path.join(OUT, 'CHUNKY.VZ'),
                    '0x8000', 'CHUNKY FUNKY'], check=True)


if __name__ == '__main__':
    main()
