"""CHUNKY FUNKY - the demo tune (original), for the three-voice pulse player.
One sixteenth = 6 fields (125 bpm). One bar = 96 fields. The song is 64 bars and loops;
the demo's parts change on its 4-bar section boundaries (see PARTS in build.py).
"""
from music import compile_channel, note_steps, INSTR

INSTR = list(INSTR) + [
    (92, 6, 26, 0),   # 12 slap bass: hard attack, settles to a firm tone
    (62, 3, 16, 0),   # 13 pluck lead
    (40, 1, 22, 0),   # 14 warm lead (long notes)
]

U = 'u6 '   # one length unit = a sixteenth


# ---------------------------------------------------------------- bass
def bass_bar(root):
    """A syncopated funk bar on a root like 'E2' (16 sixteenths)."""
    names = ['C', 'C#', 'D', 'D#', 'E', 'F', 'F#', 'G', 'G#', 'A', 'A#', 'B']
    n = root[:-1]; o = int(root[-1])
    i = names.index(n)

    def nt(semis):
        k = i + semis
        return names[k % 12] + str(o + k // 12)
    R, R8, b7, f5 = nt(0), nt(12), nt(10), nt(7)
    return '%s:3 %s:1 %s:2 r:1 %s:1 r:2 %s:2 %s:2 %s:2 | ' % (R, R, R8, R, b7, f5, R8)


def bass_held(root):
    return '%s:8 %s:8 | ' % (root, root)


def bass(chords, held=False):
    f = bass_held if held else bass_bar
    return 'i12 ' + ''.join(f(c) for c in chords)


A_CH = ['E2', 'A2', 'E2', 'A2']
B1_CH = ['C2', 'D2', 'E2', 'E2']
B2_CH = ['C2', 'D2', 'B1', 'B1']
C_CH = ['A2', 'E2', 'A2', 'B1']
O_CH = ['E2', 'A2', 'C2', 'B1']

# ---------------------------------------------------------------- drums (channel 3)
K = 'i7 C3:1 '
S = 'i3 C5:1 '
H = 'i8 C6:1 '
R = 'r:1 '
GROOVE = K + H + H + H + S + H + K + H + H + H + K + H + S + H + H + S + '| '
GROOVE_FILL = K + H + K + H + S + H + K + H + S + S + K + S + S + S + S + S + '| '
LIGHT = K + R + H + R + H + R + K + H + R + H + K + R + H + R + H + R + '| '
FOURS = K + R + R + R + K + R + R + R + K + R + R + R + K + R + R + R + '| '


def drums(bar, fill=GROOVE_FILL):
    return bar * 3 + fill


# ---------------------------------------------------------------- melodies (64 sixteenths each)
MEL_A1 = ('i13 E5:2 G5:2 A5:2 B5:4 A5:2 G5:2 E5:2 | D5:2 E5:2 r:2 C#5:2 r:2 A4:3 B4:3 | '
          'E5:2 G5:2 A5:2 B5:3 D6:3 B5:2 A5:2 | G5:4 F#5:2 E5:2 r:4 D5:2 E5:2 | ')
MEL_A2 = ('i13 E5:2 G5:2 A5:2 B5:4 A5:2 G5:2 E5:2 | D5:2 E5:2 r:2 C#5:2 r:2 A4:3 B4:3 | '
          'B5:2 D6:2 E6:4 D6:2 B5:2 A5:2 G5:2 | E5:8 r:4 B4:2 D5:2 | ')
MEL_B1 = ('i14 G5:6 E5:2 G5:4 B5:4 | A5:6 F#5:2 A5:4 D6:4 | '
          'B5:4 A5:2 G5:2 E5:4 D5:2 E5:2 | E5:12 r:4 | ')
MEL_B2 = ('i14 G5:6 E5:2 G5:4 C6:4 | D6:6 C6:2 B5:4 A5:4 | '
          'B5:4 A5:2 F#5:2 D#5:4 F#5:4 | B5:8 A5:4 F#5:4 | ')


def arp(notes, octave_up=False):
    out = []
    for n in notes.split():
        if octave_up:
            n = n[:-1] + str(int(n[-1]) + 1)
        out.append(n + ':1')
    return ' '.join(out) + ' | '


AR_AM = 'A4 C5 E5 A5 E5 C5 E5 A5 C6 A5 E5 C5 E5 C5 A4 C5'
AR_EM = 'E4 G4 B4 E5 B4 G4 B4 E5 G5 E5 B4 G4 B4 G4 E4 G4'
AR_B7 = 'B4 D#5 F#5 A5 F#5 D#5 F#5 A5 B5 A5 F#5 D#5 F#5 D#5 B4 D#5'
MEL_C1 = 'i4 ' + arp(AR_AM) + arp(AR_EM) + arp(AR_AM) + arp(AR_B7)
MEL_C2 = 'i4 ' + arp(AR_AM, True) + arp(AR_EM, True) + arp(AR_AM, True) + arp(AR_B7, True)
MEL_O = ('i14 E5:4 r:4 E5:2 G5:2 B5:4 | A5:4 r:4 C#6:4 A5:4 | '
         'G5:4 E5:4 C5:4 G5:4 | F#5:4 D#5:4 B4:8 | ')
STABS = 'i4 ' + ('r:4 E5:1 r:3 r:2 G5:1 r:1 E5:1 r:3 | r:4 A5:1 r:3 r:2 C#6:1 r:1 A5:1 r:3 | ') * 2
REST4 = 'r:16 r:16 r:16 r:16 | '

# 16 sections of 4 bars: (lead, bass, drums)
SECTIONS = [
    (REST4, bass(A_CH, held=True), drums(FOURS, LIGHT)),       # 1  intro
    (STABS, bass(A_CH), drums(LIGHT, GROOVE_FILL)),            # 2  intro 2
    (MEL_A1, bass(A_CH), drums(GROOVE)),                       # 3  A
    (MEL_A2, bass(A_CH), drums(GROOVE)),                       # 4  A2
    (MEL_B1, bass(B1_CH), drums(GROOVE)),                      # 5  B
    (MEL_B2, bass(B2_CH), drums(GROOVE)),                      # 6  B2
    (MEL_A1, bass(A_CH), drums(GROOVE)),                       # 7  A
    (MEL_A2, bass(A_CH), drums(GROOVE)),                       # 8  A2
    (MEL_C1, bass(C_CH, held=True), drums(LIGHT, LIGHT)),      # 9  break
    (MEL_C2, bass(C_CH), drums(LIGHT, GROOVE_FILL)),           # 10 break 2
    (MEL_C1, bass(C_CH), drums(GROOVE)),                       # 11 C
    (MEL_C2, bass(C_CH), drums(GROOVE)),                       # 12 C2
    (MEL_A1, bass(A_CH), drums(GROOVE)),                       # 13 A
    (MEL_A2, bass(A_CH), drums(GROOVE)),                       # 14 A2
    (MEL_B2, bass(B2_CH), drums(GROOVE)),                      # 15 B2
    (MEL_O, bass(O_CH), drums(GROOVE, GROOVE_FILL)),           # 16 outro
]

SONG = [U + ''.join(s[k] for s in SECTIONS) for k in range(3)]
BAR_TICKS = 96


def asm():
    out = ['; generated by tools/songs.py', 'instruments:']
    for ins in INSTR:
        out.append('            db %d,%d,%d,%d' % ins)
    out.append('note_steps:')
    st = note_steps()
    for i in range(0, len(st), 12):
        out.append('            dw ' + ','.join(str(v) for v in st[i:i + 12]))
    out.append('song_main: dw song_c0,song_c1,song_c2')
    lens = []
    total = 0
    for k, ch in enumerate(SONG):
        data, t = compile_channel(ch)
        lens.append(t)
        total += len(data) + 3
        out.append('song_c%d:' % k)
        for i in range(0, len(data), 24):
            out.append('            db ' + ','.join(str(b) for b in data[i:i + 24]))
        out.append('            db 254')
        out.append('            dw song_c%d' % k)
    if len(set(lens)) != 1:
        raise SystemExit('channel lengths differ %s' % lens)
    if lens[0] != 64 * BAR_TICKS:
        raise SystemExit('song is %d ticks, expected %d' % (lens[0], 64 * BAR_TICKS))
    out.append('; music bytes: %d' % total)
    return '\n'.join(out) + '\n'


if __name__ == '__main__':
    print(asm().splitlines()[-1])
