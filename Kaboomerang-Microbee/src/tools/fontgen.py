CHARS = ' !"#$%&\'()*+,-./0123456789:;<=>?@ABCDEFGHIJKLMNOPQRSTUVWXYZ'


def glyph_rows(ch):
    s = G.get(ch)
    rows = [0] * 10
    if s is None:
        return rows
    for y, r in enumerate(s.split()):
        assert len(r) == 7, (ch, r)
        rows[1 + y] = sum(128 >> x for x, c in enumerate(r) if c == '#')
    return rows


def font_bytes():
    return [bytes(glyph_rows(ch)) for ch in CHARS]


if __name__ == '__main__':
    import sys
    from PIL import Image
    S = 4
    text = ["KABOOMERANG  SCORE 012345", "WALLY THE DEMOLITION WOMBAT", "STOP BARON VON CROAK'S CAR PARKS!",
            "SPACE OR FIRE TO PLAY  1-1 READY?", "ABCDEFGHIJKLMNOPQRSTUVWXYZ", "0123456789 +-*/:.,()"]
    im = Image.new('RGB', (40 * 8 * S, len(text) * 10 * S), (0, 0, 0))
    for r, line in enumerate(text):
        for i, ch in enumerate(line):
            g = glyph_rows(ch)
            for y in range(10):
                for x in range(8):
                    if g[y] & (128 >> x):
                        for a in range(S):
                            for b in range(S):
                                im.putpixel(((i * 8 + x) * S + a, (r * 10 + y) * S + b), (255, 220, 60))
    im.save(sys.argv[1])
