SQUASH = ["................"] * 12 + ["..############..", ".###.#.##.#.###.", "################",
                                      "################", "################", "################",
                                      ".##############.", "..############.."]


def front(face='norm', feet='a', back=False):
    return (HAT_BACK if back else HAT) + CROWN + FACES['back' if back else face] + BODY[feet]


def side(step):
    return HAT_SIDE + SIDE + SIDE_FEET[step]


if __name__ == '__main__':
    import sys
    from PIL import Image
    YEL, FUR, BG = (255, 255, 64), (192, 128, 60), (0, 0, 0)
    poses = [front(f) for f in ('norm', 'blink', 'lookL', 'lookR', 'wide', 'happy', 'dizzy')]
    poses += [front('norm', 'b'), front(back=True, feet='c'), side(0), side(1)]
    S = 8
    im = Image.new('RGB', (len(poses) * 19 * S, 26 * S), (30, 20, 16))
    for i, p in enumerate(poses):
        assert len(p) == 24, (i, len(p))
        for y, row in enumerate(p):
            assert len(row) == 16, (i, y, row, len(row))
            for x, c in enumerate(row):
                col = (YEL if y < 4 else FUR) if c == '#' else BG
                x0 = int((i * 19 + 1) * S + x * S * 1.09)
                for dy in range(S):
                    for dx in range(int(S * 1.09) + 1):
                        im.putpixel((x0 + dx, (1 + y) * S + dy), col)
    im.save(sys.argv[1] if len(sys.argv) > 1 else 'wally.png')
