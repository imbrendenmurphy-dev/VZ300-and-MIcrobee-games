import art as A

STORE_N = 512          # glyphs 0..511 (banks 0-3) are kept in every sprite block
G_FONT = 384           # font: chars 32..95 (bank 3)
G_ICON = 448           # HUD icons
G_TITLE = 512          # title picture glyphs: banks 4..13
SPR_DATA = 0x3000
GFX_STORE_C = 0x0000   # GFX block: colour store (512 x 16)
GFX_STORE_M = 0x2000   #            mono store
GFX_TITLE = 0x4000     #            title: 1000 lo, 1000 hi, 1000 colour, then dw n, n x 16 colour, n x 16 mono


def wfile(name, data):
    open(os.path.join(BUILD, name), 'wb').write(bytes(data))


def cell_bytes(bits, cx, cy):
    out = bytearray(8)
    for y in range(8):
        v = 0
        for x in range(8):
            if bits[cy * 8 + y, cx * 8 + x]:
                v |= 128 >> x
        out[y] = v
    return bytes(out)


def mono_of(pat, ink, paper):
    """the mono monitor shows only the pixel bits: where the paper is the
    brighter colour, the pattern is inverted so the picture reads the same"""
    if A.LUM[paper] > A.LUM[ink]:
        return bytes(255 - b for b in pat)
    return pat


class Glyphs:
    def __init__(self, first, limit):
        self.first, self.limit = first, limit
        self.key = {}
        self.pats = []

    def add(self, pat, mono):
        k = (pat, mono)
        if k not in self.key:
            assert len(self.pats) < self.limit - self.first, 'out of glyphs'
            self.key[k] = self.first + len(self.pats)
            self.pats.append(k)
        return self.key[k]


# ---------------------------------------------------------------- tiles
def build_tiles():
    tiles = A.all_tiles()
    gs = Glyphs(0, G_FONT)
    gs.add(bytes(8), bytes(8))                 # glyph 0: blank
    # floor glyphs first: sprites drop the floor's speckle under them
    order = [t for t in tiles if t.floor] + [t for t in tiles if not t.floor]
    recs = {}
    floor_end = None
    for t in order:
        if not t.floor and floor_end is None:
            floor_end = len(gs.pats)
        cells = []
        for q, (cx, cy) in enumerate(((0, 0), (1, 0), (0, 1), (1, 1))):
            ink, paper = t.cols[q]
            p = cell_bytes(t.bits, cx, cy)
            g = gs.add(p, mono_of(p, ink, paper))
            cells.append((g, (paper << 4) | ink))
        recs[t.name] = cells
    print('tiles: %d tiles, %d glyphs (floor glyphs 1..%d)' % (len(tiles), len(gs.pats), floor_end - 1))
    # font + icons
    font = A.font_glyphs()
    store_c = bytearray(STORE_N * 16)
    store_m = bytearray(STORE_N * 16)
    for i, (pc, pm) in enumerate(gs.pats):
        store_c[i * 16:i * 16 + 8] = pc
        store_m[i * 16:i * 16 + 8] = pm
    for i, f in enumerate(font):
        g = G_FONT + i
        store_c[g * 16:g * 16 + 8] = f
        store_m[g * 16:g * 16 + 8] = f
    icons = list(A.ICONS.items())
    for i, (n, f) in enumerate(icons):
        g = G_ICON + i
        store_c[g * 16:g * 16 + 8] = f
        store_m[g * 16:g * 16 + 8] = f
    # tiles.inc: tile table, 12 bytes a tile: 4 x glyph (dw), 4 x colour
    names = [t.name for t in tiles]
    L = ['; generated by tools/build.py: background tiles (2 x 2 cells each)',
         'FLOOR_END equ %d' % floor_end, 'G_FONT equ %d' % G_FONT, 'G_ICON equ %d' % G_ICON,
         'STORE_N equ %d' % STORE_N, 'NTILES equ %d' % len(names)]
    for i, (n, f) in enumerate(icons):
        L.append('IC_%s equ %d' % (n.upper(), G_ICON + i))
    for i, n in enumerate(names):
        L.append('T_%s equ %d' % (n, i))
    open(os.path.join(SRC, 'tiles.inc'), 'w').write('\n'.join(L) + '\n')
    L = ['; generated by tools/build.py: tile table, 12 bytes a tile', 'tile_tab:']
    for n in names:
        c = recs[n]
        L.append('\tdw %s' % ','.join(str(g) for g, _ in c))
        L.append('\tdb %s' % ','.join('$%02X' % col for _, col in c))
    open(os.path.join(SRC, 'tiledata.inc'), 'w').write('\n'.join(L) + '\n')
    return store_c, store_m


# ---------------------------------------------------------------- sprites
def sprite_frame(bits, mask, ax=0, ay=0):
    """-> header: db w, h, ax, ay; dw offsets of the 4 shifts (0,2,4,6 px);
    then per shift, per byte column: db first row, db rows, rows x (and, or)"""
    bits = np.asarray(bits, bool)
    mask = np.asarray(mask, bool) | bits
    h, W = bits.shape
    w = (W + 6 + 7) // 8
    blocks = []
    for s in range(4):
        B = np.zeros((h, w * 8), bool)
        M = np.zeros((h, w * 8), bool)
        B[:, 2 * s:2 * s + W] = bits
        M[:, 2 * s:2 * s + W] = mask
        out = bytearray()
        for c in range(w):
            colm = M[:, c * 8:(c + 1) * 8].any(1)
            rows = np.nonzero(colm)[0]
            if len(rows) == 0:
                out += bytes([0, 0])
                continue
            y0, y1 = rows.min(), rows.max()
            out += bytes([y0, y1 - y0 + 1])
            for y in range(y0, y1 + 1):
                d = k = 0
                for b in range(8):
                    if B[y, c * 8 + b]:
                        d |= 128 >> b
                    if M[y, c * 8 + b]:
                        k |= 128 >> b
                out.append((~k) & 255)
                out.append(d & k)
        blocks.append(out)
    head = bytearray([w, h, ax & 255, ay & 255])
    off = 12
    for b in blocks:
        head += off.to_bytes(2, 'little')
        off += len(b)
    return bytes(head) + b''.join(blocks)


def build_sprites():
    S = A.sprites()
    data = bytearray()
    tab = []
    L = ['; generated by tools/build.py: sprite frames (block 4, address)']
    for i, (n, b, m) in enumerate(S):
        fb = sprite_frame(b, m)
        tab.append(SPR_DATA + len(data))
        data += fb
        L.append('SF_%s equ %d' % (n, i))
    assert SPR_DATA + len(data) <= 0x8000, len(data)
    L.append('NSPRFRAMES equ %d' % len(S))
    L.append('spr_tab:')
    for a in tab:
        L.append('\tdw $%04X' % a)
    open(os.path.join(SRC, 'sprtab.inc'), 'w').write('\n'.join(L) + '\n')
    wfile('SPR0.BNK', data)
    print('sprites: %d frames, %d bytes' % (len(S), len(data)))


# ---------------------------------------------------------------- title
def scale_font(text, sx, sy):
    rows = []
    for r in range(7):
        line = []
        for ch in text:
            bits = A.FD.get(ch, A.FD[' ']).split()[r]
            for b in bits:
                line += [b == '1'] * sx
            line += [False] * sx
        rows += [line] * sy
    return np.array(rows, bool)


def build_title(store_c, store_m):
    """the title picture: 40 x 25 cells with their own glyphs (G_TITLE on)"""
    W, H = 320, 200
    bits = np.zeros((H, W), bool)
    ink = np.full((25, 40), A.GREY, np.uint8)
    paper = np.zeros((25, 40), np.uint8)
    # big lettering, 3x scaled with a rounded chunky edge
    big = scale_font('KABOOMERANG', 3, 3)
    h, w = big.shape
    w -= 3
    x0 = (W - w) // 2 // 8 * 8
    bits[8:8 + h, x0:x0 + w] = big[:, :w]
    grad = [A.WHITE, A.YELLOW, A.YELLOW, A.BRED]
    for r in range(1, 4):
        ink[r, :] = grad[r]
    ink[1, :] = A.YELLOW
    ink[2, :] = A.YELLOW
    ink[3, :] = A.BRED
    # the fuse running along under the letters
    for x in range(x0, x0 + w, 1):
        y = 34 + int(round(math.sin(x / 9.0) * 1.5))
        bits[y, x] = (x % 3) != 0
    ink[4, :] = A.BROWN
    # big Wally (3x)
    hat = A.art(A.HAT_F + A.B8)
    body = A.art(A.B8 + A.FACE['happy'] + A.FEET['wide'])
    wal = hat | body
    big_w = np.kron(wal, np.ones((3, 3), bool))
    wx, wy = 32, 56
    bits[wy:wy + 48, wx:wx + 48] = big_w
    for r in range(wy // 8, (wy + 24) // 8):
        ink[r, wx // 8:(wx + 48) // 8] = A.YELLOW
    for r in range((wy + 24) // 8, (wy + 48) // 8):
        ink[r, wx // 8:(wx + 48) // 8] = A.GREY
    # a big gumnut bomb next to him
    bb = A.bomb_bits(1, 1)
    big_b = np.kron(bb, np.ones((2, 2), bool))
    bx, by = 96, 72
    bits[by:by + 32, bx:bx + 32] = big_b
    for r in range(by // 8, by // 8 + 2):
        ink[r, bx // 8:bx // 8 + 4] = A.YELLOW
    for r in range(by // 8 + 2, by // 8 + 4):
        ink[r, bx // 8:bx // 8 + 4] = A.BGREEN
    # ground: a strip of tiles along the bottom
    T = {t.name: t for t in A.all_tiles()}
    strip = ['MOUND0', 'FLOOR1', 'PILLAR', 'FLOOR2', 'MOUND0', 'MOUND0', 'FLOOR3', 'BURROW', 'FLOOR0', 'PILLAR',
             'MOUND0', 'FLOOR1', 'IT_FIRE', 'FLOOR2', 'MOUND0', 'PILLAR', 'FLOOR0', 'MOUND0', 'FLOOR3', 'EXIT']
    gy = 20
    for i, n in enumerate(strip):
        t = T[n]
        bits[gy * 8:gy * 8 + 16, i * 16:i * 16 + 16] = t.bits
        for q, (cx, cy) in enumerate(((0, 0), (1, 0), (0, 1), (1, 1))):
            ink[gy + cy, i * 2 + cx], paper[gy + cy, i * 2 + cx] = t.cols[q]
    lo = bytearray(1000)
    hi = bytearray(1000)
    col = bytearray(1000)
    gs = Glyphs(G_TITLE, G_TITLE + 1280)
    gs.add(bytes(8), bytes(8))
    for cy in range(25):
        for cx in range(40):
            p = cell_bytes(bits, cx, cy)
            if not any(p):
                g = 0
            else:
                g = gs.add(p, mono_of(p, ink[cy, cx], paper[cy, cx]))
            lo[cy * 40 + cx] = 0x80 | (g & 127)
            hi[cy * 40 + cx] = g >> 7
            col[cy * 40 + cx] = (int(paper[cy, cx]) << 4) | int(ink[cy, cx])
    n = len(gs.pats)
    out = bytes(lo) + bytes(hi) + bytes(col) + n.to_bytes(2, 'little')
    out += b''.join(pc + bytes(8) for pc, pm in gs.pats)
    out += b''.join(pm + bytes(8) for pc, pm in gs.pats)
    print('title: %d glyphs' % n)
    return out


