#!/usr/bin/env python3
"""ROBOGEDDON music + sound effects -> music.inc
The beeper runs a 16-bit phase accumulator in the idle loop (182 T-states per
sample at 3.5469 MHz = 19489 Hz).  A note is a 16-bit step; bit 15 = noise.
Music: (step word, frames) with the last frame of each note silent.
SFX:   one step word per game frame (25 Hz), $FFFF ends.
All tunes are original.
"""
import sys
RATE = 3546900 / 182.0
NOTE = {'C': 0, 'C#': 1, 'D': 2, 'D#': 3, 'E': 4, 'F': 5, 'F#': 6, 'G': 7,
        'G#': 8, 'A': 9, 'A#': 10, 'B': 11}

def freq(n):
    name, octv = n[:-1], int(n[-1])
    semis = NOTE[name] + 12 * (octv + 1) - 69
    return 440.0 * 2 ** (semis / 12.0)

def step(f):
    return max(1, min(0x7FFF, int(round(f * 65536 / RATE))))

E8 = 4      # eighth note = 4 frames (160 ms)

def song(spec):
    out = []
    for tok in spec.split():
        if ':' in tok:
            n, d = tok.split(':')
            d = float(d)
        else:
            n, d = tok, 1
        frames = int(round(d * E8))
        s = 0 if n == '-' else step(freq(n))
        out += [s & 255, s >> 8, frames]
    out += [0xFF, 0xFF]
    return out

TITLE = """
E3 E3 G3 E3 A3 E3 B3 A3
E3 E3 G3 E3 D4 C4 B3 A3
E3 E3 G3 E3 A3 E3 B3 D4
E4:2 D4 B3 G3:2 A3 B3
B4:2 A4 G4 F#4:2 E4:2
G4 F#4 E4 D4 E4:4
B4:2 A4 G4 F#4 G4 A4 B4
E5:2 D5 B4 E4:2 -:2
E3 E3 G3 E3 A3 E3 B3 A3
E3 E3 G3 E3 D4 C4 B3 A3
C4 C4 E4 C4 D4 D4 F#4 D4
E4 B3 G3 B3 E4:2 -:2
"""
GAMEOVER = "B3:2 A3:2 G3:2 F#3:2 E3:6 -:2"
HISCORE = "E4 G4 B4 E5:2 B4 E5:4 -:2"
WAVEDONE = "E4 G4 B4 G4 E5:4 -:1"

def sfx(prio, steps):
    out = [prio]
    for s in steps:
        out += [s & 255, s >> 8]
    out += [0xFF, 0xFF]
    return out

def t(f):
    return step(f)

def nz(f):
    return step(f) | 0x8000

SFX = [
    ('SFX_SHOT', 1, [t(1250), t(820), t(560)]),
    ('SFX_KILL', 3, [nz(3000), nz(1800), nz(1000), nz(600)]),
    ('SFX_ZAP', 2, [nz(5000), nz(2500)]),
    ('SFX_RESCUE', 5, [t(520), t(660), t(780), t(1040), t(1300)]),
    ('SFX_DIE', 9, [nz(4000), nz(3000), t(300), nz(2500), nz(2000), t(250),
                    nz(1600), nz(1300), t(200), nz(1000), nz(800), nz(700),
                    nz(600), nz(500), nz(420), nz(360), nz(300), nz(250),
                    nz(200), nz(160)]),
    ('SFX_SKULL', 4, [t(330), t(300), t(260), t(220), t(180), t(150)]),
    ('SFX_MUTATE', 4, [t(400), t(800), t(400), t(800), t(400), t(800)]),
    ('SFX_LIFE', 8, [t(1000), t(1300), t(1000), t(1300), t(1000), t(1300), t(1600), t(1600)]),
    ('SFX_PICKUP', 6, [t(700), t(900), t(1100), t(1400), t(1800)]),
    ('SFX_SPAWN', 2, [t(1800), t(1400)]),
    ('SFX_THUD', 2, [nz(400), t(110)]),
    ('SFX_EFIRE', 1, [t(1600), t(1900)]),
    ('SFX_TICK', 1, [t(1500)]),
    ('SFX_BIGKILL', 5, [nz(5000), nz(4000), nz(3000), nz(2200), nz(1600), nz(1100), nz(700), nz(400)]),
    ('SFX_MAT', 3, [t(200), t(260), t(330), t(420), t(520), t(650), t(800), t(1000), t(1250), t(1500), t(1800), t(2200)]),
    ('SFX_SELECT', 4, [t(900), t(1200)]),
]

def db(label, data):
    s = [label + ':']
    for i in range(0, len(data), 16):
        s.append('    db ' + ','.join('$%02X' % b for b in data[i:i + 16]))
    return '\n'.join(s)

def main():
    out = ['; generated by music.py - do not edit']
    for name, spec in [('mus_title', TITLE), ('mus_gameover', GAMEOVER),
                       ('mus_hiscore', HISCORE), ('mus_wavedone', WAVEDONE)]:
        out.append(db(name, song(spec)))
    out.append('sfxtab:')
    for i, (name, prio, steps) in enumerate(SFX):
        out.append('    dw %s_d' % name.lower())
    for i, (name, prio, steps) in enumerate(SFX):
        out.append('%s equ %d' % (name, i))
    for name, prio, steps in SFX:
        out.append(db(name.lower() + '_d', sfx(prio, steps)))
    out.append('STEP_E3 equ %d' % step(freq('E3')))
    open(sys.argv[1] if len(sys.argv) > 1 else 'music.inc', 'w').write('\n'.join(out) + '\n')

main()
