NAMES = {'TRI': 96, 'BALL': 127}


def _parse(src):
    """Parse an ASCII-art block source into {code: [row strings]}."""
    out = {}
    lines = src.split('\n')
    i = 0
    while i < len(lines):
        s = lines[i].strip()
        if not s.startswith(':'):
            i += 1
            continue
        names = s[1:].split()
        rows = []
        i += 1
        while i < len(lines) and lines[i].strip() and not lines[i].strip().startswith(':'):
            toks = lines[i].split()
            assert len(toks) == len(names), (names, lines[i])
            rows.append(toks)
            i += 1
        for k, n in enumerate(names):
            code = NAMES.get(n, ord(n) if len(n) == 1 else None)
            assert code is not None, n
            g = [r[k] for r in rows]
            for r in g:
                assert set(r) <= set('.#'), (n, r)
            out[code] = g
    return out


def _to_bytes(rows16):
    """16 strings of up to 8 chars -> 16-byte glyph."""
    assert len(rows16) == 16
    b = bytearray()
    for r in rows16:
        r = (r + '........')[:8]
        v = 0
        for c, ch in enumerate(r):
            if ch == '#':
                v |= 0x80 >> c
        b.append(v)
    return bytes(b)


def _blank_rows():
    return ['........'] * 16


SHEAR7 = 'MW'


def _build_sport():
    src = _parse(SPORT_SRC)
    glyphs = {}
    for code, g in src.items():
        rows = _blank_rows()
        width = max(len(r) for r in g)
        shear = width <= 6 or chr(code) in SHEAR7
        for idx, r in enumerate(g):
            if shear and idx <= 4:
                r = '.' + r          # italic lean: top five rows one px right
            rows[2 + idx] = r
        glyphs[code] = rows
    return glyphs


def _build_classic():
    src = _parse(CLASSIC_SRC)
    glyphs = {}
    for code, g in src.items():
        rows = _blank_rows()
        for idx, r in enumerate(g):
            rows[3 + idx] = r
        glyphs[code] = rows
    return glyphs


def _build_led():
    src = _parse(LED_SRC)
    glyphs = {}
    for code, g in src.items():
        rows = _blank_rows()
        for k, r in enumerate(g):
            rows[1 + 2 * k] = '.' + r
        glyphs[code] = rows
    return glyphs


def _finish(glyphs, icons, keep_tri=False):
    for code, g in icons.items():
        if code == 96 and keep_tri and 96 in glyphs:
            continue
        glyphs[code] = g
    table = []
    for code in range(32, 128):
        src = code
        if 97 <= code <= 122:
            src = code - 32
        g = glyphs.get(src)
        table.append(_to_bytes(g) if g else bytes(16))
    return table


