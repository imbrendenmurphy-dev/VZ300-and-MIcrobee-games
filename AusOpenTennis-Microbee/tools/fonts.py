def text_bitmap(font, text):
    """Return a (16, 8*len) uint8 array of 0/1 for text in FONTS[font]."""
    tab = FONTS[font]
    arr = np.zeros((16, 8 * len(text)), np.uint8)
    for i, ch in enumerate(text):
        c = ord(ch)
        if not 32 <= c <= 127:
            continue
        g = tab[c - 32]
        for y in range(16):
            for x in range(8):
                if g[y] & (0x80 >> x):
                    arr[y, 8 * i + x] = 1
    return arr


def preview(path, scale=3, aspect=1.5):
    cols = 40
    lines = []   # (font, text, colour)
    for name in FONTS:
        lines.append(('SPORT', name + ' FONT', LABEL))
        for start in (32, 64, 96):
            lines.append((name, ''.join(chr(c) for c in range(start, start + 32)), INK))
        lines.append((name, '', INK))
        for s in SAMPLES:
            lines.append((name, s, INK))
        lines.append((name, '', INK))
    h = 16 * len(lines)
    w = 8 * cols
    img = np.zeros((h, w, 3), np.uint8)
    img[:, :] = PAPER
    for li, (font, text, colour) in enumerate(lines):
        bm = text_bitmap(font, text[:cols])
        ys, xs = np.nonzero(bm)
        img[16 * li + ys, 8 + xs] = colour if xs.size else colour
    im = Image.fromarray(img, 'RGB')
    im = im.resize((int(w * scale), int(round(h * scale * aspect))), Image.NEAREST)
    d = os.path.dirname(path)
    if d:
        os.makedirs(d, exist_ok=True)
    im.save(path)
    return path


