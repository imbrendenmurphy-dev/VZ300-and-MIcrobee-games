"""Packing pictures and sprites into Microbee RAM block files."""
import numpy as np
from cells import compile_cells, compile_mono, mono_bits, GlyphSet, CH, CW

BLK_SPR = 4
SPR_DATA = 0x2000


def picture_bytes(pats, ink, paper, first=0, glyphs=None):
    """pats (16,64,16) -> bytes: dw n, n*16 patterns, 1024 lo, 1024 bank, 1024 colour.
    Glyph numbers start at 0 within the file (the game offsets them by lp_first)."""
    gs = glyphs or GlyphSet(0)
    if not len(gs):
        gs.add(bytes(16))      # glyph 0 is always the blank one
    rows, cols = ink.shape
    lo = bytearray(1024)
    hi = bytearray(1024)
    col = bytearray(1024)
    for cy in range(rows):
        for cx in range(cols):
            g = gs.add(pats[cy, cx])
            i = cy * 64 + cx
            lo[i] = 0x80 | (g & 127)
            hi[i] = g >> 7
            col[i] = (paper[cy, cx] << 4) | ink[cy, cx]
    data = gs.data()
    return len(gs).to_bytes(2, 'little') + data + bytes(lo) + bytes(hi) + bytes(col), gs


def sprite_frame(bits, mask=None, ax=0, ay=0):
    """bits: (h, W) bool. mask: pixels the sprite owns (default: bits grown by 1).
    -> header: db w, h, ax, ay; dw offsets of the 4 shifts (0,2,4,6 px) from the
    header; then per shift, per byte column: db first row, db rows, rows x (and, or).
    Columns are trimmed to the rows that change something, so empty corners
    of the bounding box take no cells."""
    bits = np.asarray(bits, bool)
    h, W = bits.shape
    if mask is None:
        m = bits.copy()
        m[:, 1:] |= bits[:, :-1]
        m[:, :-1] |= bits[:, 1:]
        m[1:, :] |= bits[:-1, :]
        m[:-1, :] |= bits[1:, :]
        mask = m
    mask = np.asarray(mask, bool) | bits
    w = (W + 6 + 7) // 8
    blocks = []
    for s in range(4):
        B = np.zeros((h, w * 8), bool)
        M = np.zeros((h, w * 8), bool)
        B[:, 2 * s:2 * s + W] = bits
        M[:, 2 * s:2 * s + W] = mask
        out = bytearray()
        for c in range(w):
            colm = M[:, c * 8:(c + 1) * 8].any(1)
            rows = np.nonzero(colm)[0]
            if len(rows) == 0:
                out += bytes([0, 0])
                continue
            y0, y1 = rows.min(), rows.max()
            out += bytes([y0, y1 - y0 + 1])
            for y in range(y0, y1 + 1):
                d = 0
                k = 0
                for b in range(8):
                    if B[y, c * 8 + b]:
                        d |= 128 >> b
                    if M[y, c * 8 + b]:
                        k |= 128 >> b
                out.append((~k) & 255)
                out.append(d & k)
        blocks.append(out)
    head = bytearray([w, h, ax & 255, ay & 255])
    off = 12
    for b in blocks:
        head += off.to_bytes(2, 'little')
        off += len(b)
    return bytes(head) + b''.join(blocks)


class SpriteBanks:
    def __init__(self, first_block=BLK_SPR):
        self.first = first_block
        self.banks = [bytearray()]
        self.tab = []          # (block, addr)
        self.names = []

    def add(self, name, frame_bytes):
        if len(self.banks[-1]) + len(frame_bytes) > 32768 - SPR_DATA:
            self.banks.append(bytearray())
        self.tab.append((self.first + len(self.banks) - 1, SPR_DATA + len(self.banks[-1])))
        self.names.append(name)
        self.banks[-1] += frame_bytes
        return len(self.tab) - 1

    def inc(self):
        L = ['; generated by tools: sprite frames (block, address)', 'NSPRFRAMES equ %d' % len(self.tab)]
        for i, n in enumerate(self.names):
            L.append('SF_%s equ %d' % (n, i))
        L.append('spr_tab:')
        for b, a in self.tab:
            L.append('\tdb %d\n\tdw $%04X' % (b, a))
        return '\n'.join(L) + '\n'
