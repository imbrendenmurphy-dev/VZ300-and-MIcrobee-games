"""Music data for the Microbee: the TENNIS II tunes (tools/vzmusic.py) with
the note table recomputed for the Microbee beeper loop (127 T at 3.375 MHz)."""
import os
HERE = os.path.dirname(os.path.abspath(__file__))


def build(out):
    L = []

    def db(bs):
        bs = list(bs)
        for i in range(0, len(bs), 16):
            L.append("    db " + ",".join("$%02X" % b for b in bs[i:i + 16]))
    src = open(os.path.join(HERE, 'vzmusic.py')).read()
    src = src.replace("LOOPRATE = 3546900.0 / 126", "LOOPRATE = 3375000.0 / 127")
    extra = os.path.join(HERE, 'mbmusic.py')
    if os.path.exists(extra):
        src += '\n' + open(extra).read()
    ns = dict(L=L, db=db)
    exec(src, ns)
    open(out, 'w').write('; generated by tools/mkmusic.py\n' + '\n'.join(L) + '\n')


if __name__ == '__main__':
    build(os.path.join(HERE, '..', 'src', 'music.inc'))
