BIG = [  # 8x10, 2px strokes, slanted terminals
"..####.. .######. ##....## ##...### ##.##.## ###...## ##....## ##....## .######. ..####..",
"...##... ..###... .####... ...##... ...##... ...##... ...##... ...##... ...##... .######.",
"..####.. .######. ##....## .....##. ....##.. ...##... ..##.... .##..... ######## ########",
".######. ##....## .....##. ...###.. ...####. ......## ......## ##....## .######. ..####..",
"....###. ...####. ..##.##. .##..##. ##...##. ######## ######## .....##. .....##. .....##.",
"######## ######## ##...... ######.. #######. ......## ......## ##....## .######. ..####..",
"..####.. .##..... ##...... ######.. #######. ##....## ##....## ##....## .######. ..####..",
"######## ######## .....##. ....##.. ...##... ..##.... ..##.... ..##.... ..##.... ..##....",
"..####.. .######. ##....## .######. .######. ##....## ##....## ##....## .######. ..####..",
"..####.. .######. ##....## ##....## .####### ..###### ......## .....##. ..####.. .####...",
]
def build():
    out = bytearray()
    for c in range(32, 96):
        g = F.get(chr(c), "### #.# #.# #.# ###")
        for row in g.split():
            n = 0
            for ch in row: n = (n << 1) | (ch == '#')
            out.append(n << 1)          # 3 px + 1 blank on the right
    for d in BIG:
        for row in d.split():
            n = 0
            for ch in row: n = (n << 1) | (ch == '#')
            out.append(n)
    return out

if __name__ == '__main__':
    out = build()
    B = os.path.join(os.path.dirname(__file__), '..', 'build')
    open(os.path.join(B, 'font.bin'), 'wb').write(out)
    print('font', len(out))
