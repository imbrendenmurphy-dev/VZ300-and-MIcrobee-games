"""Songs for the sequencer in music.asm -> build/songs.asm.
Style (as the user likes from Cybernoid's title): gritty, irreverent, notes
kept separate (short decays, gaps), a simple tune that isn't screechy -
the lead sits in the middle register, bass carries the weight.
Notes: 'C4' etc, 0 = C1.  Durations in 50 Hz steps."""
import os
NAMES = {'C':0,'C#':1,'D':2,'D#':3,'E':4,'F':5,'F#':6,'G':7,'G#':8,'A':9,'A#':10,'B':11}
def n(s):
    nm = s[:-1]; o = int(s[-1])
    return (o - 1) * 12 + NAMES[nm]
AYCLK = 1773400
def period(note):
    f = 32.703 * 2 ** (note / 12)
    return max(1, min(4095, int(round(AYCLK / 16 / f))))

# instruments: start volume, steps per volume drop, noise, floor
INST = [
    (13, 2, 0, 0),    # 0 lead: plucky, dies away -> separate notes
    (14, 3, 0, 0),    # 1 bass: punchy
    (11, 1, 0, 0),    # 2 arp blip
    (13, 1, 1, 0),    # 3 snare (noise)
    (15, 1, 0, 0),    # 4 kick (short low tone)
    (12, 4, 0, 6),    # 5 held lead (sustains)
    (10, 1, 1, 0),    # 6 hat (noise, quiet)
]

class Ch:
    def __init__(s): s.b = []; s.inst = None
    def i(s, k):
        if s.inst != k: s.b += [0x61, k]; s.inst = k
    def note(s, nm, d, inst=None, gate=None):
        """gate: sounding steps, rest of d is silence (keeps notes apart)"""
        if inst is not None: s.i(inst)
        g = d if gate is None else gate
        s.b += [n(nm), g]
        if d > g: s.b += [0x60, d - g]
    def rest(s, d): s.b += [0x60, d]
    def end(s, loop=True): s.b.append(0x62 if loop else 0x63)

def bass_line(ch, roots, steps=6, bars=1):
    for r in roots:
        for k in range(4):           # driving 8ths: root, root, octave, root
            o = r if k != 2 else r[:-1] + str(int(r[-1]) + 1)
            ch.note(o, steps, 1, gate=steps - 2)

def title():
    # 4-bar progression in A minor: Am F C G, twice, then a break
    S = 6   # steps per eighth (125 bpm-ish)
    lead, bass, drum = Ch(), Ch(), Ch()
    prog = ['A2', 'F2', 'C3', 'G2']
    melody = [
        ('E4', 2), ('A4', 2), ('C5', 2), ('B4', 1), ('A4', 1),
        ('G4', 2), ('A4', 2), ('C5', 3), ('D5', 1),
        ('E5', 2), ('D5', 1), ('C5', 1), ('G4', 2), ('E4', 2),
        ('D4', 2), ('E4', 1), ('G4', 1), ('A4', 4),
    ]
    melody2 = [
        ('A4', 1), ('A4', 1), ('C5', 2), ('E5', 2), ('D5', 2),
        ('C5', 1), ('A4', 1), ('F4', 2), ('A4', 2), ('C5', 2),
        ('G4', 1), ('G4', 1), ('B4', 2), ('D5', 2), ('B4', 2),
        ('A4', 3), ('G4', 1), ('E4', 2), ('A4', 2),
    ]
    for mel in (melody, melody2):
        for nm, e in mel: lead.note(nm, e * S, 0, gate=max(2, e * S - 3))
    # bass: 2 passes of the progression
    for _ in range(2): bass_line(bass, prog, S)
    # drums: kick on 1 and 3, snare on 2 and 4, hats between
    for bar in range(8):
        for beat in range(4):
            if beat in (0, 2): drum.note('C2', S, 4, gate=2)
            else: drum.note('C5', S, 3, gate=3)
            drum.note('C6', S, 6, gate=1)
    # middle eight: arpeggios over held bass
    arps = [['A3', 'C4', 'E4'], ['F3', 'A3', 'C4'], ['G3', 'B3', 'D4'], ['E3', 'G#3', 'B3']]
    for chord in arps:
        for k in range(8):
            lead.note(chord[k % 3], 3, 2, gate=2)
        lead.note(chord[0][:-1] + '5', 0 + 8, 0, gate=6)
        bass.note(chord[0][:-1] + '2', 32, 1, gate=28)
        for k in range(4):
            drum.note('C2', 4, 4, gate=2); drum.note('C6', 4, 6, gate=1)
    for c in (lead, bass, drum): c.end(True)
    return lead, bass, drum

def jingle(notes, bassn, S=5):
    lead, bass, drum = Ch(), Ch(), Ch()
    for nm, e in notes: lead.note(nm, e * S, 0, gate=max(2, e * S - 2))
    for nm, e in bassn: bass.note(nm, e * S, 1, gate=max(2, e * S - 3))
    tot = sum(e for _, e in notes)
    for k in range(tot // 2):
        drum.note('C2' if k % 2 == 0 else 'C5', 2 * S, 4 if k % 2 == 0 else 3, gate=2)
    for c in (lead, bass, drum): c.end(False)
    return lead, bass, drum

def songs():
    out = {}
    out['title'] = title()
    out['start'] = jingle([('A4', 2), ('C5', 2), ('E5', 2), ('A5', 4), ('G5', 1), ('A5', 5)],
                          [('A2', 4), ('A2', 2), ('E2', 2), ('A2', 8)])
    out['clear'] = jingle([('C5', 1), ('E5', 1), ('G5', 1), ('C6', 3), ('A5', 1), ('C6', 1), ('D6', 2), ('E6', 6)],
                          [('C3', 3), ('C3', 3), ('F2', 2), ('G2', 2), ('C3', 6)])
    out['over'] = jingle([('A4', 3), ('G4', 3), ('E4', 3), ('D4', 2), ('C4', 2), ('A3', 6)],
                         [('A2', 6), ('F2', 6), ('E2', 4), ('A1', 6)], S=6)
    return out

if __name__ == '__main__':
    B = os.path.join(os.path.dirname(__file__), '..', 'build')
    L = ['; generated by tools/music.py']
    L.append('ptab:')
    for k in range(96):
        L.append('        dw %d' % period(k))
    L.append('instruments:')
    for ins in INST: L.append('        db %d,%d,%d,%d' % ins)
    for name, chs in songs().items():
        L.append('song_%s: dw %s' % (name, ','.join('song_%s_%d' % (name, i) for i in range(3))))
        for i, c in enumerate(chs):
            L.append('song_%s_%d:' % (name, i))
            for k in range(0, len(c.b), 16):
                L.append('        db ' + ','.join(str(x) for x in c.b[k:k + 16]))
    open(os.path.join(B, 'songs.asm'), 'w').write('\n'.join(L) + '\n')
    print('songs ok', sum(len(c.b) for chs in songs().values() for c in chs), 'bytes')
