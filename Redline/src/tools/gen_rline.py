"""Generate the one-pass scanline writer (build/rline.asm).
A road line is  grass | rumble | road | line | road | rumble | grass  with
six boundaries p0..p5 (pixels 0..128, sorted).  The row is written left to
right exactly once: a pending byte collects the boundary mixes, full bytes
between boundaries come from a fill chain.  Colours are patched in per
segment (rl_c1..rl_c5) and per row (grass, rl_g*)."""
import os
B = os.path.join(os.path.dirname(__file__), '..', 'build')
L = []
def e(s): L.append(s)
e('; generated by tools/gen_rline.py')
e('; in: bnd0..bnd5 (pixels), (rowadr), grass colour patched; uses BC DE HL A')
e('rl_write:')
e('        ld hl,(rowadr)')
e('        ld a,l')
e('        ld ixl,a                ; row start (low byte)')
e('        add a,32')
e('        ld (rl_end+1),a')
e('rl_g0:  ld d,0                  ; pending byte = grass')
e('        ld b,high T_PIX')
cols = ['g', 'c1', 'c2', 'c3', 'c4', 'c5', 'g2']   # colour of run k (left of boundary k is run k)
for k in range(6):
    left = 'rl_cl%d' % k
    e('        ; boundary %d' % k)
    e('        ld a,(bnd+%d)' % k)
    e('        ld c,a')
    e('        cp 128')
    e('        jp nc,rl_fin%d' % k)
    e('        ld a,(bc)               ; byte index')
    e('        add a,ixl')
    e('        cp l')
    e('        jr z,rl_same%d' % k)
    e('        ld (hl),d               ; flush the pending byte')
    e('        inc l')
    e('        sub l')
    e('%s: ld e,0                ; colour of the run' % left)
    e('        jr z,rl_nf%d' % k)
    e('        cp 1')
    e('        jr nz,rl_cf%d' % k)
    e('        ld (hl),e')
    e('        inc l')
    e('        jr rl_nf%d' % k)
    e('rl_cf%d: call rl_fill' % k)
    e('rl_nf%d:' % k)
    e('        ld d,e')
    e('rl_same%d:' % k)
    e('        inc b')
    e('        ld a,(bc)               ; mask of pixels >= p')
    e('        dec b')
    e('        ld e,a')
    e('        ld a,d')
    e('rl_cr%d: xor 0                 ; colour right of the boundary' % k)
    e('        and e')
    e('        xor d')
    e('        ld d,a')
# all six placed: finish with grass
e('rl_fin6:')
e('        ld (hl),d')
e('        inc l')
e('rl_end: ld a,0')
e('        sub l')
e('        ret z')
e('        ret c')
e('rl_g1:  ld e,0')
e('        jp rl_fill')
for k in range(6):
    e('rl_fin%d:                       ; rest of the row is the run left of boundary %d' % (k, k))
    e('        ld (hl),d')
    e('        inc l')
    e('        ld a,(rl_end+1)')
    e('        sub l')
    e('        ret z')
    e('        ret c')
    e('        ld b,a')
    e('        ld a,(rl_cl%d+1)' % k)
    e('        ld e,a')
    e('        ld a,b')
    e('        jp rl_fill')
e('; fill A bytes (1..32) at HL with E, advancing L')
e('rl_fill:')
e('        add a,a')
e('        neg')
e('        add a,64')
e('        ld (rl_fj+1),a')
e('rl_fj:  jr $+2')
for _ in range(32):
    e('        ld (hl),e')
    e('        inc l')
e('        ret')
e('rl_rowlo: ld a,0')
open(os.path.join(B, 'rline.asm'), 'w').write('\n'.join(L) + '\n')
