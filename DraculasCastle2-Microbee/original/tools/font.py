def asm():
    out=['; generated 3x5 font, 5 bytes/glyph (bits 2..0 = pixels), chars 32..95','font:']
    for c in range(32,96):
        rows=F[chr(c)]
        bs=[sum((1<<(2-i)) for i,ch in enumerate(r) if ch=='#') for r in rows]
        out.append('            db '+','.join('%d'%b for b in bs)+'   ; '+repr(chr(c)))
    return '\n'.join(out)+'\n'
