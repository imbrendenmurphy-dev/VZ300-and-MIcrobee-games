def small_caps(rows9):
    """drop the 2nd and 6th rows of a capital: 9 rows -> 7 (rows 3-9)."""
    keep = [r for i, r in enumerate(rows9[:9]) if i not in (2, 6)]
    return [E, E] + keep

for c in 'ABCDEFGHIJKLMNOPQRSTUVWXYZ':
    G[c.lower()] = small_caps(G[c])

def glyph_rows(ch):
    """11 row bytes for an ASCII character (unknown -> blank)."""
    rows = G.get(ch)
    if rows is None:
        return [0]*11
    out = [0]
    for r in rows:
        v = 0
        for x in range(7):
            v = (v << 1) | (1 if r[x] == '#' else 0)
        out.append(v << 1)       # 7 px wide, column 7 = spacing
    while len(out) < 11:
        out.append(0)
    return out[:11]
