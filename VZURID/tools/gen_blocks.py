#!/usr/bin/env python3
"""Generate the unrolled copy chain and band-copy routines (build/gen_blocks.asm)."""
import os

OUT = os.path.join(os.path.dirname(__file__), '..', 'build', 'gen_blocks.asm')
L = []
L.append('; ---- generated by tools/gen_blocks.py - do not edit ----')
L.append('; 32 x LDI chain: entering at byte 2*i copies 32-i bytes')
L.append('CHAIN:')
for i in range(32):
    L.append('    ldi')
L.append('    ret')
L.append('')
L.append('; copy 8 rows (32 bytes each) when the 32-byte window does not wrap the ring')
L.append('copy_nosplit:')
for r in range(8):
    L.append('    call CHAIN')
    L.append('    ld bc,160')
    L.append('    add hl,bc')
L.append('    ret')
L.append('')
L.append('; copy 8 rows when the window wraps: segment A (to slot 47), then segment B (from slot 0)')
L.append('copy_split:')
for r in range(8):
    L.append('    call thunkA')
    L.append('    ld bc,-48')
    L.append('    add hl,bc')
    L.append('    call thunkB')
    L.append('    ld bc,208')
    L.append('    add hl,bc')
L.append('    ret')
L.append('thunkA:  jp 0')
L.append('thunkB:  jp 0')
L.append('')
L.append('; 5 x masked byte (7 bytes of code each): entering at 7*(5-n) draws n bytes')
L.append('SBCHAIN:')
for i in range(5):
    L.append('    ld a,(de)')
    L.append('    and (hl)')
    L.append('    inc hl')
    L.append('    or (hl)')
    L.append('    inc hl')
    L.append('    ld (de),a')
    L.append('    inc de')
L.append('    ret')
with open(OUT, 'w') as f:
    f.write('\n'.join(L) + '\n')
print('wrote', OUT)
