TXT={0:((7,255,0),(0,92,0)),1:((255,160,0),(110,32,0))}   # css -> (bright, dark)
def render(vram,css=0,scale=3,border=16):
    W,H=256+2*border,192+2*border
    im=Image.new('RGB',(W,H),(0,0,0)); px=im.load()
    bright,dark=TXT[css]
    for r in range(16):
        for c in range(32):
            b=vram[r*32+c]; x0=border+c*8; y0=border+r*12
            if b&0x80:
                col=SG[(b>>4)&7]
                for q,(qx,qy) in enumerate(((0,0),(4,0),(0,6),(4,6))):
                    on=b>>(3-q)&1
                    for y in range(6):
                        for x in range(4): px[x0+qx+x,y0+qy+y]=col if on else (0,0,0)
            else:
                ch=b&0x3F; chr_=chr(ch+0x40) if ch<0x20 else chr(ch)
                inv=b&0x40; bg,fg=(dark,bright) if inv else (bright,dark)
                g=G.get(chr_,G['?'])
                for y in range(12):
                    row=g[y-3] if 3<=y<10 else 0
                    for x in range(8):
                        on=1<=x<=5 and row>>(5-x)&1
                        px[x0+x,y0+y]=fg if on else bg
    return im.resize((W*scale,H*scale),Image.NEAREST)
