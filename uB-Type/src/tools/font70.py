"""70s 'future' font skeletons: 6 wide x 9 tall, 1-pixel strokes.
'#' = stroke, '@' = stroke thickened (double), '+' = single pixel (never
emboldened). A 7-character row is taken literally, pixel for pixel. Rule: the left-hand stroke (column 0) is doubled from row 4 down."""
