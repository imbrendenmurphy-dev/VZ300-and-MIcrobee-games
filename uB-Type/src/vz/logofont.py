BAND=['1','1','1','13','3','3','3','32','2','2','2']   # per row: heat band (two chars = dither)
def shade(g):
    H=len(g); W=len(g[0]); out=[]
    for y in range(H):
        r=''
        for x in range(W):
            if g[y][x]!='1': r+='.'; continue
            b=BAND[y]
            c=b[(x+y)%2] if len(b)==2 else b
            left = x==0 or g[y][x-1]!='1'
            right= x==W-1 or g[y][x+1]!='1'
            if left and 2<y<8: c='1'        # lit left bevel
            elif right and y>=6: c='2'      # shaded right bevel
            r+=c
        out.append(r)
    # drop shadow (1 px down) in red under the letter
    sh=['.'*W]
    out=out+sh
    for x in range(W):
        if g[H-1][x]=='1' and out[H][x]=='.': out[H]=out[H][:x]+'2'+out[H][x+1:]
    return out
