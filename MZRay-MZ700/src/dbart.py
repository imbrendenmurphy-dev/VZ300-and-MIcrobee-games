def raster(fn, pal, outline='K', n=16):
    """-> n x n grid (rows of colour letters or None). pal maps shape colour index 0-3 to MZ letters."""
    g = [[fn((x+0.5)/n, (y+0.5)/n) for x in range(n)] for y in range(n)]
    g = [[None if c is None else pal[c] for c in r] for r in g]
    o = [r[:] for r in g]
    if outline:
        for y in range(n):
            for x in range(n):
                if g[y][x] is None and any(0 <= y+dy < n and 0 <= x+dx < n and g[y+dy][x+dx] is not None
                                           for dx, dy in ((1, 0), (-1, 0), (0, 1), (0, -1))):
                    o[y][x] = outline
    return o
