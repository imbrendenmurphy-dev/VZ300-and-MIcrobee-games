def gen_title():
    """128x64 title backdrop. Returns pixel grid (chars)."""
    random.seed(13)
    W, H = 128, 64
    P = [['b'] * W for _ in range(H)]
    # stars
    for _ in range(46):
        x, y = random.randrange(W), random.randrange(0, 40)
        P[y][x] = 'y'
    # moon at upper right
    cx, cy, rad = 113, 31, 7
    for y in range(H):
        for x in range(W):
            dx = (x - cx); dy = (y - cy) * 1.5
            d = math.hypot(dx, dy)
            if d < rad:
                P[y][x] = 'y'
                if (x * 7 + y * 3) % 11 == 0 and d < rad - 2: P[y][x] = 'g'
            elif d < rad + 1.2 and (x + y) % 2 == 0:
                P[y][x] = 'y'
    # distant hills (dithered green)
    for x in range(W):
        h = int(46 + 3 * math.sin(x * 0.07) + 2 * math.sin(x * 0.23 + 1))
        for y in range(h, H):
            P[y][x] = 'g' if (x + y) % 2 == 0 or y > h + 3 else 'b'
    def rect(x0, y0, x1, y1, c='r'):
        for y in range(max(0, y0), min(H, y1)):
            for x in range(max(0, x0), min(W, x1)):
                P[y][x] = c
    # crag
    for x in range(0, 52):
        top = 50 - int(5 * math.sin(x / 52 * math.pi))
        rect(x, top, x + 1, H)
    # castle (left): keep, towers, spire
    rect(8, 36, 44, 47)                  # curtain wall
    rect(5, 30, 12, 47); rect(40, 30, 47, 47)    # side towers
    rect(19, 24, 33, 36)                 # keep
    rect(23, 19, 29, 24)                 # spire tower
    for i in range(4):
        rect(26 - i // 2 - 1, 15 + i, 26 + i // 2 + 1, 16 + i)
    P[14][26] = 'r'; P[13][26] = 'y'
    for (x0, x1, y) in [(5, 12, 30), (40, 47, 30), (19, 33, 24), (8, 44, 36)]:
        for x in range(x0, x1, 2): P[y - 1][x] = 'r'
    rect(4, 29, 13, 30); rect(39, 29, 48, 30)
    # tower roof cones
    for i in range(4):
        rect(8 - i, 25 + i, 9 + i, 26 + i); rect(43 - i, 25 + i, 44 + i, 26 + i)
    P[24][8] = 'r'; P[24][43] = 'r'
    # gate
    rect(24, 41, 28, 47, 'b'); rect(25, 40, 27, 41, 'b')
    wins = [(8, 33), (43, 33), (22, 28), (29, 28), (26, 21), (14, 40), (36, 40), (19, 40), (33, 40)]
    for x, y in wins:
        P[y][x] = 'y'; P[y + 1][x] = 'y'
    # graveyard foreground (right)
    for gx in (66, 78, 92, 104, 117):
        rect(gx, 54, gx + 4, 60, 'r'); rect(gx + 1, 53, gx + 3, 54, 'r')
    for cxx in (72, 98, 111):
        rect(cxx + 1, 50, cxx + 2, 58, 'r'); rect(cxx, 52, cxx + 3, 53, 'r')
    rect(56, 58, 128, 64, 'r')
    for x in range(56, 128, 2):
        if random.random() < 0.6: P[57][x] = 'r'
    # dead tree
    rect(86, 34, 88, 58, 'r')
    for i in range(8):
        P[34 - i // 2][86 - i] = 'r'; P[37 - i // 3][88 + i] = 'r'
    for i in range(4):
        P[30 - i][82 - i] = 'r'
    return P, wins

