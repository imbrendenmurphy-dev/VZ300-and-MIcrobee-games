    RESIDENT_SPRITES = _rsp()
    L = ['; generated by mkassets.py - do not edit', '']
    L += sprite_lines(RESIDENT_SPRITES, 'S_')
    # ----------------------------------------------------- hero layered data
    L.append('')
    L.append('; hero frames: 16 rows x 12 px, byte = armourclass<<4 | bodyclass')
    H = ['; hero class data (lives in SRAM bank B)', 'HERO_CLS:']
    bodycls = '.SreUy'
    for fi, fr in enumerate(HERO_FRAMES):
        bs = []
        for b, a in fr:
            for x in range(12):
                bc = bodycls.index(b[x])
                ac = ARMOUR_CLASSES.index(a[x])
                if a[x] == 'K' and b[x] != '.': ac = 0   # cape only behind body
                bs.append(ac << 4 | bc)
        H.append('; frame %d' % fi)
        H += db_lines(bs, 12)
    open(os.path.join(OUT, 'herocls.asm'), 'w').write('\n'.join(H) + '\n')
    L.append('NHEROF equ %d' % len(HERO_FRAMES))
    L.append('HERO_BODYTAB:   ; body class -> colour (FF transparent)')
    L.append('    db $FF,%d,%d,%d,%d,%d,$FF,$FF,$FF,$FF,$FF,$FF,$FF,$FF,$FF,$FF' %
             tuple(CI[BODY_COL[c]] for c in 'SreUy'))
    L.append('HERO_ARMTAB:    ; level x armour class -> colour (FF not worn)')
    for lv, t in enumerate(ARMOUR_LEVELS):
        row = [0xFF]
        for c in ARMOUR_CLASSES[1:]:
            v = t.get(c)
            row.append(CI[v] if v else 0xFF)
        row += [0xFF] * (16 - len(row))
        L.append('    db ' + hexrow(row) + '   ; ' + ARMOUR_NAMES[lv])
    L.append('ARMOUR_NAMES:')
    for n in ARMOUR_NAMES:
        L.append('    db "%s",0' % n)
    # ----------------------------------------------------- font (ASCII 32..95)
    L.append('')
    L.append('FONT:   ; 5 rows per char, ascii 32-95, pixels as 11 bits')
    for code in range(32, 96):
        ch = chr(code)
        g = FONT.get(ch, FONT['?'] if ch not in FONT else None) or FONT['?']
        bs = []
        for r in g:
            v = 0
            for c in r + '.':
                v = (v << 2) | (3 if c == '#' else 0)
            bs.append(v)
        L.append('    db ' + hexrow(bs) + '   ; ' + repr(ch))
    open(os.path.join(OUT, 'gfx.asm'), 'w').write('\n'.join(L) + '\n')

