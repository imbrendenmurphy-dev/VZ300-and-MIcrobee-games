CI = {'g': 0, 'y': 1, 'b': 2, 'r': 3}

def pack(row):
    """row of chars -> (keep bytes, data bytes); '.' transparent"""
    assert len(row) % 4 == 0, row
    keep, data = [], []
    for i in range(0, len(row), 4):
        k = d = 0
        for c in row[i:i+4]:
            k <<= 2; d <<= 2
            if c == '.': k |= 3
            else: d |= CI[c]
        keep.append(k); data.append(d)
    return keep, data

def hexrow(bs):
    return ','.join('$%02X' % b for b in bs)

def db_lines(bs, per=16):
    return ['    db ' + hexrow(bs[i:i+per]) for i in range(0, len(bs), per)]

