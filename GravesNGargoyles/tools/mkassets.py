def word_grid(word):
    rows = [''] * 9
    for ch in word:
        g = LOGO_LETTERS[ch]
        for r in range(9):
            rows[r] += g[r]
    return [r.rstrip('.') for r in rows]

def gen_logo():
    """Two-line logo: GRAVES 'N' / GARGOYLES -> list of rows of 'y','r','.'"""
    top = word_grid('GRAVES')
    bot = word_grid('GARGOYLES')
    W = max(max(len(r) for r in bot), max(len(r) for r in top) + 13) + 1
    H = 9 + 2 + 9 + 1
    canvas = [['.'] * W for _ in range(H)]
    def stamp(grid, x0, y0, col):
        for y, row in enumerate(grid):
            for x, c in enumerate(row):
                if c == '#':
                    canvas[y0 + y][x0 + x] = col
    tw = max(len(r) for r in top) + 13
    bw = max(len(r) for r in bot)
    tx = (W - 1 - tw) // 2
    bx = (W - 1 - bw) // 2
    # shadows first (red, one pixel right and down), then the yellow letters
    for grid, x0, y0 in ((top, tx, 0), (bot, bx, 11)):
        stamp(grid, x0 + 1, y0 + 1, 'r')
    for grid, x0, y0 in ((top, tx, 0), (bot, bx, 11)):
        stamp(grid, x0, y0, 'y')
    # the little 'N' between the words, in red, with a green glint
    nx = tx + max(len(r) for r in top) + 2
    for y, row in enumerate(SMALL_N):
        for x, c in enumerate(row):
            if c == '#':
                canvas[2 + y][nx + x] = 'r'
    return [''.join(r) for r in canvas]

def title_bytes():
    P, wins = gen_title()
    out = []
    for y in range(64):
        k, d = pack(''.join(P[y]))
        out += d
    return out, wins, P

def gen_title_asm():
    data, wins, P = title_bytes()
    # RLE: n<128: run of n copies of next byte; 128+n: n literals; 0 end
    rle = []
    i = 0
    while i < len(data):
        j = i
        while j < len(data) and data[j] == data[i] and j - i < 127: j += 1
        if j - i >= 3:
            rle += [j - i, data[i]]; i = j; continue
        k = i; lit = []
        while k < len(data) and len(lit) < 127:
            j = k
            while j < len(data) and data[j] == data[k] and j - k < 3: j += 1
            if j - k >= 3: break
            lit.append(data[k]); k += 1
        rle += [128 + len(lit)] + lit; i = k
    rle.append(0)
    L = ['; title backdrop, RLE packed (%d -> %d bytes)' % (len(data), len(rle)), 'TITLE_RLE:']
    L += db_lines(rle, 32)
    L.append('TITLE_WINS:   ; window byte offsets + pixel masks')
    for x, y in wins:
        L.append('    dw %d\n    db $%02X' % (y * 32 + x // 4, 3 << (6 - 2 * (x % 4))))
    L.append('    dw $FFFF')
    L.append('NWINS equ %d' % len(wins))
    # logo: pre-composed two-line masked sprite
    logo = gen_logo()
    W4 = ((len(logo[0]) + 3) // 4) * 4
    rows = [r + '.' * (W4 - len(r)) for r in logo]
    SPR = []
    for r in rows:
        k, d = pack(r)
        SPR += d               # data only; the mask is rebuilt at run time
    assert 'g' not in ''.join(rows)
    L.append('LOGO_W equ %d' % (W4 // 4))
    L.append('LOGO_H equ %d' % len(rows))
    L.append('LOGO_X equ %d' % (4 + (32 - W4 // 4) // 2))
    L.append('LOGO_DAT:')
    L += db_lines(SPR)
    open(os.path.join(OUT, 'title.asm'), 'w').write('\n'.join(L) + '\n')
    return P, rows

