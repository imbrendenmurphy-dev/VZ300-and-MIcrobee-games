STAGE1_SPRITES = ['zombie', 'skel', 'skull', 'bat', 'ghost', 'crow', 'plant', 'imp', 'moon', 'bskull', 'bjaw']
FRONT_SPRITES = ['zombie', 'skel', 'bat', 'ghost', 'crow', 'plant', 'imp']
NOP2 = ('bskull', 'bjaw', 'moon')
def _rsp():
    return [n for n in SPRITES if n not in STAGE1_SPRITES]
def sprite_lines(names, prefix):
    desc, data = [], []
    for name in names:
        for fi, f in enumerate(SPRITES[name]):
            w = len(f[0]); h = len(f)
            pw = (w + 3) // 4
            rows = [r + '.' * (pw * 4 - w) for r in f]
            p0 = []
            for r in rows:
                k, d = pack(r)
                for a, b in zip(k, d): p0 += [a, b]
            p2 = []
            for r in rows:
                k, d = pack('..' + r + '..')
                for a, b in zip(k, d): p2 += [a, b]
            lab = '%s%s_%d' % (prefix, name.upper(), fi)
            nop2 = name in NOP2
            desc.append('%s: db %d,%d\n    dw %s_P0,%s' % (lab, pw, h, lab, '0' if nop2 else lab + '_P2'))
            data.append('%s_P0:' % lab)
            data += db_lines(p0)
            if not nop2:
                data.append('%s_P2:' % lab)
                data += db_lines(p2)
    return desc + data

def tile_lines():
    L = []
    L.append('TILES:')
    for n in TILE_ORDER:
        bs = []
        for r in TILES[n]:
            k, d = pack(r)
            bs += d
        L.append('    db ' + hexrow(bs) + '   ; ' + n)
    L.append('TILES_END:')
    L.append('NTILES equ %d' % len(TILE_ORDER))
    L.append('TATTR:')
    attrs = [1 if n in SOLID else 2 if n in ONEWAY else 3 if n in HAZARD else 0 for n in TILE_ORDER]
    L += db_lines(attrs)
    for i, n in enumerate(TILE_ORDER):
        L.append('T_%s equ %d' % (n.upper(), i))
    return L

