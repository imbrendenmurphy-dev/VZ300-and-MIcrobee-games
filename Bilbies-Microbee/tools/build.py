"""BILBIES! for the Microbee Premium Plus: build everything into build/.

  python3 tools/build.py [--quick]

1. sprites + HUD (mkdata, mkhud)
2. the 24 levels and the title scene: world banks in colour and mono,
   packed (LZB, tools/lzbc.c) into level banks LEVn.BNK + src/levels.inc
3. the program (src/main.asm) and the CP/M loader (src/loader.asm)
4. the disk image BILBIES.DS8 (tools/build_disk.py)
"""
import os
import sys
import subprocess
HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
BUILD = os.path.join(ROOT, 'build')
SRC = os.path.join(ROOT, 'src')
sys.path.insert(0, HERE)
os.makedirs(BUILD, exist_ok=True)

import world
import mkdata
import mkhud
from orig_title import title_level

BLK_LEVEL = 12
WORLD_LEN = 0x7960          # what a level needs of the WORLD block (to the minimap)
MONO_LEN = 0x5A00           # mono: bitmap + colours + dug colours


def lzbc():
    exe = os.path.join(HERE, 'lzbc')
    src = os.path.join(HERE, 'lzbc.c')
    if not os.path.exists(exe) or os.path.getmtime(src) > os.path.getmtime(exe):
        subprocess.check_call(['gcc', '-O2', '-o', exe, src])
    return exe


def pack(data):
    tmp = os.path.join(BUILD, 'pk.raw')
    out = os.path.join(BUILD, 'pk.lzb')
    open(tmp, 'wb').write(data)
    subprocess.check_call([lzbc(), tmp, out])
    return open(out, 'rb').read()


def levels():
    lvs = list(world.levels.LEVELS) + [title_level()]
    banks = [bytearray()]
    index = []
    for i, lv in enumerate(lvs):
        col, _ = mkdata.world_bank(lv, mono=False)
        mono, _ = mkdata.world_bank(lv, mono=True)
        open(os.path.join(BUILD, 'W%02dC.BNK' % i), 'wb').write(col)
        open(os.path.join(BUILD, 'W%02dM.BNK' % i), 'wb').write(mono)
        ent = []
        for data in (col[:WORLD_LEN], mono[:MONO_LEN]):
            p = pack(data)
            if len(banks[-1]) + len(p) > 32768:
                banks.append(bytearray())
            ent.append((BLK_LEVEL + len(banks) - 1, len(banks[-1])))
            banks[-1] += p
        index.append(ent)
        print('  level', i, lv.name)
    for k, b in enumerate(banks):
        open(os.path.join(BUILD, 'LEV%d.BNK' % k), 'wb').write(bytes(b))
    lines = ['; generated by tools/build.py: packed levels (block, address) colour, mono',
             'NLEVELS\tequ %d' % len(world.levels.LEVELS), 'LV_TITLE\tequ %d' % len(world.levels.LEVELS),
             'NLEVBANKS\tequ %d' % len(banks), 'LEVTAB:']
    for (cb, ca), (mb, ma) in index:
        lines.append('\tdb %d\n\tdw $%04X\n\tdb %d\n\tdw $%04X' % (cb, ca, mb, ma))
    # level names, ratings and the demo list for the front end
    lines.append('LVNAMES:')
    for lv in lvs:
        lines.append('\tdb "%s",0' % lv.name)
    open(os.path.join(SRC, 'levels.inc'), 'w').write('\n'.join(lines) + '\n')
    tot = sum(len(b) for b in banks)
    print('levels: %d worlds packed into %d banks, %d bytes' % (len(lvs), len(banks), tot))
    return len(banks)


def loadfiles(nlev):
    names = [('STG_PROG', 'BILBIES', 'BIN'), ('BLK_GFX', 'GFX', 'BNK')]
    for i in range(8):
        if os.path.exists(os.path.join(BUILD, 'SPR%d.BNK' % i)):
            names.append(('BLK_SPR+%d' % i, 'SPR%d' % i, 'BNK'))
    for i in range(nlev):
        names.append(('BLK_LEVEL+%d' % i, 'LEV%d' % i, 'BNK'))
    lines = ['\tDB %s, "%-8s%s"' % (b, n, e) for b, n, e in names]
    open(os.path.join(SRC, 'loadfiles.inc'), 'w').write('\n'.join(lines) + '\n')
    return names


def assemble():
    zasm = os.path.join(HERE, 'zasm.py')
    subprocess.check_call([sys.executable, zasm, 'main.asm', '--sym=../build/main.sym'], cwd=SRC)
    subprocess.check_call([sys.executable, zasm, 'loader.asm', '--sym=../build/loader.sym'], cwd=SRC)


if __name__ == '__main__':
    import mkmusic
    mkmusic.write(os.path.join(SRC, 'musicdata.inc'))
    mkdata.sprites()
    mkhud.build()
    if '--quick' not in sys.argv or not os.path.exists(os.path.join(SRC, 'levels.inc')):
        nlev = levels()
    else:
        nlev = len([f for f in os.listdir(BUILD) if f.startswith('LEV') and f.endswith('.BNK')])
    loadfiles(nlev)
    assemble()
    import build_disk
    build_disk.main()
