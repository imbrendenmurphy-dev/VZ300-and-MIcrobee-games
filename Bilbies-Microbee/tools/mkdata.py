"""Build the game's data: level worlds (colour + mono), sprite banks and
their index (src/spridx.inc)."""
import os
import sys
import numpy as np
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import world
import bilby
from sprites import Frame, Packer

ROOT = os.path.dirname(HERE)
BUILD = os.path.join(ROOT, 'build')
os.makedirs(BUILD, exist_ok=True)

WBMP, WCOL, WDUG, WHDR, WMASK = 0x0000, 0x5000, 0x5500, 0x5A00, 0x6000
SKILLS8 = 8


def w16(v):
    return [v & 255, (v >> 8) & 255]


def header(lv, brick_ink, spr_ink):
    lv.check()
    b = bytearray(100)
    nm = lv.name.encode()[:23]
    b[0:len(nm)] = nm
    b[24:28] = bytes([lv.n, lv.rate, lv.save, lv.minutes])
    b[28:36] = bytes(lv.skills)
    b[36] = lv.width // 4
    b[37] = lv.height
    hx, hy = lv.hatch
    ex, ey = lv.exit
    b[38:41] = bytes(w16(hx) + [hy])
    b[41:44] = bytes(w16(ex) + [ey])
    b[44] = brick_ink
    if lv.water:
        wy, x0, x1 = lv.water
        b[45:50] = bytes([wy] + w16(x0) + w16(x1))
    b[50] = spr_ink
    b[51] = len(lv.steel)
    o = 52
    for x0, y0, x1, y1 in lv.steel:
        b[o:o + 6] = bytes(w16(x0) + [y0] + w16(x1) + [y1])
        o += 6
    assert o <= 100
    return b


def world_bank(lv, mono=False):
    img, solid, rep = world.paint_level(lv)
    bits, col, dug = world.compile_cells(img, solid, mono=mono, bgimg=rep['backdrop'])
    bank = bytearray(32768)
    # bitmap: column-major, byte column wc rows 0..159
    packed = np.packbits(bits, axis=1)          # 160 x 128
    bank[WBMP:WBMP + 20480] = packed.T.tobytes()
    bank[WCOL:WCOL + 1280] = col.tobytes()
    bank[WDUG:WDUG + 1280] = dug.tobytes()
    hdr = header(lv, world.WHT if mono else world.BRN, world.WHT if mono else world.YEL)
    bank[WHDR:WHDR + 100] = hdr
    m = np.packbits(rep['mask'], axis=1)        # 80 x 64
    bank[WMASK:WMASK + 5120] = m.tobytes()
    # minimap (the HUD's corner, the briefing's picture): 128 x 80, 16 x 5 cells
    mm = rep['mask'][:, :].reshape(80, 128, 4).any(2)        # 4 VZ pixels -> 1
    glyphs = bytearray()
    cols = bytearray()
    for r in range(5):
        for c in range(16):
            blk = mm[r * 16:(r + 1) * 16, c * 8:(c + 1) * 8]
            glyphs += bytes(int(''.join('1' if v else '0' for v in row), 2) for row in blk)
            cols.append((world.BLK << 4) | (world.LGR if mono else world.BRN))
    bank[0x7400:0x7400 + 1280] = glyphs
    bank[0x7400 + 1280:0x7400 + 1360] = cols
    sb = bytearray()
    for ev in lv.script:
        t, c, sk = ev[:3]
        if c == 'all':
            c = 255
        x0, x1 = (ev[3], ev[4]) if len(ev) > 3 else (0, 1023)
        sb += bytes([t & 255, t >> 8, c, world.lvlkit.SKILLS.index(sk), x0 & 255, x0 >> 8, x1 & 255, x1 >> 8])
    sb += b'\xFF'
    assert len(sb) <= 128
    bank[WHDR + 0x100:WHDR + 0x100 + len(sb)] = sb
    return bytes(bank), (bits, col)


def sprites():
    pk = Packer(first_bank=4, nbanks=8)
    seen = {}
    lines = ['; generated by tools/mkdata.py: sprite index (bank, shift table)', 'SPRIDX:']
    bases = {}
    order = []
    fid = 0
    for name, n, r, l in bilby.all_frames():
        bases[name] = fid
        for d, lst in enumerate((r, l)):
            for g in lst:
                k = tuple(g.rows())
                if k not in seen:
                    seen[k] = pk.add(Frame(g.rows(), bilby.AX, bilby.AY))
                order.append(seen[k])
                fid += 1
    # extras: cursor (cross, box), bomb digits 1-5, a spark
    def add_extra(rows, ax, ay, outline=True):
        nonlocal fid
        k = ('x',) + tuple(rows)
        if k not in seen:
            seen[k] = pk.add(Frame(rows, ax, ay, outline_on=outline, foot=False))
        order.append(seen[k])
        fid += 1
    bases['curs'] = fid
    cross = ['.......#.......'] * 5 + ['...............', '#####.....#####', '...............'] + ['.......#.......'] * 5
    box = ['####.......####', '#.............#', '#.............#', '#.............#'] + ['...............'] * 7 + ['#.............#', '#.............#', '#.............#', '####.......####']
    add_extra(cross, 0, 0)
    add_extra(box, 0, 0)
    bases['digit'] = fid
    D = {'1': ['.#.', '##.', '.#.', '.#.', '###'], '2': ['###', '..#', '###', '#..', '###'],
         '3': ['###', '..#', '.##', '..#', '###'], '4': ['#.#', '#.#', '###', '..#', '..#'],
         '5': ['###', '#..', '###', '..#', '###']}
    for d in '12345':
        rows = []
        for r in D[d]:
            big = ''.join(c * 2 for c in r)
            rows += [big, big]
        add_extra(rows, 0, 0)
    bases['spark'] = fid
    add_extra(['##', '##'], 0, 0, outline=False)
    for i in order:
        b, a = pk.index[i]
        lines.append('\tdb %d\n\tdw $%04X' % (b, a))
    for name, v in bases.items():
        lines.append('SF_%s\tequ %d' % (name.upper(), v))
    lines.append('SFTAB:\t; per state 1-15: first index entry, frames')
    for name, n, r, l in bilby.all_frames():
        lines.append('\tdw SPRIDX+%d*3\n\tdb %d' % (bases[name], n))
    lines.append('SPR_AX\tequ %d' % (bilby.AX + 1))
    lines.append('SPR_AY\tequ %d' % (bilby.AY + 1))
    open(os.path.join(ROOT, 'src', 'spridx.inc'), 'w').write('\n'.join(lines) + '\n')
    for i, bk in enumerate(pk.banks):
        if bk:
            open(os.path.join(BUILD, 'SPR%d.BNK' % i), 'wb').write(bytes(bk))
    print('sprites: %d frames, %d banks, %d bytes' % (fid, pk.cur + 1, sum(len(b) for b in pk.banks)))


if __name__ == '__main__':
    sprites()
    which = [int(a) for a in sys.argv[1:]] or [1]
    for i in which:
        lv = world.levels.LEVELS[i]
        for mono in (False, True):
            data, _ = world_bank(lv, mono)
            open(os.path.join(BUILD, 'W%02d%s.BNK' % (i, 'M' if mono else 'C')), 'wb').write(data)
    print('worlds:', which)
