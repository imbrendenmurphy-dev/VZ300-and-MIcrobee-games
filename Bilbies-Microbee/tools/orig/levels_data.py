def cave(l, top=8, bot=72, seed=1):
    """solid rock all round a big hall from row `top` to row `bot`"""
    l.rect('rock', 0, 0, 512, 80)
    l.rect('rock', 4, top, 504, bot - top, ERASE)
    return l

