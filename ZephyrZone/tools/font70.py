ORDER = ' ABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789!?-.:\''
def asm():
    s = ['; generated by tools/font70.py: 8 rows per glyph, bit 6 = left pixel', 'font70:']
    for ch in ORDER:
        s.append('            db %s   ; %r' % (','.join(str(int(r.replace('#', '1').replace('.', '0'), 2)) for r in G[ch]), ch))
    tab = []
    for c in range(32, 96):
        ch = chr(c); tab.append(ORDER.index(ch) if ch in ORDER else 0)
    s.append('font70map:  ; ASCII 32..95 -> glyph')
    for i in range(0, 64, 16): s.append('            db ' + ','.join(map(str, tab[i:i + 16])))
    return '\n'.join(s) + '\n'
def text_mask(text, sx=1, rows=None):
    """boolean pixel grid of text, 8 px per char (7 + gap), horizontal scale sx,
    rows: list of glyph-row indices to emit (to stretch vertically)"""
    rows = rows or list(range(8))
    W = len(text) * 8 * sx
    out = []
    for r in rows:
        line = []
        for ch in text:
            gl = G.get(ch, G[' '])[r] + '.'
            for c in gl:
                line += [c == '#'] * sx
        out.append(line)
    return out
def styled(mask, fill_top=1, fill_bot=3, split=None, outline=2, shadow=3):
    """colour a mask: fill (two-tone), 1-px outline, drop shadow; -1 = transparent"""
    h = len(mask); w = len(mask[0])
    H, Wd = h + 3, w + 3
    out = [[-1] * Wd for _ in range(H)]
    M = [[False] * Wd for _ in range(H)]
    for y in range(h):
        for x in range(w): M[y + 1][x + 1] = mask[y][x]
    split = h * 2 // 3 if split is None else split
    for y in range(H):
        for x in range(Wd):
            if M[y][x]: continue
            if y >= 2 and x >= 2 and M[y - 2][x - 1] and shadow is not None: out[y][x] = shadow
    for y in range(H):
        for x in range(Wd):
            if M[y][x]: continue
            if any(0 <= y + dy < H and 0 <= x + dx < Wd and M[y + dy][x + dx] for dy in (-1, 0, 1) for dx in (-1, 0, 1)):
                out[y][x] = outline
    for y in range(H):
        for x in range(Wd):
            if M[y][x]:
                yy = y - 1
                out[y][x] = fill_top if yy < split else (fill_bot if (yy + x) % 2 == 0 or yy >= split + 2 else fill_top)
    return out
def logo_lines():
    rows = [0, 0, 1, 2, 2, 3, 4, 4, 5, 6, 6, 7]   # 8 glyph rows stretched to 12
    a = styled(text_mask('ZEPHYR', 2, rows), split=7)
    b = styled(text_mask('ZONE', 2, rows), split=7)
    return a, b
