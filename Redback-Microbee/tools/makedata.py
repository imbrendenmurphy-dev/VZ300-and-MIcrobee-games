"""Build the data banks and include files for REDBACK:
build/PAIRS.BNK  (block 8: pair glyph records, sprites at 4000h)
build/DECK.BNK   (block 12: slot and ref columns)
build/data.inc   (constants)"""
import sys
from pathlib import Path
sys.path.insert(0, str(Path(__file__).resolve().parent))
import numpy as np
import deckart, deckpack, sprites
from deckpack import NPH, REC, AHEAD

ROOT = Path(__file__).resolve().parent.parent
B = ROOT / 'build'
B.mkdir(exist_ok=True)

SLOT_STRIDE, REF_STRIDE = 24, 48
REFS_AT = 0x1400


def main():
    c = deckart.build_deck()
    grid, order = deckart.cells_of(c)
    R, WC = grid.shape
    pairs, P, slot_of, blank, worst, OFF = deckpack.build(grid, order)
    # pair records: 80 phase bytes + colour
    bank = bytearray(0x8000)
    refs = {}
    off = 0
    for i, (key, glyphs, col) in enumerate(pairs):
        if i == blank:
            refs[i] = 0xFFFF
            continue
        assert off + REC <= 0x4000, 'pair data overflows 16K: %d pairs' % len(pairs)
        bank[off:off + 80] = glyphs
        bank[off + 80] = col
        refs[i] = off
        off += REC
    idx, sblocks, ids, frames = sprites.pack()
    bank[0x4000:0x4000 + len(idx)] = idx
    (B / 'PAIRS.BNK').write_bytes(bytes(bank[:0x4000 + len(idx)]))
    for i, blk in enumerate(sblocks):
        (B / ('SPR%d.BNK' % i)).write_bytes(blk)
    # columns
    ncols = WC + 2 * OFF
    deck = bytearray(0x4000)
    for j in range(-OFF, WC + OFF):
        jj = j + OFF
        for r in range(R):
            s = slot_of[(j, r)]
            deck[jj * SLOT_STRIDE + r] = s
            p = P[(j, r)]
            ref = refs[p] if s else 0xFFFF
            deck[REFS_AT + jj * REF_STRIDE + r * 2] = ref & 255
            deck[REFS_AT + jj * REF_STRIDE + r * 2 + 1] = ref >> 8
    assert REFS_AT + ncols * REF_STRIDE <= 0x4000
    (B / 'DECK.BNK').write_bytes(bytes(deck[:REFS_AT + ncols * REF_STRIDE]))
    inc = ['; generated by tools/makedata.py',
           'WC\t\tEQU %d' % WC, 'OFF\t\tEQU %d' % OFF, 'NCOLS\t\tEQU %d' % ncols,
           'SLOT_STRIDE\tEQU %d' % SLOT_STRIDE, 'REF_STRIDE\tEQU %d' % REF_STRIDE, 'REFS_AT\t\tEQU $%04X' % REFS_AT,
           'REC\t\tEQU %d' % REC, 'XMAX\t\tEQU %d' % ((WC - 40) * 8),
           'SPR_N\t\tEQU %d' % len(frames)]
    for name, i in ids.items():
        inc.append('F_%s\tEQU %d' % (name, i))
    (B / 'data.inc').write_text('\n'.join(inc) + '\n')
    print('pairs %d (%d bytes), max busy %d, sprites %d bytes in %d blocks, deck %d cols' % (len(pairs), off, worst, sum(len(b) for b in sblocks), len(sblocks), WC))
    # HUD font: 10-line glyphs, 16 bytes each, in the order of font.ORDER
    import font
    lines = []
    for ch in font.ORDER:
        g = [0] * 10
        for i, r in enumerate(font.F[ch]):
            b = 0
            for x, c in enumerate(r):
                if c == '#':
                    b |= 0xC0 >> (2 * x)
            g[2 + i] = b
        lines.append('\tDB ' + ','.join('$%02X' % v for v in g) + ',0,0,0,0,0,0')
    (B / 'font.inc').write_text('font_gl:\n' + '\n'.join(lines) + '\nN_FONT\tEQU %d\n' % len(font.ORDER))
    import math
    fm = []
    for a in range(32, 128):
        ch = chr(a)
        fm.append(0x80 + font.ORDER.index(ch) if ch in font.ORDER else 0x80)
    (B / 'font.inc').write_text((B / 'font.inc').read_text() + 'fmap:\n\tDB ' + ','.join('$%02X' % v for v in fm) + '\n')
    sn = [int(round(63 * math.sin(2 * math.pi * i / 256))) & 255 for i in range(256)]
    (B / 'sine.inc').write_text('sine:\n' + '\n'.join('\tDB ' + ','.join('$%02X' % v for v in sn[i:i + 16]) for i in range(0, 256, 16)) + '\n')
    # keep the expected picture for the emulator checks
    np.save(B / 'deck_grid.npy', grid)
    import pickle
    pickle.dump(order, open(B / 'deck_order.pkl', 'wb'))


if __name__ == '__main__':
    main()
