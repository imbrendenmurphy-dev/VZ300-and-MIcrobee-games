# ---- effects: (frequency | 'N<density 0-15>' | 0, frames) ... 0,0
def sfx(name, steps):
    v = []
    for f, t in steps:
        if isinstance(f, str):
            v += [0xF0 | int(f[1:]), t]
        else:
            v += [0 if f == 0 else per(f), t]
    v += [0, 0]
    emit(name, v)


