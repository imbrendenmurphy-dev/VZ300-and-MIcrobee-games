"""SPINDRIFT's music and effects -> src/snd.inc

The beeper loop (src/sound.asm) toggles a voice every 'pitch' passes of a
62 T loop, so a pitch is round(3375000 / (2 * 62 * f)). All the music is
original. A frame is 1/25 s.
"""
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
LOOP_T = 62
NAMES = ['A', 'A#', 'B', 'C', 'C#', 'D', 'D#', 'E', 'F', 'F#', 'G', 'G#']
BASE = 110.0                    # A2: note index 1


def freq_of(name):
    n, o = name[:-1], int(name[-1])
    semis = {'C': -9, 'C#': -8, 'D': -7, 'D#': -6, 'E': -5, 'F': -4, 'F#': -3, 'G': -2, 'G#': -1,
             'A': 0, 'A#': 1, 'B': 2}[n] + (o - 4) * 12
    return 440.0 * 2 ** (semis / 12.0)


def per(f):
    return max(1, min(255, int(round(3375000 / (2.0 * LOOP_T * f)))))


def idx(name):
    """note index: 1 = A2"""
    return int(round(12 * __import__('math').log2(freq_of(name) / BASE))) + 1


NOTES = 52


def notetab():
    return [per(BASE * 2 ** (i / 12.0)) for i in range(NOTES)]


def chan(seq, unit):
    out = []
    for n, d in seq:
        out += [0 if n == 'R' else idx(n), d * unit]
    return out


L = ['; generated by tools/mkmusic.py - do not edit', 'notetab:']
nt = notetab()
for i in range(0, NOTES, 13):
    L.append('\tdb ' + ','.join(str(v) for v in nt[i:i + 13]))


def emit(name, data):
    L.append('%s:' % name)
    for i in range(0, len(data), 16):
        L.append('\tdb ' + ','.join(str(v & 255) for v in data[i:i + 16]))


def tune(name, mel, bass, unit, gate, loop=True, check=None):
    a, b = chan(mel, unit), chan(bass, unit)
    la = sum(d for _, d in mel)
    lb = sum(d for _, d in bass)
    if check:
        assert la == lb == check, (name, la, lb, check)
    end = [0xFE] if loop else [0xFF]
    L.append('%s:\tdw %s_m,%s_b\n\tdb %d' % (name, name, name, gate))
    emit(name + '_m', a + end)
    emit(name + '_b', b + end)


def bar(*notes):
    return list(notes)


