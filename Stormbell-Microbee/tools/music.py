"""STORMBELL sound tables -> src/snd.inc

Effects are lists of per-tick bursts; tunes are slow, spaced blips in a
minor pentatonic, as the beeper likes them. Loop timing (src/sound.asm):
a half cycle takes 26 T-states a count plus about 60.
"""
CLK = 3375000.0
NAMES = {'C': 0, 'C#': 1, 'D': 2, 'D#': 3, 'E': 4, 'F': 5, 'F#': 6, 'G': 7, 'G#': 8, 'A': 9, 'A#': 10, 'B': 11}


def hp(f):
    return max(2, int(round((CLK / (2 * f) - 60) / 26)))


def cycles(f, ms):
    return max(2, min(255, int(round(2 * f * ms / 1000.0))))


def freq(name):
    n, o = name[:-1], int(name[-1])
    return 440.0 * 2 ** ((NAMES[n] + 12 * (o - 4) - 9) / 12.0)


NOTES = ['A2', 'C3', 'D3', 'E3', 'G3', 'A3', 'C4', 'D4', 'E4', 'G4', 'A4', 'C5', 'D5', 'E5', 'G5', 'A5']


def tone(f, ms):
    return (hp(f), cycles(f, ms), 0)


def noise(mask, n):
    return (mask, n, 1)


def sweep(f0, f1, n, ms):
    out = []
    for i in range(n):
        f = f0 * (f1 / f0) ** (i / max(1, n - 1))
        out.append(tone(f, ms))
    return out


SFX = [
    ('STEP', [noise(14, 18)]),
    ('PUNCH', [noise(6, 40), noise(10, 24)]),
    ('KICK', [noise(10, 30), noise(14, 40), noise(18, 24)]),
    ('HIT', [tone(160, 9), tone(120, 7), noise(30, 30)]),
    ('HITK', [tone(140, 11), tone(100, 9), tone(80, 6), noise(40, 30)]),
    ('BLOCK', [tone(1900, 4), tone(1400, 3), noise(4, 20)]),
    ('FALL', sweep(500, 140, 8, 5)),
    ('THUD', [tone(70, 14), noise(60, 30), tone(55, 8)]),
    ('GONG', [tone(f, ms) for k in range(16) for f, ms in (((196.0, 9 - k * 0.45),) if k % 2 == 0 else ((541.0, 6 - k * 0.3),))]),
    ('BELL', [tone(f, ms) for k in range(8) for f, ms in (((784.0, 6 - k * 0.5),) if k % 2 == 0 else ((2163.0, 3 - k * 0.25),))]),
]

# tunes: (note or '.', ticks)
def tune(s):
    out = []
    for tok in s.split():
        n, t = tok.split(':')
        out.append((0 if n == '.' else NOTES.index(n) + 1, int(t)))
    return out


TUNES = {
    'title': tune("A3:8 C4:4 D4:4 E4:12 .:4 G4:6 E4:6 D4:12 .:8 "
                  "C4:6 D4:6 E4:6 A3:14 .:6 G3:6 A3:6 C4:6 D4:18 .:10 "
                  "A3:8 C4:4 D4:4 E4:12 .:4 A4:8 G4:4 E4:4 D4:12 .:6 "
                  "E4:6 D4:6 C4:6 A3:24 .:20"),
    'fight': tune("A2:10 .:6 A2:4 C3:4 D3:10 .:10 A2:10 .:6 A2:4 C3:4 E3:10 .:14 "
                  "D3:10 .:6 D3:4 E3:4 G3:10 .:10 E3:8 D3:8 C3:8 A2:10 .:18"),
    'boss': tune("A2:6 A2:6 .:4 C3:6 A2:6 .:10 A2:6 A2:6 .:4 D3:6 C3:6 .:10 "
                 "E3:6 E3:6 .:4 G3:6 E3:6 .:6 D3:4 C3:4 A2:12 .:16"),
    'win': tune("A3:4 C4:4 E4:4 A4:12 .:6 G4:4 A4:16 .:200"),
    'lose': tune("E4:8 D4:8 C4:8 A3:20 .:250"),
    'end': tune("A3:6 C4:6 E4:6 G4:6 A4:12 .:6 E4:6 G4:6 A4:6 C5:6 D5:12 .:6 "
                "E5:8 D5:8 C5:8 A4:16 .:10 G4:6 A4:6 C5:6 A4:20 .:30"),
}


def build(out):
    L = ['; generated by tools/music.py']
    for i, (n, steps) in enumerate(SFX):
        L.append('SFX_%s equ %d' % (n, i))
    L.append('sfxtab:')
    L.append('\tdw ' + ','.join('sx_' + n.lower() for n, s in SFX))
    for n, steps in SFX:
        L.append('sx_%s:' % n.lower())
        for h, c, nz in steps:
            L.append('\tdw %d\n\tdb %d,%d' % (h, c, nz))
        L.append('\tdw 0')
    L.append('; notes: dw half period, db half cycles of the blip, of its tail')
    L.append('notetab:')
    for nm in NOTES:
        f = freq(nm)
        L.append('\tdw %d\n\tdb %d,%d\t; %s' % (hp(f), cycles(f, 6), cycles(f, 2), nm))
    for name, t in TUNES.items():
        L.append('tune_%s:' % name)
        L.append('\tdb ' + ','.join('%d,%d' % nt for nt in t) + ',$FF')
    open(out, 'w').write('\n'.join(L) + '\n')
